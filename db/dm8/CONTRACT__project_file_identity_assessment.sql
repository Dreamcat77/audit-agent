-- DEPENDS-ON: project-file-parse-result,project-file-role-assessment,contract-candidate-authority
-- PURPOSE: durable file-to-project identity assessment and human resolution
-- EXECUTION: CONTROLLED_MANUAL
-- IDEMPOTENCY: NOT_ASSUMED

-- PROJECT_VERSION_NO is historical input provenance, not a FK to mutable PROJECT.VERSION_NO.
-- A Project metadata update must not be blocked by earlier immutable assessments/decisions.
ALTER TABLE PROJECT_EXTRACTION_RESULT ADD
    CONSTRAINT UK_PROJECT_EXTRACTION_ID_PARSE_OWNER
    UNIQUE (ID, PROJECT_ID, SOURCE_FILE_ID, PARSE_RESULT_ID);

CREATE TABLE PROJECT_FILE_IDENTITY_ASSESSMENT (
    ASSESSMENT_ID VARCHAR(36) NOT NULL,
    PROJECT_ID VARCHAR(36) NOT NULL,
    PROJECT_VERSION_NO BIGINT NOT NULL,
    FILE_ID VARCHAR(36) NOT NULL,
    FILE_SHA256 VARCHAR(64) NOT NULL,
    PARSE_RESULT_ID VARCHAR(36) NOT NULL,
    PARSE_VERSION INTEGER NOT NULL,
    ASSESSMENT_SOURCE VARCHAR(32) NOT NULL,
    ASSESSMENT_VERSION VARCHAR(100) NOT NULL,
    IDENTITY_POLICY_VERSION VARCHAR(100) NOT NULL,
    STATUS VARCHAR(32) NOT NULL,
    NORMALIZED_INPUT_FINGERPRINT VARCHAR(64) NOT NULL,
    SAFE_REASON_CODE VARCHAR(100),
    CREATED_AT TIMESTAMP NOT NULL,
    COMPLETED_AT TIMESTAMP NOT NULL,
    VERSION_NO BIGINT DEFAULT 0 NOT NULL,
    CONSTRAINT PK_PROJECT_FILE_IDENTITY_ASSESSMENT PRIMARY KEY (ASSESSMENT_ID),
    CONSTRAINT UK_PROJECT_FILE_IDENTITY_ASSESSMENT_BINDING UNIQUE
        (ASSESSMENT_ID, PROJECT_ID, PROJECT_VERSION_NO, FILE_ID, FILE_SHA256, PARSE_RESULT_ID, PARSE_VERSION),
    CONSTRAINT FK_PROJECT_FILE_IDENTITY_ASSESSMENT_PROJECT FOREIGN KEY (PROJECT_ID)
        REFERENCES PROJECT (ID),
    CONSTRAINT FK_PROJECT_FILE_IDENTITY_ASSESSMENT_FILE FOREIGN KEY (PROJECT_ID, FILE_ID)
        REFERENCES PROJECT_FILE (PROJECT_ID, ID),
    CONSTRAINT FK_PROJECT_FILE_IDENTITY_ASSESSMENT_PARSE FOREIGN KEY
        (PARSE_RESULT_ID, PROJECT_ID, FILE_ID, FILE_SHA256, PARSE_VERSION)
        REFERENCES PROJECT_FILE_PARSE_RESULT
        (PARSE_RESULT_ID, PROJECT_ID, FILE_ID, FILE_SHA256, PARSE_VERSION),
    CONSTRAINT CK_PROJECT_FILE_IDENTITY_ASSESSMENT_STATUS CHECK
        (STATUS IN ('LIKELY_SAME_PROJECT', 'CONFLICT', 'INSUFFICIENT', 'SAME_PROJECT')),
    CONSTRAINT CK_PROJECT_FILE_IDENTITY_ASSESSMENT_SOURCE CHECK (ASSESSMENT_SOURCE = 'DETERMINISTIC'),
    CONSTRAINT CK_PROJECT_FILE_IDENTITY_ASSESSMENT_VERSIONS CHECK
        (PROJECT_VERSION_NO >= 0 AND PARSE_VERSION > 0 AND VERSION_NO >= 0),
    CONSTRAINT CK_PROJECT_FILE_IDENTITY_ASSESSMENT_HASHES CHECK
        (LENGTH(FILE_SHA256) = 64 AND LENGTH(NORMALIZED_INPUT_FINGERPRINT) = 64),
    CONSTRAINT CK_PROJECT_FILE_IDENTITY_ASSESSMENT_TIME CHECK (COMPLETED_AT >= CREATED_AT)
);

CREATE TABLE PROJECT_FILE_IDENTITY_EVIDENCE (
    EVIDENCE_ID VARCHAR(36) NOT NULL,
    ASSESSMENT_ID VARCHAR(36) NOT NULL,
    PROJECT_ID VARCHAR(36) NOT NULL,
    PROJECT_VERSION_NO BIGINT NOT NULL,
    FILE_ID VARCHAR(36) NOT NULL,
    FILE_SHA256 VARCHAR(64) NOT NULL,
    PARSE_RESULT_ID VARCHAR(36) NOT NULL,
    PARSE_VERSION INTEGER NOT NULL,
    FACT_TYPE VARCHAR(40) NOT NULL,
    EXTRACTION_RESULT_ID VARCHAR(36),
    LEFT_SOURCE VARCHAR(40) NOT NULL,
    RIGHT_SOURCE VARCHAR(40) NOT NULL,
    LEFT_NORMALIZED_HASH VARCHAR(64),
    RIGHT_NORMALIZED_HASH VARCHAR(64),
    LEFT_BOUNDED_VALUE VARCHAR(160),
    RIGHT_BOUNDED_VALUE VARCHAR(160),
    COMPARISON_OUTCOME VARCHAR(32) NOT NULL,
    SIGNIFICANCE_CODE VARCHAR(40) NOT NULL,
    SOURCE_LOCATOR VARCHAR(500),
    CREATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT PK_PROJECT_FILE_IDENTITY_EVIDENCE PRIMARY KEY (EVIDENCE_ID),
    CONSTRAINT FK_PROJECT_FILE_IDENTITY_EVIDENCE_ASSESSMENT FOREIGN KEY
        (ASSESSMENT_ID, PROJECT_ID, PROJECT_VERSION_NO, FILE_ID, FILE_SHA256, PARSE_RESULT_ID, PARSE_VERSION)
        REFERENCES PROJECT_FILE_IDENTITY_ASSESSMENT
        (ASSESSMENT_ID, PROJECT_ID, PROJECT_VERSION_NO, FILE_ID, FILE_SHA256, PARSE_RESULT_ID, PARSE_VERSION),
    CONSTRAINT FK_PROJECT_FILE_IDENTITY_EVIDENCE_EXTRACTION FOREIGN KEY
        (EXTRACTION_RESULT_ID, PROJECT_ID, FILE_ID, PARSE_RESULT_ID)
        REFERENCES PROJECT_EXTRACTION_RESULT (ID, PROJECT_ID, SOURCE_FILE_ID, PARSE_RESULT_ID),
    CONSTRAINT CK_PROJECT_FILE_IDENTITY_EVIDENCE_FACT CHECK
        (FACT_TYPE IN ('PROJECT_NO', 'PROJECT_NAME')),
    CONSTRAINT CK_PROJECT_FILE_IDENTITY_EVIDENCE_OUTCOME CHECK
        (COMPARISON_OUTCOME IN ('MATCH', 'MISMATCH', 'MISSING_FILE_VALUE', 'MISSING_PROJECT_VALUE')),
    CONSTRAINT CK_PROJECT_FILE_IDENTITY_EVIDENCE_VERSIONS CHECK
        (PROJECT_VERSION_NO >= 0 AND PARSE_VERSION > 0),
    CONSTRAINT CK_PROJECT_FILE_IDENTITY_EVIDENCE_BOUNDS CHECK
        ((LEFT_BOUNDED_VALUE IS NULL OR LENGTH(LEFT_BOUNDED_VALUE) <= 160)
            AND (RIGHT_BOUNDED_VALUE IS NULL OR LENGTH(RIGHT_BOUNDED_VALUE) <= 160)
            AND (SOURCE_LOCATOR IS NULL OR LENGTH(SOURCE_LOCATOR) <= 500))
);

CREATE TABLE PROJECT_FILE_IDENTITY_DECISION (
    DECISION_ID VARCHAR(36) NOT NULL,
    PROJECT_ID VARCHAR(36) NOT NULL,
    PROJECT_VERSION_NO BIGINT NOT NULL,
    FILE_ID VARCHAR(36) NOT NULL,
    FILE_SHA256 VARCHAR(64) NOT NULL,
    PARSE_RESULT_ID VARCHAR(36) NOT NULL,
    PARSE_VERSION INTEGER NOT NULL,
    ASSESSMENT_ID VARCHAR(36) NOT NULL,
    RESOLUTION VARCHAR(40) NOT NULL,
    DECIDED_BY VARCHAR(36) NOT NULL,
    DECIDED_AT TIMESTAMP NOT NULL,
    SUPERSEDES_DECISION_ID VARCHAR(36),
    REASON VARCHAR(500),
    VERSION_NO BIGINT NOT NULL,
    CONSTRAINT PK_PROJECT_FILE_IDENTITY_DECISION PRIMARY KEY (DECISION_ID),
    CONSTRAINT UK_PROJECT_FILE_IDENTITY_DECISION_VERSION UNIQUE (FILE_ID, VERSION_NO),
    CONSTRAINT UK_PROJECT_FILE_IDENTITY_DECISION_OWNERSHIP UNIQUE
        (DECISION_ID, PROJECT_ID, FILE_ID),
    CONSTRAINT UK_PROJECT_FILE_IDENTITY_DECISION_PARSE_BINDING UNIQUE
        (DECISION_ID, PROJECT_ID, FILE_ID, PARSE_RESULT_ID),
    CONSTRAINT FK_PROJECT_FILE_IDENTITY_DECISION_ASSESSMENT FOREIGN KEY
        (ASSESSMENT_ID, PROJECT_ID, PROJECT_VERSION_NO, FILE_ID, FILE_SHA256, PARSE_RESULT_ID, PARSE_VERSION)
        REFERENCES PROJECT_FILE_IDENTITY_ASSESSMENT
        (ASSESSMENT_ID, PROJECT_ID, PROJECT_VERSION_NO, FILE_ID, FILE_SHA256, PARSE_RESULT_ID, PARSE_VERSION),
    CONSTRAINT FK_PROJECT_FILE_IDENTITY_DECISION_DECIDED_BY FOREIGN KEY (DECIDED_BY)
        REFERENCES SYS_USER (ID),
    CONSTRAINT FK_PROJECT_FILE_IDENTITY_DECISION_SUPERSEDES FOREIGN KEY
        (SUPERSEDES_DECISION_ID, PROJECT_ID, FILE_ID)
        REFERENCES PROJECT_FILE_IDENTITY_DECISION (DECISION_ID, PROJECT_ID, FILE_ID),
    CONSTRAINT CK_PROJECT_FILE_IDENTITY_DECISION_RESOLUTION CHECK
        (RESOLUTION IN ('CONFIRM_SAME_PROJECT', 'CONFIRM_NOT_SAME_PROJECT')),
    CONSTRAINT CK_PROJECT_FILE_IDENTITY_DECISION_VERSIONS CHECK
        (PROJECT_VERSION_NO > 0 AND PARSE_VERSION > 0 AND VERSION_NO > 0),
    CONSTRAINT CK_PROJECT_FILE_IDENTITY_DECISION_SHA CHECK (LENGTH(FILE_SHA256) = 64),
    CONSTRAINT CK_PROJECT_FILE_IDENTITY_DECISION_SUPERSEDES CHECK
        (SUPERSEDES_DECISION_ID IS NULL OR SUPERSEDES_DECISION_ID <> DECISION_ID)
);

ALTER TABLE CONTRACT_CANDIDATE ADD SOURCE_IDENTITY_DECISION_ID VARCHAR(36);
ALTER TABLE CONTRACT_CANDIDATE ADD
    CONSTRAINT FK_CONTRACT_CANDIDATE_SOURCE_IDENTITY_DECISION FOREIGN KEY
        (SOURCE_IDENTITY_DECISION_ID, PROJECT_ID, SOURCE_CONTRACT_FILE_ID, SOURCE_PARSE_RESULT_ID)
        REFERENCES PROJECT_FILE_IDENTITY_DECISION (DECISION_ID, PROJECT_ID, FILE_ID, PARSE_RESULT_ID);
ALTER TABLE CONTRACT_CANDIDATE ADD
    CONSTRAINT CK_CONTRACT_CANDIDATE_SOURCE_IDENTITY_TUPLE CHECK
        (SOURCE_IDENTITY_DECISION_ID IS NULL OR
            (SOURCE_PARSE_RESULT_ID IS NOT NULL AND SOURCE_ROLE_DECISION_ID IS NOT NULL
                AND SOURCE_AUTHORITY_SOURCE = 'HUMAN_CONFIRMATION'));

CREATE INDEX IDX_PROJECT_FILE_IDENTITY_ASSESSMENT_FILE
    ON PROJECT_FILE_IDENTITY_ASSESSMENT (FILE_ID, PROJECT_VERSION_NO, CREATED_AT DESC);
CREATE INDEX IDX_PROJECT_FILE_IDENTITY_EVIDENCE_ASSESSMENT
    ON PROJECT_FILE_IDENTITY_EVIDENCE (ASSESSMENT_ID, FACT_TYPE, EVIDENCE_ID);
CREATE INDEX IDX_PROJECT_FILE_IDENTITY_DECISION_FILE
    ON PROJECT_FILE_IDENTITY_DECISION (FILE_ID, VERSION_NO DESC, DECISION_ID DESC);
CREATE INDEX IDX_CONTRACT_CANDIDATE_SOURCE_IDENTITY_DECISION
    ON CONTRACT_CANDIDATE (SOURCE_IDENTITY_DECISION_ID, PROJECT_ID, SOURCE_CONTRACT_FILE_ID);
