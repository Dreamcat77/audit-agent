-- MIGRATION-NAMESPACE: CONTRACT
-- MIGRATION-ID: contract-final-closeout-typed-clause
-- DEPENDS-ON: review-run-results
-- PURPOSE: durable BREACH/TERM v2 bilateral values bound to frozen finding evidence
-- EXECUTION: CONTROLLED_MANUAL
-- IDEMPOTENCY: NOT_ASSUMED

CREATE TABLE CONTRACT_REVIEW_CLAUSE_COMPARISON (
    COMPARISON_ID VARCHAR(36) NOT NULL,
    FINDING_ID VARCHAR(36) NOT NULL,
    RUN_ID VARCHAR(36) NOT NULL,
    STEP_ID VARCHAR(36) NOT NULL,
    ATTEMPT_ID VARCHAR(36) NOT NULL,
    COMPARISON_KEY VARCHAR(200) NOT NULL,
    KIND VARCHAR(32) NOT NULL,
    RESULT VARCHAR(32) NOT NULL,
    SCHEMA_VERSION INT NOT NULL,
    CONSTRAINT PK_CONTRACT_REVIEW_CLAUSE_COMPARISON PRIMARY KEY (COMPARISON_ID),
    CONSTRAINT UK_CONTRACT_REVIEW_CLAUSE_RUN UNIQUE (COMPARISON_ID, RUN_ID),
    CONSTRAINT UK_CONTRACT_REVIEW_CLAUSE_FINDING UNIQUE (FINDING_ID),
    CONSTRAINT UK_CONTRACT_REVIEW_CLAUSE_KEY UNIQUE (ATTEMPT_ID, COMPARISON_KEY),
    CONSTRAINT FK_CONTRACT_REVIEW_CLAUSE_FINDING FOREIGN KEY
        (FINDING_ID, RUN_ID, STEP_ID, ATTEMPT_ID)
        REFERENCES CONTRACT_REVIEW_FINDING (FINDING_ID, RUN_ID, STEP_ID, ATTEMPT_ID),
    CONSTRAINT CK_CONTRACT_REVIEW_CLAUSE_KIND CHECK (KIND IN ('BREACH','TERM')),
    CONSTRAINT CK_CONTRACT_REVIEW_CLAUSE_RESULT CHECK (RESULT IN ('MATCH','DIFFERENT','NOT_EVALUATED','CONFLICT')),
    CONSTRAINT CK_CONTRACT_REVIEW_CLAUSE_SCHEMA CHECK (SCHEMA_VERSION=2)
);

CREATE INDEX IX_CONTRACT_REVIEW_CLAUSE_RUN
    ON CONTRACT_REVIEW_CLAUSE_COMPARISON (RUN_ID, STEP_ID, ATTEMPT_ID);

CREATE TABLE CONTRACT_REVIEW_CLAUSE_VALUE (
    VALUE_ID VARCHAR(36) NOT NULL,
    COMPARISON_ID VARCHAR(36) NOT NULL,
    RUN_ID VARCHAR(36) NOT NULL,
    SIDE_KEY VARCHAR(140) NOT NULL,
    SOURCE_FILE_ID VARCHAR(36) NOT NULL,
    STATE VARCHAR(32) NOT NULL,
    SCENARIO_KEY VARCHAR(200) NOT NULL,
    RESPONSIBLE_PARTY VARCHAR(200),
    CALCULATION_BASIS VARCHAR(200),
    RATE_VALUE DECIMAL(18,6),
    RATE_UNIT VARCHAR(64),
    FREQUENCY VARCHAR(64),
    PERIOD_VALUE VARCHAR(100),
    CAP_RATE DECIMAL(18,6),
    CAP_AMOUNT DECIMAL(18,6),
    TERMINATION_THRESHOLD VARCHAR(500),
    DATE_TYPE VARCHAR(100),
    NORMALIZED_DATE VARCHAR(100),
    TERM_START VARCHAR(100),
    DURATION_VALUE VARCHAR(200),
    EFFECTIVE_CONDITION VARCHAR(1000),
    TERMINATION_CONDITION VARCHAR(1000),
    CONSTRAINT PK_CONTRACT_REVIEW_CLAUSE_VALUE PRIMARY KEY (VALUE_ID),
    CONSTRAINT UK_CONTRACT_REVIEW_CLAUSE_SIDE UNIQUE (COMPARISON_ID, SIDE_KEY),
    CONSTRAINT FK_CONTRACT_REVIEW_CLAUSE_VALUE FOREIGN KEY (COMPARISON_ID, RUN_ID)
        REFERENCES CONTRACT_REVIEW_CLAUSE_COMPARISON (COMPARISON_ID, RUN_ID),
    CONSTRAINT FK_CONTRACT_REVIEW_CLAUSE_VALUE_MATERIAL FOREIGN KEY (RUN_ID, SOURCE_FILE_ID)
        REFERENCES CONTRACT_REVIEW_RUN_MATERIAL (RUN_ID, FILE_ID),
    CONSTRAINT CK_CONTRACT_REVIEW_CLAUSE_STATE CHECK (STATE IN ('KNOWN','NOT_EXTRACTED','NOT_APPLICABLE','CONFLICT'))
);

CREATE TABLE CONTRACT_REVIEW_CLAUSE_VALUE_EVIDENCE (
    VALUE_ID VARCHAR(36) NOT NULL,
    EVIDENCE_ID VARCHAR(36) NOT NULL,
    CONSTRAINT PK_CONTRACT_REVIEW_CLAUSE_VALUE_EVIDENCE PRIMARY KEY (VALUE_ID, EVIDENCE_ID),
    CONSTRAINT UK_CONTRACT_REVIEW_CLAUSE_EVIDENCE UNIQUE (EVIDENCE_ID),
    CONSTRAINT FK_CONTRACT_REVIEW_CLAUSE_VALUE_ID FOREIGN KEY (VALUE_ID)
        REFERENCES CONTRACT_REVIEW_CLAUSE_VALUE (VALUE_ID),
    CONSTRAINT FK_CONTRACT_REVIEW_CLAUSE_EVIDENCE_ID FOREIGN KEY (EVIDENCE_ID)
        REFERENCES CONTRACT_REVIEW_EVIDENCE (EVIDENCE_ID)
);
