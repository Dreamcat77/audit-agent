CREATE TABLE BUDGET_SPLIT_RISK_RULE (
    RULE_CODE                  VARCHAR(64)    NOT NULL PRIMARY KEY,
    RULE_NAME                  VARCHAR(200)   NOT NULL,
    WINDOW_DAYS                INT            NOT NULL,
    INDIVIDUAL_AMOUNT_LIMIT    DECIMAL(18,2)  NOT NULL,
    AGGREGATE_AMOUNT_THRESHOLD DECIMAL(18,2)  NOT NULL,
    MINIMUM_RECORD_COUNT       INT            NOT NULL,
    WARNING_SCORE              INT            NOT NULL,
    CRITICAL_SCORE             INT            NOT NULL,
    VERSION_NO                 INT            NOT NULL,
    STATUS                     VARCHAR(16)     NOT NULL DEFAULT 'ACTIVE',
    CREATED_TIME               TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_TIME               TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE BUDGET_SPLIT_RISK_RULE IS 'F05 项目拆分风险评分配置';
COMMENT ON COLUMN BUDGET_SPLIT_RISK_RULE.INDIVIDUAL_AMOUNT_LIMIT IS '单条记录必须严格小于该审批阈值';
COMMENT ON COLUMN BUDGET_SPLIT_RISK_RULE.AGGREGATE_AMOUNT_THRESHOLD IS '窗口内合计金额触发阈值';

CREATE INDEX IDX_BUDGET_SPLIT_RULE_STATUS
    ON BUDGET_SPLIT_RISK_RULE (STATUS, AGGREGATE_AMOUNT_THRESHOLD);

CREATE TABLE BUDGET_SPLIT_RISK_ASSESSMENT (
    ID                       VARCHAR(36)    NOT NULL PRIMARY KEY,
    PROCUREMENT_IDS_JSON     CLOB           NOT NULL,
    TOTAL_AMOUNT             DECIMAL(18,2)  NOT NULL,
    RISK_LEVEL               VARCHAR(16)    NOT NULL,
    RISK_SCORE               INT            NOT NULL,
    SPLIT_RATIO              DECIMAL(5,2)   NOT NULL,
    TIME_CONCENTRATION       DECIMAL(5,2)   NOT NULL,
    SUPPLIER_CONCENTRATION   DECIMAL(5,2)   NOT NULL,
    RECORDS_JSON             CLOB           NOT NULL,
    CREATED_BY               VARCHAR(64)    NOT NULL,
    CREATED_AT               TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE BUDGET_SPLIT_RISK_ASSESSMENT IS 'F05 项目拆分风险评估事实';
COMMENT ON COLUMN BUDGET_SPLIT_RISK_ASSESSMENT.RECORDS_JSON IS '触发规则、金额窗口和采购记录的不可变快照';

CREATE INDEX IDX_BUDGET_SPLIT_ASSESSMENT_TIME
    ON BUDGET_SPLIT_RISK_ASSESSMENT (CREATED_AT, RISK_LEVEL);

