-- V025: 采购需求审批流程事实表。
-- DM8 是审批状态、节点状态和操作历史的唯一事实源；local profile 使用内存适配器。

CREATE TABLE PROCUREMENT_APPROVAL_INSTANCE (
    ID                  VARCHAR(36)  NOT NULL PRIMARY KEY,
    PROJECT_ID          VARCHAR(36)  NOT NULL,
    STATUS              VARCHAR(32)  NOT NULL,
    CURRENT_NODE_CODE   VARCHAR(64),
    STARTED_BY_USER_ID  VARCHAR(64)  NOT NULL,
    STARTED_BY_NAME     VARCHAR(100) NOT NULL,
    STARTED_TIME        TIMESTAMP    NOT NULL,
    COMPLETED_TIME      TIMESTAMP,
    CREATED_TIME        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_TIME        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT UK_PROC_APPROVAL_INSTANCE_PROJECT UNIQUE (PROJECT_ID),
    CONSTRAINT CK_PROC_APPROVAL_INSTANCE_STATUS CHECK (
        STATUS IN ('IN_PROGRESS', 'APPROVED', 'RETURNED')
    ),
    CONSTRAINT FK_PROC_APPROVAL_INSTANCE_PROJECT FOREIGN KEY (PROJECT_ID)
        REFERENCES PROCUREMENT_DEMAND (ID)
);

COMMENT ON TABLE PROCUREMENT_APPROVAL_INSTANCE IS '采购需求审批流程实例表';
COMMENT ON COLUMN PROCUREMENT_APPROVAL_INSTANCE.PROJECT_ID IS '采购需求ID';
COMMENT ON COLUMN PROCUREMENT_APPROVAL_INSTANCE.STATUS IS '流程状态：IN_PROGRESS/APPROVED/RETURNED';
COMMENT ON COLUMN PROCUREMENT_APPROVAL_INSTANCE.CURRENT_NODE_CODE IS '当前审批节点编码';
COMMENT ON COLUMN PROCUREMENT_APPROVAL_INSTANCE.STARTED_BY_USER_ID IS '发起人用户ID';
COMMENT ON COLUMN PROCUREMENT_APPROVAL_INSTANCE.STARTED_BY_NAME IS '发起人名称';

CREATE INDEX IDX_PROC_APPROVAL_INSTANCE_STATUS
    ON PROCUREMENT_APPROVAL_INSTANCE (STATUS, UPDATED_TIME);

CREATE TABLE PROCUREMENT_APPROVAL_NODE (
    ID                VARCHAR(36)  NOT NULL PRIMARY KEY,
    INSTANCE_ID       VARCHAR(36)  NOT NULL,
    NODE_CODE         VARCHAR(64)  NOT NULL,
    NODE_NAME         VARCHAR(100) NOT NULL,
    NODE_ORDER        INT          NOT NULL,
    STATUS            VARCHAR(32)  NOT NULL,
    ASSIGNEE_USER_ID  VARCHAR(64),
    ASSIGNEE_NAME     VARCHAR(100),
    STARTED_TIME      TIMESTAMP,
    COMPLETED_TIME    TIMESTAMP,
    CONSTRAINT UK_PROC_APPROVAL_NODE_ORDER UNIQUE (INSTANCE_ID, NODE_ORDER),
    CONSTRAINT UK_PROC_APPROVAL_NODE_CODE UNIQUE (INSTANCE_ID, NODE_CODE),
    CONSTRAINT CK_PROC_APPROVAL_NODE_STATUS CHECK (
        STATUS IN ('PENDING', 'IN_PROGRESS', 'COMPLETED', 'RETURNED')
    ),
    CONSTRAINT FK_PROC_APPROVAL_NODE_INSTANCE FOREIGN KEY (INSTANCE_ID)
        REFERENCES PROCUREMENT_APPROVAL_INSTANCE (ID)
);

COMMENT ON TABLE PROCUREMENT_APPROVAL_NODE IS '采购需求审批节点表';
COMMENT ON COLUMN PROCUREMENT_APPROVAL_NODE.NODE_CODE IS '节点编码';
COMMENT ON COLUMN PROCUREMENT_APPROVAL_NODE.NODE_NAME IS '节点名称';
COMMENT ON COLUMN PROCUREMENT_APPROVAL_NODE.NODE_ORDER IS '节点顺序';
COMMENT ON COLUMN PROCUREMENT_APPROVAL_NODE.STATUS IS '节点状态：PENDING/IN_PROGRESS/COMPLETED/RETURNED';
COMMENT ON COLUMN PROCUREMENT_APPROVAL_NODE.ASSIGNEE_USER_ID IS '处理人用户ID';
COMMENT ON COLUMN PROCUREMENT_APPROVAL_NODE.ASSIGNEE_NAME IS '处理人名称';

CREATE INDEX IDX_PROC_APPROVAL_NODE_CURRENT
    ON PROCUREMENT_APPROVAL_NODE (INSTANCE_ID, STATUS, NODE_ORDER);

CREATE TABLE PROCUREMENT_APPROVAL_OPERATION_LOG (
    ID                VARCHAR(36)  NOT NULL PRIMARY KEY,
    INSTANCE_ID       VARCHAR(36)  NOT NULL,
    PROJECT_ID        VARCHAR(36)  NOT NULL,
    NODE_CODE         VARCHAR(64)  NOT NULL,
    OPERATION_TYPE    VARCHAR(32)  NOT NULL,
    OPERATOR_USER_ID  VARCHAR(64)  NOT NULL,
    OPERATOR_NAME     VARCHAR(100) NOT NULL,
    OPINION           VARCHAR(2000),
    FROM_STATUS       VARCHAR(32),
    TO_STATUS         VARCHAR(32),
    OPERATED_TIME     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CREATED_TIME      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CK_PROC_APPROVAL_OPERATION_TYPE CHECK (
        OPERATION_TYPE IN ('START', 'APPROVE', 'RETURN', 'COMMENT')
    ),
    CONSTRAINT FK_PROC_APPROVAL_OPERATION_INSTANCE FOREIGN KEY (INSTANCE_ID)
        REFERENCES PROCUREMENT_APPROVAL_INSTANCE (ID),
    CONSTRAINT FK_PROC_APPROVAL_OPERATION_PROJECT FOREIGN KEY (PROJECT_ID)
        REFERENCES PROCUREMENT_DEMAND (ID)
);

COMMENT ON TABLE PROCUREMENT_APPROVAL_OPERATION_LOG IS '采购需求审批操作日志表';
COMMENT ON COLUMN PROCUREMENT_APPROVAL_OPERATION_LOG.OPERATION_TYPE IS '操作类型：START/APPROVE/RETURN/COMMENT';
COMMENT ON COLUMN PROCUREMENT_APPROVAL_OPERATION_LOG.OPINION IS '审批意见或操作说明';
COMMENT ON COLUMN PROCUREMENT_APPROVAL_OPERATION_LOG.FROM_STATUS IS '操作前流程状态';
COMMENT ON COLUMN PROCUREMENT_APPROVAL_OPERATION_LOG.TO_STATUS IS '操作后流程状态';

CREATE INDEX IDX_PROC_APPROVAL_OPERATION_PROJECT
    ON PROCUREMENT_APPROVAL_OPERATION_LOG (PROJECT_ID, OPERATED_TIME);
CREATE INDEX IDX_PROC_APPROVAL_OPERATION_INSTANCE
    ON PROCUREMENT_APPROVAL_OPERATION_LOG (INSTANCE_ID, OPERATED_TIME);

COMMIT;
