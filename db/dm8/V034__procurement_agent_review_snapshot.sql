-- V034: 每个采购项目仅保留最新一次智能体预审结果。

CREATE TABLE PROCUREMENT_AGENT_REVIEW_SNAPSHOT (
    ID             VARCHAR(36) NOT NULL PRIMARY KEY,
    PROJECT_ID     VARCHAR(36) NOT NULL,
    GENERATED_TIME TIMESTAMP   NOT NULL,
    REVIEW_JSON    CLOB        NOT NULL,
    CONSTRAINT UK_PROC_AGENT_REVIEW_PROJECT UNIQUE (PROJECT_ID),
    CONSTRAINT FK_PROC_AGENT_REVIEW_PROJECT FOREIGN KEY (PROJECT_ID)
        REFERENCES PROCUREMENT_DEMAND (ID)
);

CREATE INDEX IDX_PROC_AGENT_REVIEW_TIME
    ON PROCUREMENT_AGENT_REVIEW_SNAPSHOT (PROJECT_ID, GENERATED_TIME);

COMMENT ON TABLE PROCUREMENT_AGENT_REVIEW_SNAPSHOT IS '采购项目最新智能体预审结果快照';
COMMENT ON COLUMN PROCUREMENT_AGENT_REVIEW_SNAPSHOT.REVIEW_JSON IS '规则与AI预审结果 JSON';

COMMIT;
