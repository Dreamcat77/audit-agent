ALTER TABLE CONTRACT_CANDIDATE ADD SOURCE_PARSE_RESULT_ID VARCHAR(36);
ALTER TABLE CONTRACT_CANDIDATE ADD SOURCE_ROLE_DECISION_ID VARCHAR(36);
ALTER TABLE CONTRACT_CANDIDATE ADD SOURCE_AUTHORITY_SOURCE VARCHAR(32);
ALTER TABLE CONTRACT_CANDIDATE ADD SOURCE_FACT_FINGERPRINT VARCHAR(64);

ALTER TABLE PROJECT_FILE_PARSE_RESULT ADD
    CONSTRAINT UK_PROJECT_FILE_PARSE_RESULT_OWNERSHIP
    UNIQUE (PARSE_RESULT_ID, PROJECT_ID, FILE_ID);

ALTER TABLE PROJECT_FILE_ROLE_DECISION ADD
    CONSTRAINT UK_PROJECT_FILE_ROLE_DECISION_PARSE_BINDING
    UNIQUE (DECISION_ID, PROJECT_ID, FILE_ID, PARSE_RESULT_ID);

ALTER TABLE CONTRACT_CANDIDATE ADD
    CONSTRAINT UK_CONTRACT_CANDIDATE_SOURCE_OWNER
    UNIQUE (PROJECT_ID, ID, SOURCE_CONTRACT_FILE_ID);

ALTER TABLE CONTRACT_CANDIDATE ADD
    CONSTRAINT UK_CONTRACT_CANDIDATE_PARSE_OWNER
    UNIQUE (PROJECT_ID, ID, SOURCE_PARSE_RESULT_ID);

ALTER TABLE CONTRACT_CANDIDATE ADD
    CONSTRAINT FK_CONTRACT_CANDIDATE_SOURCE_PARSE
    FOREIGN KEY (SOURCE_PARSE_RESULT_ID, PROJECT_ID, SOURCE_CONTRACT_FILE_ID)
    REFERENCES PROJECT_FILE_PARSE_RESULT (PARSE_RESULT_ID, PROJECT_ID, FILE_ID);

ALTER TABLE CONTRACT_CANDIDATE ADD
    CONSTRAINT FK_CONTRACT_CANDIDATE_SOURCE_ROLE_DECISION
    FOREIGN KEY (SOURCE_ROLE_DECISION_ID, PROJECT_ID, SOURCE_CONTRACT_FILE_ID, SOURCE_PARSE_RESULT_ID)
    REFERENCES PROJECT_FILE_ROLE_DECISION (DECISION_ID, PROJECT_ID, FILE_ID, PARSE_RESULT_ID);

ALTER TABLE CONTRACT_CANDIDATE ADD
    CONSTRAINT CK_CONTRACT_CANDIDATE_AUTHORITY_TUPLE CHECK (
        (SOURCE_PARSE_RESULT_ID IS NULL AND SOURCE_ROLE_DECISION_ID IS NULL
            AND SOURCE_AUTHORITY_SOURCE IS NULL AND SOURCE_FACT_FINGERPRINT IS NULL)
        OR (SOURCE_PARSE_RESULT_ID IS NOT NULL AND SOURCE_ROLE_DECISION_ID IS NOT NULL
            AND SOURCE_AUTHORITY_SOURCE IS NOT NULL
            AND SOURCE_AUTHORITY_SOURCE = 'HUMAN_CONFIRMATION' AND SOURCE_FACT_FINGERPRINT IS NOT NULL)
        OR (SOURCE_PARSE_RESULT_ID IS NOT NULL AND SOURCE_ROLE_DECISION_ID IS NULL
            AND SOURCE_AUTHORITY_SOURCE IS NOT NULL
            AND SOURCE_AUTHORITY_SOURCE = 'LEGACY_COMPAT' AND SOURCE_FACT_FINGERPRINT IS NULL));

ALTER TABLE CONTRACT_CANDIDATE ADD
    CONSTRAINT CK_CONTRACT_CANDIDATE_AUTHORITY_SOURCE
    CHECK (SOURCE_AUTHORITY_SOURCE IS NULL
        OR SOURCE_AUTHORITY_SOURCE IN ('HUMAN_CONFIRMATION', 'LEGACY_COMPAT'));

ALTER TABLE CONTRACT_CANDIDATE ADD
    CONSTRAINT CK_CONTRACT_CANDIDATE_FACT_FINGERPRINT
    CHECK (SOURCE_FACT_FINGERPRINT IS NULL
        OR (LENGTH(SOURCE_FACT_FINGERPRINT) = 64
            AND SOURCE_FACT_FINGERPRINT = LOWER(SOURCE_FACT_FINGERPRINT)));

ALTER TABLE PROJECT_EXTRACTION_RESULT ADD PARSE_RESULT_ID VARCHAR(36);

ALTER TABLE PROJECT_EXTRACTION_RESULT ADD
    CONSTRAINT FK_PROJECT_EXTRACTION_PARSE_RESULT
    FOREIGN KEY (PARSE_RESULT_ID, PROJECT_ID, SOURCE_FILE_ID)
    REFERENCES PROJECT_FILE_PARSE_RESULT (PARSE_RESULT_ID, PROJECT_ID, FILE_ID);

ALTER TABLE PROJECT_EXTRACTION_RESULT ADD
    CONSTRAINT FK_PROJECT_EXTRACTION_CANDIDATE_SOURCE
    FOREIGN KEY (PROJECT_ID, CANDIDATE_ID, SOURCE_FILE_ID)
    REFERENCES CONTRACT_CANDIDATE (PROJECT_ID, ID, SOURCE_CONTRACT_FILE_ID);

ALTER TABLE PROJECT_EXTRACTION_RESULT ADD
    CONSTRAINT FK_PROJECT_EXTRACTION_CANDIDATE_PARSE
    FOREIGN KEY (PROJECT_ID, CANDIDATE_ID, PARSE_RESULT_ID)
    REFERENCES CONTRACT_CANDIDATE (PROJECT_ID, ID, SOURCE_PARSE_RESULT_ID);

CREATE INDEX IDX_CONTRACT_CANDIDATE_SOURCE_PARSE
    ON CONTRACT_CANDIDATE (SOURCE_PARSE_RESULT_ID, PROJECT_ID, SOURCE_CONTRACT_FILE_ID);
CREATE INDEX IDX_CONTRACT_CANDIDATE_SOURCE_ROLE_DECISION
    ON CONTRACT_CANDIDATE (SOURCE_ROLE_DECISION_ID, PROJECT_ID, SOURCE_CONTRACT_FILE_ID);
CREATE INDEX IDX_PROJECT_EXTRACTION_SOURCE_PARSE
    ON PROJECT_EXTRACTION_RESULT (PROJECT_ID, SOURCE_FILE_ID, PARSE_RESULT_ID, FACT_TYPE, EXTRACTION_KEY);
