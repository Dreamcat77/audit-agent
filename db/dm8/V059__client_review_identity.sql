-- Single-client deployment registry: formal name and explicitly approved aliases.
-- No real customer names or example aliases are seeded in source control.
CREATE TABLE AUDIT_CLIENT_IDENTITY (
    IDENTITY_ID VARCHAR(36) NOT NULL,
    MATCH_NAME VARCHAR(480) NOT NULL,
    NAME_KIND VARCHAR(16) NOT NULL,
    ENABLED SMALLINT DEFAULT 1 NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_AUDIT_CLIENT_IDENTITY PRIMARY KEY (IDENTITY_ID),
    CONSTRAINT UK_AUDIT_CLIENT_MATCH_NAME UNIQUE (MATCH_NAME),
    CONSTRAINT CK_AUDIT_CLIENT_NAME_KIND CHECK (NAME_KIND IN ('FORMAL','ALIAS')),
    CONSTRAINT CK_AUDIT_CLIENT_ENABLED CHECK (ENABLED IN (0,1))
);
COMMENT ON TABLE AUDIT_CLIENT_IDENTITY IS '部署服务对象名称及经批准的精确匹配别名；不得发送给外部模型';
