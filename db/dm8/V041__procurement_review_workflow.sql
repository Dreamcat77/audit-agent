-- V041: Procurement review wizard state. Individual review modules remain their own facts of record.
CREATE TABLE PROCUREMENT_REVIEW_WORKFLOW (
    ID VARCHAR(36) NOT NULL PRIMARY KEY,
    PROJECT_ID VARCHAR(36) NOT NULL,
    CURRENT_STEP_ORDER INTEGER NOT NULL,
    STATUS VARCHAR(32) NOT NULL,
    CREATED_TIME TIMESTAMP NOT NULL,
    UPDATED_TIME TIMESTAMP NOT NULL,
    CONSTRAINT UK_PROC_REVIEW_WORKFLOW_PROJECT UNIQUE (PROJECT_ID),
    CONSTRAINT FK_PROC_REVIEW_WORKFLOW_PROJECT FOREIGN KEY (PROJECT_ID) REFERENCES PROCUREMENT_DEMAND(ID),
    CONSTRAINT CK_PROC_REVIEW_WORKFLOW_STEP CHECK (CURRENT_STEP_ORDER BETWEEN 1 AND 8),
    CONSTRAINT CK_PROC_REVIEW_WORKFLOW_STATUS CHECK (STATUS IN ('IN_PROGRESS','COMPLETED'))
);
CREATE TABLE PROCUREMENT_REVIEW_STEP (
    WORKFLOW_ID VARCHAR(36) NOT NULL,
    STEP_CODE VARCHAR(64) NOT NULL,
    STEP_ORDER INTEGER NOT NULL,
    STEP_NAME VARCHAR(100) NOT NULL,
    STATUS VARCHAR(32) NOT NULL,
    COMPLETED_TIME TIMESTAMP,
    RESULT_SUMMARY VARCHAR(2000),
    CONSTRAINT PK_PROC_REVIEW_STEP PRIMARY KEY (WORKFLOW_ID, STEP_CODE),
    CONSTRAINT UK_PROC_REVIEW_STEP_ORDER UNIQUE (WORKFLOW_ID, STEP_ORDER),
    CONSTRAINT FK_PROC_REVIEW_STEP_WORKFLOW FOREIGN KEY (WORKFLOW_ID) REFERENCES PROCUREMENT_REVIEW_WORKFLOW(ID),
    CONSTRAINT CK_PROC_REVIEW_STEP_ORDER CHECK (STEP_ORDER BETWEEN 1 AND 8),
    CONSTRAINT CK_PROC_REVIEW_STEP_STATUS CHECK (STATUS IN ('PENDING','IN_PROGRESS','COMPLETED'))
);
CREATE INDEX IDX_PROC_REVIEW_STEP_WORKFLOW ON PROCUREMENT_REVIEW_STEP (WORKFLOW_ID, STEP_ORDER);
COMMENT ON TABLE PROCUREMENT_REVIEW_WORKFLOW IS '采购审查八步向导流程实例';
COMMENT ON TABLE PROCUREMENT_REVIEW_STEP IS '采购审查步骤执行状态';
COMMIT;
