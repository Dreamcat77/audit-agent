-- MIGRATION-NAMESPACE: CONTRACT
-- MIGRATION-ID: contract-final-closeout-fact-extraction
-- DEPENDS-ON: contract-final-closeout,project-file-identity-assessment,contract-candidate-authority
-- PURPOSE: durable A-mini request identity, provenance and validated/rejected candidate audit
-- EXECUTION: CONTROLLED_MANUAL
-- IDEMPOTENCY: NOT_ASSUMED

CREATE TABLE PROJECT_FACT_EXTRACTION_ATTEMPT (
    ATTEMPT_ID VARCHAR(36) NOT NULL,
    PROJECT_ID VARCHAR(36) NOT NULL,
    FILE_ID VARCHAR(36) NOT NULL,
    FILE_SHA256 VARCHAR(64) NOT NULL,
    PARSE_RESULT_ID VARCHAR(36) NOT NULL,
    PARSE_VERSION INT NOT NULL,
    CANONICAL_TEXT_SHA256 VARCHAR(64) NOT NULL,
    EFFECTIVE_ROLE VARCHAR(32) NOT NULL,
    ROLE_DECISION_ID VARCHAR(36) NOT NULL,
    IDENTITY_DECISION_ID VARCHAR(36) NOT NULL,
    INPUT_FINGERPRINT VARCHAR(64) NOT NULL,
    ACTOR_ID VARCHAR(36) NOT NULL,
    OPERATION_KEY VARCHAR(128) NOT NULL,
    PROVIDER VARCHAR(100) NOT NULL,
    MODEL_NAME VARCHAR(200) NOT NULL,
    MODEL_REVISION VARCHAR(200) NOT NULL,
    PROMPT_VERSION VARCHAR(100) NOT NULL,
    SCHEMA_VERSION VARCHAR(100) NOT NULL,
    STATUS VARCHAR(32) NOT NULL,
    CALL_COUNT INT DEFAULT 1 NOT NULL,
    ACCEPTED_COUNT INT DEFAULT 0 NOT NULL,
    REJECTED_COUNT INT DEFAULT 0 NOT NULL,
    FAILURE_REASON VARCHAR(200),
    CREATED_AT TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP NOT NULL,
    VERSION_NO BIGINT DEFAULT 0 NOT NULL,
    CONSTRAINT PK_PROJECT_FACT_EXTRACTION_ATTEMPT PRIMARY KEY (ATTEMPT_ID),
    CONSTRAINT UK_PROJECT_FACT_EXTRACTION_OPERATION UNIQUE (ACTOR_ID, OPERATION_KEY),
    CONSTRAINT FK_PROJECT_FACT_EXTRACTION_FILE FOREIGN KEY (PROJECT_ID, FILE_ID)
        REFERENCES PROJECT_FILE (PROJECT_ID, ID),
    CONSTRAINT FK_PROJECT_FACT_EXTRACTION_PARSE FOREIGN KEY
        (PARSE_RESULT_ID, PROJECT_ID, FILE_ID, FILE_SHA256, PARSE_VERSION)
        REFERENCES PROJECT_FILE_PARSE_RESULT
        (PARSE_RESULT_ID, PROJECT_ID, FILE_ID, FILE_SHA256, PARSE_VERSION),
    CONSTRAINT FK_PROJECT_FACT_EXTRACTION_ROLE FOREIGN KEY
        (ROLE_DECISION_ID, PROJECT_ID, FILE_ID, PARSE_RESULT_ID)
        REFERENCES PROJECT_FILE_ROLE_DECISION
        (DECISION_ID, PROJECT_ID, FILE_ID, PARSE_RESULT_ID),
    CONSTRAINT FK_PROJECT_FACT_EXTRACTION_IDENTITY FOREIGN KEY
        (IDENTITY_DECISION_ID, PROJECT_ID, FILE_ID, PARSE_RESULT_ID)
        REFERENCES PROJECT_FILE_IDENTITY_DECISION
        (DECISION_ID, PROJECT_ID, FILE_ID, PARSE_RESULT_ID),
    CONSTRAINT FK_PROJECT_FACT_EXTRACTION_ACTOR FOREIGN KEY (ACTOR_ID)
        REFERENCES SYS_USER (ID),
    CONSTRAINT CK_PROJECT_FACT_EXTRACTION_ROLE CHECK (EFFECTIVE_ROLE IN ('CONTRACT_BODY','AWARD_NOTICE')),
    CONSTRAINT CK_PROJECT_FACT_EXTRACTION_STATUS CHECK (STATUS IN ('IN_PROGRESS','SUCCEEDED','FAILED','OUTCOME_UNKNOWN')),
    CONSTRAINT CK_PROJECT_FACT_EXTRACTION_COUNTS CHECK (PARSE_VERSION > 0 AND CALL_COUNT > 0 AND ACCEPTED_COUNT >= 0 AND REJECTED_COUNT >= 0)
);

CREATE INDEX IX_PROJECT_FACT_EXTRACTION_FILE_PARSE
    ON PROJECT_FACT_EXTRACTION_ATTEMPT (PROJECT_ID, FILE_ID, PARSE_RESULT_ID, UPDATED_AT);

CREATE INDEX IX_PROJECT_FACT_EXTRACTION_INPUT
    ON PROJECT_FACT_EXTRACTION_ATTEMPT (INPUT_FINGERPRINT);

CREATE TABLE PROJECT_FACT_EXTRACTION_CANDIDATE (
    CANDIDATE_ID VARCHAR(36) NOT NULL,
    ATTEMPT_ID VARCHAR(36) NOT NULL,
    CANDIDATE_KEY VARCHAR(80) NOT NULL,
    FACT_TYPE VARCHAR(64) NOT NULL,
    GROUP_KEY VARCHAR(128),
    VALUE_TEXT VARCHAR(1000),
    VALUE_DECIMAL DECIMAL(18,4),
    SEGMENT_ID VARCHAR(100) NOT NULL,
    SOURCE_LOCATOR VARCHAR(200) NOT NULL,
    EXCERPT VARCHAR(1000) NOT NULL,
    EXCERPT_START INT NOT NULL,
    EXCERPT_END INT NOT NULL,
    CONTEXT_CODE VARCHAR(64) NOT NULL,
    CONFIDENCE DECIMAL(6,5) NOT NULL,
    VALIDATION_STATUS VARCHAR(32) NOT NULL,
    VALIDATION_REASON VARCHAR(64) NOT NULL,
    PUBLISHED_EXTRACTION_ID VARCHAR(36),
    CREATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT PK_PROJECT_FACT_EXTRACTION_CANDIDATE PRIMARY KEY (CANDIDATE_ID),
    CONSTRAINT UK_PROJECT_FACT_EXTRACTION_CANDIDATE UNIQUE (ATTEMPT_ID, CANDIDATE_KEY),
    CONSTRAINT FK_PROJECT_FACT_EXTRACTION_ATTEMPT FOREIGN KEY (ATTEMPT_ID)
        REFERENCES PROJECT_FACT_EXTRACTION_ATTEMPT (ATTEMPT_ID),
    CONSTRAINT FK_PROJECT_FACT_EXTRACTION_PUBLISHED FOREIGN KEY (PUBLISHED_EXTRACTION_ID)
        REFERENCES PROJECT_EXTRACTION_RESULT (ID),
    CONSTRAINT CK_PROJECT_FACT_CANDIDATE_OFFSETS CHECK (EXCERPT_START >= 0 AND EXCERPT_END > EXCERPT_START),
    CONSTRAINT CK_PROJECT_FACT_CANDIDATE_CONFIDENCE CHECK (CONFIDENCE >= 0 AND CONFIDENCE <= 1),
    CONSTRAINT CK_PROJECT_FACT_CANDIDATE_PUBLICATION CHECK (
        (VALIDATION_STATUS='ACCEPTED' AND PUBLISHED_EXTRACTION_ID IS NOT NULL)
        OR (VALIDATION_STATUS='REJECTED' AND PUBLISHED_EXTRACTION_ID IS NULL)
    )
);

CREATE INDEX IX_PROJECT_FACT_CANDIDATE_ATTEMPT
    ON PROJECT_FACT_EXTRACTION_CANDIDATE (ATTEMPT_ID, CREATED_AT);
