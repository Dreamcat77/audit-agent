-- MIGRATION-NAMESPACE: CONTRACT
-- MIGRATION-ID: review-run-results
-- DEPENDS-ON: review-run
-- PURPOSE: append-only review-run findings and parse-bound evidence
-- EXECUTION: CONTROLLED_MANUAL
-- IDEMPOTENCY: NOT_ASSUMED

-- These keys are strictly additive to the existing Phase 2A tables. They make
-- the exact owner and frozen parse tuple referencable without changing old rows.
ALTER TABLE CONTRACT_REVIEW_STEP_ATTEMPT ADD
    CONSTRAINT UK_CONTRACT_REVIEW_STEP_ATTEMPT_OWNER UNIQUE (RUN_ID, STEP_ID, ATTEMPT_ID);
ALTER TABLE CONTRACT_REVIEW_RUN_MATERIAL ADD
    CONSTRAINT UK_CONTRACT_REVIEW_RUN_MATERIAL_PARSE_TUPLE UNIQUE
        (RUN_ID, FILE_ID, FILE_SHA256, PARSE_RESULT_ID, PARSE_VERSION, CANONICAL_TEXT_SHA256);
ALTER TABLE CONTRACT_REVIEW_STEP_ATTEMPT MODIFY "MODEL" VARCHAR(128);

CREATE TABLE CONTRACT_REVIEW_FINDING (
    FINDING_ID VARCHAR(36) NOT NULL,
    RUN_ID VARCHAR(36) NOT NULL,
    STEP_ID VARCHAR(36) NOT NULL,
    ATTEMPT_ID VARCHAR(36) NOT NULL,
    ORDINAL INTEGER NOT NULL,
    FINDING_TYPE VARCHAR(128) NOT NULL,
    CATEGORY VARCHAR(128) NOT NULL,
    STATUS_CODE VARCHAR(128),
    ATTENTION_CODE VARCHAR(128),
    RISK_LEVEL VARCHAR(32),
    SUMMARY VARCHAR(1000) NOT NULL,
    RECOMMENDATION VARCHAR(2000),
    FINDING_SCHEMA_VERSION INTEGER NOT NULL,
    POLICY_VERSION VARCHAR(100) NOT NULL,
    SOURCE VARCHAR(32) NOT NULL,
    MODEL_PROVIDER VARCHAR(100),
    MODEL_NAME VARCHAR(128),
    MODEL_REVISION VARCHAR(100),
    PROMPT_VERSION VARCHAR(100),
    MODEL_SCHEMA_VERSION VARCHAR(100),
    CREATED_AT TIMESTAMP NOT NULL,
    VERSION_NO BIGINT DEFAULT 0 NOT NULL,
    CONSTRAINT PK_CONTRACT_REVIEW_FINDING PRIMARY KEY (FINDING_ID),
    CONSTRAINT UK_CONTRACT_REVIEW_FINDING_OWNER UNIQUE
        (FINDING_ID, RUN_ID, STEP_ID, ATTEMPT_ID),
    CONSTRAINT UK_CONTRACT_REVIEW_FINDING_ORDINAL UNIQUE (ATTEMPT_ID, ORDINAL),
    CONSTRAINT FK_CONTRACT_REVIEW_FINDING_ATTEMPT FOREIGN KEY (RUN_ID, STEP_ID, ATTEMPT_ID)
        REFERENCES CONTRACT_REVIEW_STEP_ATTEMPT (RUN_ID, STEP_ID, ATTEMPT_ID),
    CONSTRAINT CK_CONTRACT_REVIEW_FINDING_VERSION CHECK
        (ORDINAL > 0 AND FINDING_SCHEMA_VERSION > 0 AND VERSION_NO >= 0),
    CONSTRAINT CK_CONTRACT_REVIEW_FINDING_SOURCE CHECK
        (SOURCE IN ('DETERMINISTIC', 'MODEL_ASSISTED')),
    CONSTRAINT CK_CONTRACT_REVIEW_FINDING_RISK CHECK
        (RISK_LEVEL IS NULL OR RISK_LEVEL IN ('GREEN', 'YELLOW', 'RED')),
    CONSTRAINT CK_CONTRACT_REVIEW_FINDING_TYPED CHECK
        (LENGTH(FINDING_TYPE) > 0 AND LENGTH(CATEGORY) > 0
            AND (STATUS_CODE IS NULL OR LENGTH(STATUS_CODE) > 0)
            AND LENGTH(SUMMARY) > 0 AND LENGTH(POLICY_VERSION) > 0),
    CONSTRAINT CK_CONTRACT_REVIEW_FINDING_DETERMINISTIC CHECK
        (SOURCE <> 'DETERMINISTIC' OR (MODEL_PROVIDER IS NULL AND MODEL_NAME IS NULL
            AND MODEL_REVISION IS NULL AND PROMPT_VERSION IS NULL AND MODEL_SCHEMA_VERSION IS NULL))
);

CREATE INDEX IDX_CONTRACT_REVIEW_FINDING_ATTEMPT
    ON CONTRACT_REVIEW_FINDING (RUN_ID, STEP_ID, ATTEMPT_ID, ORDINAL);

CREATE TABLE CONTRACT_REVIEW_EVIDENCE (
    EVIDENCE_ID VARCHAR(36) NOT NULL,
    FINDING_ID VARCHAR(36) NOT NULL,
    RUN_ID VARCHAR(36) NOT NULL,
    STEP_ID VARCHAR(36) NOT NULL,
    ATTEMPT_ID VARCHAR(36) NOT NULL,
    ORDINAL INTEGER NOT NULL,
    FILE_ID VARCHAR(36) NOT NULL,
    FILE_SHA256 VARCHAR(64) NOT NULL,
    PARSE_RESULT_ID VARCHAR(36) NOT NULL,
    PARSE_VERSION INTEGER NOT NULL,
    CANONICAL_TEXT_SHA256 VARCHAR(64) NOT NULL,
    EVIDENCE_ROLE VARCHAR(32) NOT NULL,
    VALIDATION_STATUS VARCHAR(32) NOT NULL,
    VALIDATION_POLICY_VERSION VARCHAR(100) NOT NULL,
    PAGE_NUMBER INTEGER,
    PARAGRAPH_INDEX INTEGER,
    TABLE_INDEX INTEGER,
    ROW_INDEX INTEGER,
    CELL_INDEX INTEGER,
    SEGMENT_INDEX INTEGER,
    LOCATOR_AVAILABLE INTEGER NOT NULL,
    START_OFFSET INTEGER,
    END_OFFSET INTEGER,
    EXCERPT_SHA256 VARCHAR(64),
    BOUNDED_EXCERPT VARCHAR(1000) NOT NULL,
    LOCATOR_SCHEMA_VERSION INTEGER NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    VERSION_NO BIGINT DEFAULT 0 NOT NULL,
    CONSTRAINT PK_CONTRACT_REVIEW_EVIDENCE PRIMARY KEY (EVIDENCE_ID),
    CONSTRAINT UK_CONTRACT_REVIEW_EVIDENCE_ORDINAL UNIQUE (FINDING_ID, ORDINAL),
    CONSTRAINT FK_CONTRACT_REVIEW_EVIDENCE_FINDING FOREIGN KEY
        (FINDING_ID, RUN_ID, STEP_ID, ATTEMPT_ID)
        REFERENCES CONTRACT_REVIEW_FINDING (FINDING_ID, RUN_ID, STEP_ID, ATTEMPT_ID),
    CONSTRAINT FK_CONTRACT_REVIEW_EVIDENCE_MATERIAL FOREIGN KEY
        (RUN_ID, FILE_ID, FILE_SHA256, PARSE_RESULT_ID, PARSE_VERSION, CANONICAL_TEXT_SHA256)
        REFERENCES CONTRACT_REVIEW_RUN_MATERIAL
            (RUN_ID, FILE_ID, FILE_SHA256, PARSE_RESULT_ID, PARSE_VERSION, CANONICAL_TEXT_SHA256),
    CONSTRAINT CK_CONTRACT_REVIEW_EVIDENCE_VERSION CHECK
        (ORDINAL > 0 AND PARSE_VERSION > 0 AND LOCATOR_SCHEMA_VERSION > 0 AND VERSION_NO >= 0),
    CONSTRAINT CK_CONTRACT_REVIEW_EVIDENCE_HASH CHECK
        (LENGTH(FILE_SHA256) = 64 AND LENGTH(CANONICAL_TEXT_SHA256) = 64
            AND (EXCERPT_SHA256 IS NULL OR LENGTH(EXCERPT_SHA256) = 64)),
    CONSTRAINT CK_CONTRACT_REVIEW_EVIDENCE_ROLE CHECK
        (EVIDENCE_ROLE IN ('PROBLEM', 'COMPARISON', 'SUPPORT')),
    CONSTRAINT CK_CONTRACT_REVIEW_EVIDENCE_STATUS CHECK
        (VALIDATION_STATUS IN ('VALIDATED', 'LOCATOR_UNAVAILABLE')),
    CONSTRAINT CK_CONTRACT_REVIEW_EVIDENCE_DIMENSIONS CHECK
        ((PAGE_NUMBER IS NULL OR PAGE_NUMBER > 0)
            AND (PARAGRAPH_INDEX IS NULL OR PARAGRAPH_INDEX >= 0)
            AND (TABLE_INDEX IS NULL OR TABLE_INDEX >= 0)
            AND (ROW_INDEX IS NULL OR ROW_INDEX >= 0)
            AND (CELL_INDEX IS NULL OR CELL_INDEX >= 0)
            AND (SEGMENT_INDEX IS NULL OR SEGMENT_INDEX >= 0)),
    CONSTRAINT CK_CONTRACT_REVIEW_EVIDENCE_LOCATOR CHECK
        (LOCATOR_AVAILABLE IN (0, 1)
            AND ((LOCATOR_AVAILABLE = 0 AND VALIDATION_STATUS = 'LOCATOR_UNAVAILABLE'
                    AND START_OFFSET IS NULL AND END_OFFSET IS NULL)
                OR (LOCATOR_AVAILABLE = 1 AND VALIDATION_STATUS = 'VALIDATED'
                    AND START_OFFSET >= 0 AND END_OFFSET > START_OFFSET
                    AND EXCERPT_SHA256 IS NOT NULL))),
    CONSTRAINT CK_CONTRACT_REVIEW_EVIDENCE_TEXT CHECK
        (LENGTH(BOUNDED_EXCERPT) > 0 AND LENGTH(VALIDATION_POLICY_VERSION) > 0)
);

CREATE INDEX IDX_CONTRACT_REVIEW_EVIDENCE_FINDING
    ON CONTRACT_REVIEW_EVIDENCE (RUN_ID, STEP_ID, ATTEMPT_ID, FINDING_ID, ORDINAL);
