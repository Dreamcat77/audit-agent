-- Procurement material facts are independent of Contract Project Intake.
-- Apply once after catalog preflight; additive only, never rewrites historical associations.
CREATE TABLE BUSINESS_MATERIAL_INTAKE (
    ID VARCHAR(36) NOT NULL PRIMARY KEY,
    ACTOR_ID VARCHAR(64) NOT NULL,
    OPERATION_KEY VARCHAR(36) NOT NULL,
    FILE_NAME VARCHAR(255) NOT NULL,
    MEDIA_TYPE VARCHAR(100) NOT NULL,
    FILE_SIZE BIGINT NOT NULL,
    SHA256 VARCHAR(64) NOT NULL,
    STORAGE_KEY VARCHAR(64) NOT NULL,
    STATUS VARCHAR(20) NOT NULL,
    LEASE_TOKEN VARCHAR(36) NOT NULL,
    LEASE_UNTIL TIMESTAMP(6) NOT NULL,
    PARSE_METHOD VARCHAR(20),
    ERROR_CODE VARCHAR(64),
    PROJECT_NAME VARCHAR(200),
    PROJECT_NO VARCHAR(200),
    DEPARTMENT_NAME VARCHAR(200),
    PROCUREMENT_TYPE VARCHAR(20),
    BUDGET_AMOUNT DECIMAL(18,2),
    SUBJECT_CODE VARCHAR(200),
    SUBJECT_NAME VARCHAR(200),
    PROCUREMENT_METHOD VARCHAR(40),
    REQUIREMENT_DESCRIPTION VARCHAR(2000),
    APPLICANT_NAME VARCHAR(200),
    FIELDS_JSON CLOB,
    CREATED_AT TIMESTAMP(6) NOT NULL,
    UPDATED_AT TIMESTAMP(6) NOT NULL,
    CONSTRAINT UK_PROC_MAT_OPERATION UNIQUE (ACTOR_ID, OPERATION_KEY),
    CONSTRAINT CK_PROC_MAT_STATUS CHECK (STATUS IN ('PROCESSING', 'PARSED', 'FAILED', 'UNKNOWN'))
);
CREATE INDEX IDX_PROC_MAT_LIST ON BUSINESS_MATERIAL_INTAKE (STATUS, UPDATED_AT, ID);
CREATE INDEX IDX_PROC_MAT_ACTOR ON BUSINESS_MATERIAL_INTAKE (ACTOR_ID, CREATED_AT);
-- An application-owned link leaves the historical demand table/schema untouched.
-- The command inserts this link from an existing demand and parsed material in one transaction.
CREATE TABLE PROCUREMENT_MATERIAL_LINK (
    DEMAND_ID VARCHAR(36) NOT NULL PRIMARY KEY,
    MATERIAL_ID VARCHAR(36) NOT NULL,
    CREATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_PROC_MATERIAL_LINK FOREIGN KEY (MATERIAL_ID) REFERENCES BUSINESS_MATERIAL_INTAKE (ID)
);
CREATE INDEX IDX_PROC_MATERIAL_LINK ON PROCUREMENT_MATERIAL_LINK (MATERIAL_ID);
