-- MIGRATION-NAMESPACE: CONTRACT
-- MIGRATION-ID: contract-system-auto-authority
-- DEPENDS-ON: contract-candidate-authority,project-file-identity-assessment
-- PURPOSE: allow upload-time system classification to retain a distinct authority source
-- EXECUTION: CONTROLLED_MANUAL
-- IDEMPOTENCY: NOT_ASSUMED

-- This migration is additive to the authority vocabulary only. It does not rewrite
-- existing candidate rows or decision history. Unknown/other schema must stop.
ALTER TABLE CONTRACT_CANDIDATE DROP CONSTRAINT CK_CONTRACT_CANDIDATE_AUTHORITY_TUPLE;
ALTER TABLE CONTRACT_CANDIDATE ADD CONSTRAINT CK_CONTRACT_CANDIDATE_AUTHORITY_TUPLE CHECK (
    (SOURCE_PARSE_RESULT_ID IS NULL AND SOURCE_ROLE_DECISION_ID IS NULL
        AND SOURCE_AUTHORITY_SOURCE IS NULL AND SOURCE_FACT_FINGERPRINT IS NULL)
    OR (SOURCE_PARSE_RESULT_ID IS NOT NULL AND SOURCE_ROLE_DECISION_ID IS NOT NULL
        AND SOURCE_AUTHORITY_SOURCE IS NOT NULL
        AND SOURCE_AUTHORITY_SOURCE IN ('HUMAN_CONFIRMATION', 'SYSTEM_AUTO')
        AND SOURCE_FACT_FINGERPRINT IS NOT NULL)
    OR (SOURCE_PARSE_RESULT_ID IS NOT NULL AND SOURCE_ROLE_DECISION_ID IS NULL
        AND SOURCE_AUTHORITY_SOURCE IS NOT NULL
        AND SOURCE_AUTHORITY_SOURCE = 'LEGACY_COMPAT' AND SOURCE_FACT_FINGERPRINT IS NULL));

ALTER TABLE CONTRACT_CANDIDATE DROP CONSTRAINT CK_CONTRACT_CANDIDATE_AUTHORITY_SOURCE;
ALTER TABLE CONTRACT_CANDIDATE ADD CONSTRAINT CK_CONTRACT_CANDIDATE_AUTHORITY_SOURCE CHECK (
    SOURCE_AUTHORITY_SOURCE IS NULL
    OR SOURCE_AUTHORITY_SOURCE IN ('HUMAN_CONFIRMATION', 'SYSTEM_AUTO', 'LEGACY_COMPAT'));

ALTER TABLE CONTRACT_CANDIDATE DROP CONSTRAINT CK_CONTRACT_CANDIDATE_SOURCE_IDENTITY_TUPLE;
ALTER TABLE CONTRACT_CANDIDATE ADD CONSTRAINT CK_CONTRACT_CANDIDATE_SOURCE_IDENTITY_TUPLE CHECK (
    SOURCE_IDENTITY_DECISION_ID IS NULL OR
    (SOURCE_PARSE_RESULT_ID IS NOT NULL AND SOURCE_ROLE_DECISION_ID IS NOT NULL
        AND SOURCE_AUTHORITY_SOURCE IN ('HUMAN_CONFIRMATION', 'SYSTEM_AUTO')));
