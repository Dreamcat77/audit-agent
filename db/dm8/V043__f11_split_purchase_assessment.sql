-- F11 拆分采购识别：每个采购项目仅保留最新一次 30 天窗口分析结果。
CREATE TABLE PROCUREMENT_SPLIT_PURCHASE_ASSESSMENT (
    ID VARCHAR(36) NOT NULL PRIMARY KEY,
    PROJECT_ID VARCHAR(36) NOT NULL,
    RISK_SCORE INTEGER NOT NULL,
    RISK_LEVEL VARCHAR(16) NOT NULL,
    FINDINGS_JSON CLOB NOT NULL,
    ASSESSED_TIME TIMESTAMP NOT NULL,
    CONSTRAINT UK_PROC_SPLIT_PURCHASE_PROJECT UNIQUE(PROJECT_ID),
    CONSTRAINT FK_PROC_SPLIT_PURCHASE_PROJECT FOREIGN KEY (PROJECT_ID) REFERENCES PROCUREMENT_DEMAND(ID),
    CONSTRAINT CK_PROC_SPLIT_PURCHASE_SCORE CHECK (RISK_SCORE BETWEEN 0 AND 100),
    CONSTRAINT CK_PROC_SPLIT_PURCHASE_LEVEL CHECK (RISK_LEVEL IN ('CRITICAL','WARNING','INFO'))
);
COMMENT ON TABLE PROCUREMENT_SPLIT_PURCHASE_ASSESSMENT IS 'F11 拆分采购识别最新结果；使用 F06 询比价记录时间进行 30 天滑动窗口分析';
COMMIT;
