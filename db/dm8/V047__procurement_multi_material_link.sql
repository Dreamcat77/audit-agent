-- V047 - One procurement demand may own multiple parsed intake materials.
-- Additive compatibility migration: preserve V046 links for rollback readers.
CREATE TABLE PROCUREMENT_DEMAND_MATERIAL (
    DEMAND_ID VARCHAR(36) NOT NULL,
    MATERIAL_ID VARCHAR(36) NOT NULL,
    MATERIAL_ORDER INT NOT NULL,
    IS_PRIMARY SMALLINT NOT NULL,
    CREATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_PROC_DEMAND_MATERIAL PRIMARY KEY (DEMAND_ID, MATERIAL_ID),
    CONSTRAINT UK_PROC_DEMAND_MATERIAL UNIQUE (MATERIAL_ID),
    CONSTRAINT UK_PROC_DEMAND_MATERIAL_ORDER UNIQUE (DEMAND_ID, MATERIAL_ORDER),
    CONSTRAINT CK_PROC_DEMAND_MATERIAL_ORDER CHECK (MATERIAL_ORDER BETWEEN 1 AND 10),
    CONSTRAINT CK_PROC_DEMAND_MATERIAL_PRIMARY CHECK (IS_PRIMARY IN (0, 1)),
    CONSTRAINT FK_PROC_DEMAND_MATERIAL_MATERIAL FOREIGN KEY (MATERIAL_ID)
        REFERENCES BUSINESS_MATERIAL_INTAKE (ID)
);

INSERT INTO PROCUREMENT_DEMAND_MATERIAL
    (DEMAND_ID, MATERIAL_ID, MATERIAL_ORDER, IS_PRIMARY, CREATED_AT)
SELECT DEMAND_ID, MATERIAL_ID, 1, 1, CREATED_AT
FROM PROCUREMENT_MATERIAL_LINK;
