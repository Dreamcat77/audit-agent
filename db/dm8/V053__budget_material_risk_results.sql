-- Immutable, actor-scoped reference results from uploaded budget materials.
CREATE TABLE BUDGET_MATERIAL_RISK_RESULT (
    ID VARCHAR(36) NOT NULL PRIMARY KEY,
    ACTOR_ID VARCHAR(64) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    RESULT_JSON CLOB NOT NULL
);
CREATE INDEX IX_BUDGET_MATERIAL_RISK_ACTOR ON BUDGET_MATERIAL_RISK_RESULT(ACTOR_ID,CREATED_AT,ID);
