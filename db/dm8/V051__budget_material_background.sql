-- F01 durable upload operation and background lease. Existing tasks are untouched.
CREATE TABLE BUDGET_MATERIAL_JOB (
    ID VARCHAR(36) NOT NULL PRIMARY KEY,
    ACTOR_ID VARCHAR(64) NOT NULL,
    OPERATION_KEY VARCHAR(36) NOT NULL,
    SHA256 VARCHAR(64) NOT NULL,
    STATUS VARCHAR(20) NOT NULL,
    LEASE_TOKEN VARCHAR(36),
    LEASE_UNTIL TIMESTAMP,
    UPDATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT UK_BUDGET_MAT_OPERATION UNIQUE (ACTOR_ID, OPERATION_KEY),
    CONSTRAINT FK_BUDGET_MAT_TASK FOREIGN KEY (ID) REFERENCES BUDGET_REVIEW_TASK(ID),
    CONSTRAINT CK_BUDGET_MAT_STATUS CHECK (STATUS IN ('QUEUED','PROCESSING','PARSED','FAILED','UNKNOWN'))
);
CREATE INDEX IX_BUDGET_MAT_PENDING ON BUDGET_MATERIAL_JOB(STATUS,LEASE_UNTIL,UPDATED_AT);
