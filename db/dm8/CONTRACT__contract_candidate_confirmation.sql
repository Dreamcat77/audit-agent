-- MIGRATION-NAMESPACE: CONTRACT
-- MIGRATION-ID: contract-candidate-confirmation
-- DEPENDS-ON: project-file-identity-assessment
-- PURPOSE: immutable human confirmation snapshots for contract candidate promotion
-- EXECUTION: CONTROLLED_MANUAL
-- IDEMPOTENCY: NOT_ASSUMED

CREATE TABLE CONTRACT_CANDIDATE_CONFIRMATION (
    CONFIRMATION_ID VARCHAR(36) NOT NULL,
    PROJECT_ID VARCHAR(36) NOT NULL,
    CANDIDATE_ID VARCHAR(36) NOT NULL,
    BASE_CANDIDATE_VERSION_NO BIGINT NOT NULL,
    RESULT_CANDIDATE_VERSION_NO BIGINT NOT NULL,
    SOURCE_FILE_ID VARCHAR(36) NOT NULL,
    SOURCE_PARSE_RESULT_ID VARCHAR(36) NOT NULL,
    SOURCE_ROLE_DECISION_ID VARCHAR(36) NOT NULL,
    SOURCE_IDENTITY_DECISION_ID VARCHAR(36) NOT NULL,
    PAYLOAD_SCHEMA_VERSION INTEGER NOT NULL,
    PAYLOAD_FINGERPRINT VARCHAR(64) NOT NULL,
    CANONICAL_PAYLOAD_JSON CLOB NOT NULL,
    CONFIRMED_BY VARCHAR(36) NOT NULL,
    CONFIRMED_AT TIMESTAMP NOT NULL,
    SUPERSEDES_CONFIRMATION_ID VARCHAR(36),
    CREATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT PK_CONTRACT_CANDIDATE_CONFIRMATION PRIMARY KEY (CONFIRMATION_ID),
    CONSTRAINT UK_CONTRACT_CANDIDATE_CONFIRMATION_OWNER
        UNIQUE (CONFIRMATION_ID, PROJECT_ID, CANDIDATE_ID),
    CONSTRAINT UK_CONTRACT_CANDIDATE_CONFIRMATION_VERSION
        UNIQUE (CANDIDATE_ID, RESULT_CANDIDATE_VERSION_NO),
    CONSTRAINT FK_CONTRACT_CANDIDATE_CONFIRMATION_CANDIDATE
        FOREIGN KEY (PROJECT_ID, CANDIDATE_ID, SOURCE_FILE_ID)
        REFERENCES CONTRACT_CANDIDATE (PROJECT_ID, ID, SOURCE_CONTRACT_FILE_ID),
    CONSTRAINT FK_CONTRACT_CANDIDATE_CONFIRMATION_PARSE
        FOREIGN KEY (SOURCE_PARSE_RESULT_ID, PROJECT_ID, SOURCE_FILE_ID)
        REFERENCES PROJECT_FILE_PARSE_RESULT (PARSE_RESULT_ID, PROJECT_ID, FILE_ID),
    CONSTRAINT FK_CONTRACT_CANDIDATE_CONFIRMATION_ROLE
        FOREIGN KEY (SOURCE_ROLE_DECISION_ID, PROJECT_ID, SOURCE_FILE_ID, SOURCE_PARSE_RESULT_ID)
        REFERENCES PROJECT_FILE_ROLE_DECISION (DECISION_ID, PROJECT_ID, FILE_ID, PARSE_RESULT_ID),
    CONSTRAINT FK_CONTRACT_CANDIDATE_CONFIRMATION_IDENTITY
        FOREIGN KEY (SOURCE_IDENTITY_DECISION_ID, PROJECT_ID, SOURCE_FILE_ID, SOURCE_PARSE_RESULT_ID)
        REFERENCES PROJECT_FILE_IDENTITY_DECISION (DECISION_ID, PROJECT_ID, FILE_ID, PARSE_RESULT_ID),
    CONSTRAINT FK_CONTRACT_CANDIDATE_CONFIRMATION_ACTOR
        FOREIGN KEY (CONFIRMED_BY) REFERENCES SYS_USER (ID),
    CONSTRAINT FK_CONTRACT_CANDIDATE_CONFIRMATION_SUPERSEDES
        FOREIGN KEY (SUPERSEDES_CONFIRMATION_ID, PROJECT_ID, CANDIDATE_ID)
        REFERENCES CONTRACT_CANDIDATE_CONFIRMATION (CONFIRMATION_ID, PROJECT_ID, CANDIDATE_ID),
    CONSTRAINT CK_CONTRACT_CANDIDATE_CONFIRMATION_VERSION CHECK
        (BASE_CANDIDATE_VERSION_NO >= 0 AND RESULT_CANDIDATE_VERSION_NO = BASE_CANDIDATE_VERSION_NO + 1),
    CONSTRAINT CK_CONTRACT_CANDIDATE_CONFIRMATION_HASH CHECK (LENGTH(PAYLOAD_FINGERPRINT) = 64),
    CONSTRAINT CK_CONTRACT_CANDIDATE_CONFIRMATION_SCHEMA CHECK (PAYLOAD_SCHEMA_VERSION > 0),
    CONSTRAINT CK_CONTRACT_CANDIDATE_CONFIRMATION_TIME CHECK (CONFIRMED_AT <= CREATED_AT)
);

CREATE INDEX IDX_CONTRACT_CANDIDATE_CONFIRMATION_LATEST
    ON CONTRACT_CANDIDATE_CONFIRMATION (PROJECT_ID, CANDIDATE_ID, RESULT_CANDIDATE_VERSION_NO DESC);

ALTER TABLE CONTRACT_CANDIDATE ADD PROMOTED_CONFIRMATION_ID VARCHAR(36);
ALTER TABLE CONTRACT_CANDIDATE ADD
    CONSTRAINT FK_CONTRACT_CANDIDATE_PROMOTED_CONFIRMATION
    FOREIGN KEY (PROMOTED_CONFIRMATION_ID, PROJECT_ID, ID)
    REFERENCES CONTRACT_CANDIDATE_CONFIRMATION (CONFIRMATION_ID, PROJECT_ID, CANDIDATE_ID);
ALTER TABLE CONTRACT_CANDIDATE ADD
    CONSTRAINT CK_CONTRACT_CANDIDATE_DRAFT_CONFIRMATION CHECK
    (PROMOTION_STATE <> 'DRAFT' OR PROMOTED_CONFIRMATION_ID IS NULL);
CREATE INDEX IDX_CONTRACT_CANDIDATE_PROMOTED_CONFIRMATION
    ON CONTRACT_CANDIDATE (PROMOTED_CONFIRMATION_ID, PROJECT_ID, ID);
