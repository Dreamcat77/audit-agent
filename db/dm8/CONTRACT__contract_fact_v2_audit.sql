-- DECIMAL(20,4) retains the historical 16 integer digits of DECIMAL(18,2).
-- Java business validation continues to restrict monetary values to two
-- meaningful decimals; this change prevents valid quantity/unit-price evidence
-- from being silently rounded while crossing durable candidate storage.
ALTER TABLE PROJECT_EXTRACTION_RESULT MODIFY VALUE_AMOUNT DECIMAL(20,4);
ALTER TABLE CONTRACT_CANDIDATE_LINE_ITEM MODIFY UNIT_PRICE DECIMAL(20,4);

CREATE TABLE PROJECT_FACT_EXTRACTION_REJECTION (
    REJECTION_ID VARCHAR(36) NOT NULL,
    ATTEMPT_ID VARCHAR(36) NOT NULL,
    ATTEMPT_NO INT NOT NULL,
    SCOPE VARCHAR(32) NOT NULL,
    PROVIDER_ORDINAL INT NOT NULL,
    STAGE VARCHAR(32) NOT NULL,
    REASON_CODE VARCHAR(64) NOT NULL,
    SAFE_SHAPE_HASH VARCHAR(64) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT PK_PROJECT_FACT_EXTRACTION_REJECTION PRIMARY KEY (REJECTION_ID),
    CONSTRAINT UK_PROJECT_FACT_EXTRACTION_REJECTION
        UNIQUE (ATTEMPT_ID, ATTEMPT_NO, SCOPE, PROVIDER_ORDINAL),
    CONSTRAINT FK_PROJECT_FACT_EXTRACTION_REJECTION FOREIGN KEY (ATTEMPT_ID)
        REFERENCES PROJECT_FACT_EXTRACTION_ATTEMPT (ATTEMPT_ID),
    CONSTRAINT CK_PROJECT_FACT_REJECTION_SCOPE
        CHECK (SCOPE IN ('CORE','LINE_ITEMS','AWARD')),
    CONSTRAINT CK_PROJECT_FACT_REJECTION_STAGE
        CHECK (STAGE IN ('TYPED_SCHEMA','SCOPE','EVIDENCE','IDENTITY')),
    CONSTRAINT CK_PROJECT_FACT_REJECTION_ORDINAL
        CHECK (ATTEMPT_NO > 0 AND PROVIDER_ORDINAL > 0)
);

CREATE INDEX IX_PROJECT_FACT_REJECTION_ATTEMPT
    ON PROJECT_FACT_EXTRACTION_REJECTION (ATTEMPT_ID, ATTEMPT_NO, SCOPE, PROVIDER_ORDINAL);

CREATE TABLE CONTRACT_MODEL_CALL_AUDIT (
    CALL_AUDIT_ID VARCHAR(36) NOT NULL,
    FACT_EXTRACTION_ATTEMPT_ID VARCHAR(36),
    REVIEW_STEP_ATTEMPT_ID VARCHAR(36),
    ATTEMPT_NO INT NOT NULL,
    SCOPE VARCHAR(32),
    CALL_ORDINAL INT NOT NULL,
    PHASE VARCHAR(32) NOT NULL,
    REQUEST_FINGERPRINT VARCHAR(64) NOT NULL,
    PROVIDER VARCHAR(100) NOT NULL,
    MODEL_NAME VARCHAR(200) NOT NULL,
    OUTCOME VARCHAR(32) NOT NULL,
    SAFE_REASON VARCHAR(64),
    DURATION_MS BIGINT NOT NULL,
    FINISH_REASON VARCHAR(64),
    PROMPT_TOKENS INT,
    COMPLETION_TOKENS INT,
    TOTAL_TOKENS INT,
    BATCH_STATUS VARCHAR(32),
    CREATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT PK_CONTRACT_MODEL_CALL_AUDIT PRIMARY KEY (CALL_AUDIT_ID),
    CONSTRAINT UK_CONTRACT_MODEL_CALL_FACT
        UNIQUE (FACT_EXTRACTION_ATTEMPT_ID, ATTEMPT_NO, SCOPE, CALL_ORDINAL),
    CONSTRAINT UK_CONTRACT_MODEL_CALL_REVIEW
        UNIQUE (REVIEW_STEP_ATTEMPT_ID, ATTEMPT_NO, CALL_ORDINAL),
    CONSTRAINT FK_CONTRACT_MODEL_CALL_FACT FOREIGN KEY (FACT_EXTRACTION_ATTEMPT_ID)
        REFERENCES PROJECT_FACT_EXTRACTION_ATTEMPT (ATTEMPT_ID),
    CONSTRAINT FK_CONTRACT_MODEL_CALL_REVIEW FOREIGN KEY (REVIEW_STEP_ATTEMPT_ID)
        REFERENCES CONTRACT_REVIEW_STEP_ATTEMPT (ATTEMPT_ID),
    CONSTRAINT CK_CONTRACT_MODEL_CALL_OWNER CHECK (
        (FACT_EXTRACTION_ATTEMPT_ID IS NOT NULL AND REVIEW_STEP_ATTEMPT_ID IS NULL)
        OR
        (FACT_EXTRACTION_ATTEMPT_ID IS NULL AND REVIEW_STEP_ATTEMPT_ID IS NOT NULL)
    ),
    CONSTRAINT CK_CONTRACT_MODEL_CALL_FACT_SCOPE CHECK (
        (FACT_EXTRACTION_ATTEMPT_ID IS NOT NULL
            AND SCOPE IN ('CORE','LINE_ITEMS','AWARD')
            AND BATCH_STATUS IN ('EMPTY','PARTIAL','COMPLETE','FAILED'))
        OR
        (REVIEW_STEP_ATTEMPT_ID IS NOT NULL AND SCOPE IS NULL AND BATCH_STATUS IS NULL)
    ),
    CONSTRAINT CK_CONTRACT_MODEL_CALL_PHASE CHECK (PHASE IN ('TRANSPORT','REPAIR')),
    CONSTRAINT CK_CONTRACT_MODEL_CALL_OUTCOME CHECK (OUTCOME IN ('SUCCEEDED','FAILED')),
    CONSTRAINT CK_CONTRACT_MODEL_CALL_COUNTS CHECK (
        ATTEMPT_NO > 0 AND CALL_ORDINAL > 0 AND DURATION_MS >= 0
        AND (PROMPT_TOKENS IS NULL OR PROMPT_TOKENS >= 0)
        AND (COMPLETION_TOKENS IS NULL OR COMPLETION_TOKENS >= 0)
        AND (TOTAL_TOKENS IS NULL OR TOTAL_TOKENS >= 0)
    )
);

CREATE INDEX IX_CONTRACT_MODEL_CALL_FACT
    ON CONTRACT_MODEL_CALL_AUDIT (FACT_EXTRACTION_ATTEMPT_ID, ATTEMPT_NO, SCOPE, CALL_ORDINAL);
CREATE INDEX IX_CONTRACT_MODEL_CALL_REVIEW
    ON CONTRACT_MODEL_CALL_AUDIT (REVIEW_STEP_ATTEMPT_ID, ATTEMPT_NO, CALL_ORDINAL);
