-- Independent upload-only contract analysis. No business DML, no change to formal CONTRACT/ReviewRun.
-- Execute only after target ownership/permissions and backup are verified.
CREATE TABLE CONTRACT_ANALYSIS_CASE (
    ID VARCHAR(36) NOT NULL,
    PROJECT_ID VARCHAR(36) NOT NULL,
    OWNER_ID VARCHAR(100) NOT NULL,
    INPUT_DIGEST VARCHAR(64) NOT NULL,
    STATUS VARCHAR(24) NOT NULL,
    ROW_VERSION BIGINT DEFAULT 0 NOT NULL,
    LEASE_TOKEN VARCHAR(64),
    LEASE_UNTIL TIMESTAMP,
    CREATED_AT TIMESTAMP NOT NULL,
    DEADLINE TIMESTAMP NOT NULL,
    SNAPSHOT_JSON CLOB NOT NULL,
    CONSTRAINT PK_CONTRACT_ANALYSIS_CASE PRIMARY KEY (ID),
    CONSTRAINT UQ_CONTRACT_ANALYSIS_SCOPE UNIQUE (PROJECT_ID, OWNER_ID),
    CONSTRAINT CK_CONTRACT_ANALYSIS_STATE CHECK (STATUS IN ('QUEUED','RUNNING','COMPLETED','PARTIAL','DATA_INSUFFICIENT','FAILED','UNKNOWN')),
    CONSTRAINT CK_CONTRACT_ANALYSIS_VERSION CHECK (ROW_VERSION >= 0),
    CONSTRAINT CK_CONTRACT_ANALYSIS_LEASE CHECK ((STATUS = 'RUNNING' AND LEASE_TOKEN IS NOT NULL AND LEASE_UNTIL IS NOT NULL) OR (STATUS <> 'RUNNING' AND LEASE_TOKEN IS NULL AND LEASE_UNTIL IS NULL))
);
CREATE INDEX IDX_CONTRACT_ANALYSIS_WORK ON CONTRACT_ANALYSIS_CASE (STATUS, LEASE_UNTIL, CREATED_AT);
CREATE INDEX IDX_CONTRACT_ANALYSIS_OWNER ON CONTRACT_ANALYSIS_CASE (OWNER_ID, CREATED_AT);
