-- V036: F07 招标文件关键词规则库及扫描命中记录。

CREATE TABLE PROCUREMENT_TENDER_RULE (
    ID                    VARCHAR(36) NOT NULL PRIMARY KEY,
    RULE_CODE             VARCHAR(64) NOT NULL,
    RULE_NAME             VARCHAR(200) NOT NULL,
    RISK_CATEGORY         VARCHAR(64) NOT NULL,
    MATCH_TYPE            VARCHAR(16) NOT NULL,
    MATCH_CONTENT         VARCHAR(2000) NOT NULL,
    RISK_LEVEL            VARCHAR(16) NOT NULL,
    REMEDIATION_SUGGESTION VARCHAR(2000) NOT NULL,
    ENABLED               INTEGER NOT NULL,
    CREATED_TIME          TIMESTAMP NOT NULL,
    UPDATED_TIME          TIMESTAMP NOT NULL,
    CONSTRAINT UK_PROC_TENDER_RULE_CODE UNIQUE (RULE_CODE),
    CONSTRAINT CK_PROC_TENDER_RULE_MATCH_TYPE CHECK (MATCH_TYPE IN ('KEYWORD', 'REGEX')),
    CONSTRAINT CK_PROC_TENDER_RULE_LEVEL CHECK (RISK_LEVEL IN ('CRITICAL', 'WARNING', 'INFO')),
    CONSTRAINT CK_PROC_TENDER_RULE_ENABLED CHECK (ENABLED IN (0, 1))
);

CREATE TABLE PROCUREMENT_TENDER_FINDING (
    ID                    VARCHAR(36) NOT NULL PRIMARY KEY,
    PROJECT_ID            VARCHAR(36) NOT NULL,
    REVIEW_ID             VARCHAR(36) NOT NULL,
    RULE_CODE             VARCHAR(64) NOT NULL,
    RULE_NAME             VARCHAR(200) NOT NULL,
    RISK_CATEGORY         VARCHAR(64) NOT NULL,
    RISK_LEVEL            VARCHAR(16) NOT NULL,
    MATCHED_TEXT          VARCHAR(1000) NOT NULL,
    SOURCE_LOCATOR        VARCHAR(500) NOT NULL,
    PAGE_NUMBER           INTEGER,
    REMEDIATION_SUGGESTION VARCHAR(2000) NOT NULL,
    CREATED_TIME          TIMESTAMP NOT NULL,
    CONSTRAINT FK_PROC_TENDER_FINDING_PROJECT FOREIGN KEY (PROJECT_ID)
        REFERENCES PROCUREMENT_DEMAND (ID),
    CONSTRAINT FK_PROC_TENDER_FINDING_REVIEW FOREIGN KEY (REVIEW_ID)
        REFERENCES PROCUREMENT_TENDER_DOCUMENT (ID),
    CONSTRAINT CK_PROC_TENDER_FINDING_LEVEL CHECK (RISK_LEVEL IN ('CRITICAL', 'WARNING', 'INFO')),
    CONSTRAINT CK_PROC_TENDER_FINDING_PAGE CHECK (PAGE_NUMBER IS NULL OR PAGE_NUMBER >= 1)
);

CREATE INDEX IDX_PROC_TENDER_FINDING_REVIEW
    ON PROCUREMENT_TENDER_FINDING (PROJECT_ID, REVIEW_ID, CREATED_TIME);
CREATE INDEX IDX_PROC_TENDER_RULE_ENABLED
    ON PROCUREMENT_TENDER_RULE (ENABLED, RULE_CODE);

COMMENT ON TABLE PROCUREMENT_TENDER_RULE IS 'F07 招标文件合规审查规则库';
COMMENT ON TABLE PROCUREMENT_TENDER_FINDING IS 'F07 招标文件规则扫描命中记录';
COMMENT ON COLUMN PROCUREMENT_TENDER_FINDING.MATCHED_TEXT IS '命中的招标文件原文片段';
COMMENT ON COLUMN PROCUREMENT_TENDER_FINDING.SOURCE_LOCATOR IS '原文定位，如 docx/body/paragraph:18 或 pdf/page:3';

