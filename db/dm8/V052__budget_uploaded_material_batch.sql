-- Uploaded files are the business input. No preloaded approval data is required.
-- Additive workflow/evidence storage; existing F01 amounts and history stay intact.
CREATE TABLE BUDGET_MATERIAL_BATCH (
    ID VARCHAR(36) NOT NULL PRIMARY KEY,
    ACTOR_ID VARCHAR(64) NOT NULL,
    BUDGET_YEAR VARCHAR(16),
    DEPARTMENT_CODE VARCHAR(64),
    MEMBERS_JSON CLOB NOT NULL,
    MEMBER_COUNT INT NOT NULL,
    STATUS VARCHAR(20) NOT NULL,
    LEASE_TOKEN VARCHAR(36),
    LEASE_UNTIL TIMESTAMP,
    CREATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT CK_BUDGET_BATCH_STATUS CHECK (STATUS IN ('OPEN','PROCESSING','REVIEWED'))
);
CREATE INDEX IX_BUDGET_BATCH_PENDING ON BUDGET_MATERIAL_BATCH(STATUS,LEASE_UNTIL,CREATED_AT);
CREATE TABLE BUDGET_MATERIAL_SOURCE (
    TASK_ID VARCHAR(36) NOT NULL PRIMARY KEY,
    BATCH_ID VARCHAR(36) NOT NULL,
    FACTS_JSON CLOB,
    RESULT_JSON CLOB,
    CONSTRAINT FK_BUDGET_SOURCE_TASK FOREIGN KEY (TASK_ID) REFERENCES BUDGET_REVIEW_TASK(ID),
    CONSTRAINT FK_BUDGET_SOURCE_BATCH FOREIGN KEY (BATCH_ID) REFERENCES BUDGET_MATERIAL_BATCH(ID)
);
CREATE INDEX IX_BUDGET_SOURCE_BATCH ON BUDGET_MATERIAL_SOURCE(BATCH_ID,TASK_ID);
