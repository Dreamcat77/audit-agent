-- Additive only. Catalog and backup gates required; never reapply a partial schema.
CREATE TABLE PROJECT_FILE_PROCESSING_JOB (
    JOB_ID VARCHAR(36) NOT NULL,
    PROJECT_ID VARCHAR(36) NOT NULL,
    FILE_ID VARCHAR(36) NOT NULL,
    FILE_SHA256 VARCHAR(64) NOT NULL,
    ACTOR_ID VARCHAR(36) NOT NULL,
    REQUEST_ID VARCHAR(128) NOT NULL,
    TRACE_ID VARCHAR(128) NOT NULL,
    SOURCE_IP VARCHAR(128),
    STATUS VARCHAR(16) NOT NULL,
    ATTEMPT_NO INT DEFAULT 0 NOT NULL,
    LEASE_TOKEN VARCHAR(36),
    LEASE_UNTIL TIMESTAMP,
    REASON_CODE VARCHAR(64),
    PARSE_RESULT_ID VARCHAR(36),
    CREATED_AT TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT PK_PF_PROCESSING_JOB PRIMARY KEY (JOB_ID),
    CONSTRAINT UK_PF_PROCESSING_FILE UNIQUE (FILE_ID),
    CONSTRAINT FK_PF_PROCESSING_FILE FOREIGN KEY (PROJECT_ID,FILE_ID) REFERENCES PROJECT_FILE(PROJECT_ID,ID),
    CONSTRAINT FK_PF_PROCESSING_ACTOR FOREIGN KEY (ACTOR_ID) REFERENCES SYS_USER(ID),
    CONSTRAINT FK_PF_PROCESSING_PARSE FOREIGN KEY (PARSE_RESULT_ID) REFERENCES PROJECT_FILE_PARSE_RESULT(PARSE_RESULT_ID),
    CONSTRAINT CK_PF_PROCESSING_STATE CHECK (STATUS IN ('QUEUED','PROCESSING','SUCCEEDED','FAILED','UNKNOWN')),
    CONSTRAINT CK_PF_PROCESSING_ATTEMPT CHECK (ATTEMPT_NO>=0),
    CONSTRAINT CK_PF_PROCESSING_LEASE CHECK (
        (STATUS='PROCESSING' AND LEASE_TOKEN IS NOT NULL AND LEASE_UNTIL IS NOT NULL)
        OR (STATUS<>'PROCESSING' AND LEASE_TOKEN IS NULL AND LEASE_UNTIL IS NULL)),
    CONSTRAINT CK_PF_PROCESSING_SHA CHECK (LENGTH(FILE_SHA256)=64)
);
CREATE INDEX IDX_PF_PROCESSING_QUEUE ON PROJECT_FILE_PROCESSING_JOB(STATUS,CREATED_AT,JOB_ID);
CREATE INDEX IDX_PF_PROCESSING_PROJECT ON PROJECT_FILE_PROCESSING_JOB(PROJECT_ID,FILE_ID);
CREATE TABLE PROJECT_FILE_PROCESSING_ATTEMPT (
    JOB_ID VARCHAR(36) NOT NULL,
    ATTEMPT_NO INT NOT NULL,
    LEASE_TOKEN VARCHAR(36) NOT NULL,
    STATUS VARCHAR(16) NOT NULL,
    REASON_CODE VARCHAR(64),
    STARTED_AT TIMESTAMP NOT NULL,
    COMPLETED_AT TIMESTAMP,
    CONSTRAINT PK_PF_PROCESSING_ATTEMPT PRIMARY KEY (JOB_ID,ATTEMPT_NO),
    CONSTRAINT UK_PF_PROCESSING_LEASE UNIQUE (LEASE_TOKEN),
    CONSTRAINT FK_PF_PROCESSING_JOB FOREIGN KEY (JOB_ID) REFERENCES PROJECT_FILE_PROCESSING_JOB(JOB_ID),
    CONSTRAINT CK_PF_PROCESSING_ATT_STATE CHECK (STATUS IN ('PROCESSING','SUCCEEDED','FAILED','UNKNOWN','EXPIRED','DEFERRED'))
);
