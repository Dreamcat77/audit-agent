-- V035: F07 招标文件上传与文本解析记录。

CREATE TABLE PROCUREMENT_TENDER_DOCUMENT (
    ID                VARCHAR(36) NOT NULL PRIMARY KEY,
    PROJECT_ID        VARCHAR(36) NOT NULL,
    FILE_NAME         VARCHAR(500) NOT NULL,
    FILE_EXTENSION    VARCHAR(16) NOT NULL,
    CONTENT_TYPE      VARCHAR(200) NOT NULL,
    FILE_SIZE         BIGINT NOT NULL,
    SHA256            VARCHAR(64) NOT NULL,
    STORAGE_KEY       VARCHAR(64) NOT NULL,
    STATUS            VARCHAR(32) NOT NULL,
    PARSE_METHOD      VARCHAR(32),
    PARSE_ENGINE      VARCHAR(100),
    PARSE_CONFIDENCE  DECIMAL(5,4),
    PAGE_COUNT        INTEGER,
    PARSED_CONTENT    CLOB,
    PARSE_ERROR       VARCHAR(500),
    CREATED_BY        VARCHAR(100),
    CREATED_TIME      TIMESTAMP NOT NULL,
    UPDATED_TIME      TIMESTAMP NOT NULL,
    CONSTRAINT FK_PROC_TENDER_DOCUMENT_PROJECT FOREIGN KEY (PROJECT_ID)
        REFERENCES PROCUREMENT_DEMAND (ID),
    CONSTRAINT CK_PROC_TENDER_DOCUMENT_STATUS CHECK (STATUS IN ('UPLOADING', 'AVAILABLE', 'PARSE_FAILED')),
    CONSTRAINT CK_PROC_TENDER_DOCUMENT_METHOD CHECK (
        PARSE_METHOD IS NULL OR PARSE_METHOD IN ('DOCX_TEXT', 'PDF_TEXT', 'OCR')),
    CONSTRAINT CK_PROC_TENDER_DOCUMENT_CONF CHECK (
        PARSE_CONFIDENCE IS NULL OR (PARSE_CONFIDENCE >= 0 AND PARSE_CONFIDENCE <= 1)),
    CONSTRAINT CK_PROC_TENDER_DOCUMENT_SIZE CHECK (FILE_SIZE > 0),
    CONSTRAINT CK_PROC_TENDER_DOCUMENT_PAGE CHECK (PAGE_COUNT IS NULL OR PAGE_COUNT >= 0)
);

CREATE INDEX IDX_PROC_TENDER_DOCUMENT_PROJECT_TIME
    ON PROCUREMENT_TENDER_DOCUMENT (PROJECT_ID, CREATED_TIME);

COMMENT ON TABLE PROCUREMENT_TENDER_DOCUMENT IS 'F07 招标文件及文本解析记录';
COMMENT ON COLUMN PROCUREMENT_TENDER_DOCUMENT.PARSED_CONTENT IS '解析全文及段落/页码定位 JSON';
COMMENT ON COLUMN PROCUREMENT_TENDER_DOCUMENT.PARSE_ERROR IS '解析失败的安全原因';

COMMIT;
