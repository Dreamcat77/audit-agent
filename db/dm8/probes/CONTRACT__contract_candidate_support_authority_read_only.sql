       CASE WHEN C.COLUMN_NAME IS NULL THEN 'NOT_APPLIED'
            WHEN C.DATA_TYPE = E.DATA_TYPE AND C.DATA_LENGTH = E.DATA_LENGTH
                 AND C.NULLABLE = 'Y' AND C.DATA_DEFAULT IS NULL
              THEN 'ALREADY_MATCHING'
            ELSE 'PARTIAL/SCHEMA_DRIFT' END EFFECT_STATUS
