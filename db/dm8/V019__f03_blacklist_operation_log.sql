-- F03 黑名单人工移除操作日志。
-- Integrated after V018; original f01 migration was V017.
-- 黑名单条目不物理删除，人工移除通过 IS_ACTIVE=FALSE 留存主数据，
-- 并在本表记录操作人、时间和移除原因。

CREATE TABLE BLACKLIST_SUPPLIER_OPERATION_LOG (
    ID                  VARCHAR(36)   NOT NULL PRIMARY KEY,
    BLACKLIST_ID        VARCHAR(36)   NOT NULL,
    OPERATION_TYPE      VARCHAR(32)   NOT NULL,
    OPERATOR_USER_ID    VARCHAR(64)   NOT NULL,
    OPERATOR_NAME       VARCHAR(100)  NOT NULL,
    OPERATION_REASON    VARCHAR(1000) NOT NULL,
    OPERATED_TIME       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CREATED_TIME        TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IDX_BLACKLIST_OPERATION_LOG_ENTRY
    ON BLACKLIST_SUPPLIER_OPERATION_LOG (BLACKLIST_ID, OPERATED_TIME);

COMMIT;
