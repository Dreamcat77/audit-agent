-- F06 询比价异常报警。
-- 询比价批次汇总与供应商报价明细均为可追溯事实，DM8 为正式事实源。

CREATE TABLE PROCUREMENT_QUOTE_CHECK (
    ID                        VARCHAR(36)   NOT NULL PRIMARY KEY,
    BATCH_ID                  VARCHAR(128)  NOT NULL,
    BUDGET_AMOUNT             DECIMAL(18,2) NOT NULL,
    AVERAGE_QUOTE             DECIMAL(18,2) NOT NULL,
    STANDARD_DEVIATION        DECIMAL(12,4) NOT NULL,
    COEFFICIENT_OF_VARIATION  DECIMAL(12,4) NOT NULL,
    HIGHLY_CONCENTRATED       SMALLINT      NOT NULL DEFAULT 0,
    RISK_LEVEL                VARCHAR(16)   NOT NULL,
    CREATED_TIME              TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CK_PROC_QUOTE_CHECK_BUDGET CHECK (BUDGET_AMOUNT >= 0),
    CONSTRAINT CK_PROC_QUOTE_CHECK_AVERAGE CHECK (AVERAGE_QUOTE >= 0),
    CONSTRAINT CK_PROC_QUOTE_CHECK_STDDEV CHECK (STANDARD_DEVIATION >= 0),
    CONSTRAINT CK_PROC_QUOTE_CHECK_CV CHECK (COEFFICIENT_OF_VARIATION >= 0),
    CONSTRAINT CK_PROC_QUOTE_CHECK_CONCENTRATED CHECK (HIGHLY_CONCENTRATED IN (0, 1)),
    CONSTRAINT CK_PROC_QUOTE_CHECK_RISK CHECK (RISK_LEVEL IN ('CRITICAL', 'WARNING', 'INFO'))
);

CREATE INDEX IDX_PROC_QUOTE_CHECK_BATCH
    ON PROCUREMENT_QUOTE_CHECK (BATCH_ID, CREATED_TIME);

CREATE TABLE PROCUREMENT_QUOTE_CHECK_ITEM (
    ID                  VARCHAR(36)   NOT NULL PRIMARY KEY,
    CHECK_ID            VARCHAR(36)   NOT NULL,
    BATCH_ID            VARCHAR(128)  NOT NULL,
    ROW_NUMBER          INT           NOT NULL,
    SUPPLIER_NAME       VARCHAR(200)  NOT NULL,
    QUOTE_AMOUNT        DECIMAL(18,2) NOT NULL,
    PRODUCT_DESCRIPTION VARCHAR(1000),
    OVER_BUDGET         SMALLINT      NOT NULL DEFAULT 0,
    OVER_BUDGET_AMOUNT  DECIMAL(18,2) NOT NULL DEFAULT 0,
    OVER_BUDGET_RATIO   DECIMAL(12,4) NOT NULL DEFAULT 0,
    DEVIATION_RATIO     DECIMAL(12,4) NOT NULL DEFAULT 0,
    IS_SUSPICIOUS       SMALLINT      NOT NULL DEFAULT 0,
    SUSPICIOUS_REASON   VARCHAR(200),
    CREATED_TIME        TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_PROC_QUOTE_ITEM_CHECK FOREIGN KEY (CHECK_ID)
        REFERENCES PROCUREMENT_QUOTE_CHECK (ID),
    CONSTRAINT CK_PROC_QUOTE_ITEM_ROW CHECK (ROW_NUMBER > 0),
    CONSTRAINT CK_PROC_QUOTE_ITEM_AMOUNT CHECK (QUOTE_AMOUNT >= 0),
    CONSTRAINT CK_PROC_QUOTE_ITEM_OVER CHECK (OVER_BUDGET IN (0, 1)),
    CONSTRAINT CK_PROC_QUOTE_ITEM_OVER_AMOUNT CHECK (OVER_BUDGET_AMOUNT >= 0),
    CONSTRAINT CK_PROC_QUOTE_ITEM_OVER_RATIO CHECK (OVER_BUDGET_RATIO >= 0),
    CONSTRAINT CK_PROC_QUOTE_ITEM_DEVIATION CHECK (DEVIATION_RATIO >= 0),
    CONSTRAINT CK_PROC_QUOTE_ITEM_SUSPICIOUS CHECK (IS_SUSPICIOUS IN (0, 1))
);

CREATE INDEX IDX_PROC_QUOTE_ITEM_CHECK
    ON PROCUREMENT_QUOTE_CHECK_ITEM (CHECK_ID, ROW_NUMBER);
CREATE INDEX IDX_PROC_QUOTE_ITEM_BATCH
    ON PROCUREMENT_QUOTE_CHECK_ITEM (BATCH_ID, ROW_NUMBER);

COMMENT ON TABLE PROCUREMENT_QUOTE_CHECK IS 'F06询比价异常分析批次汇总';
COMMENT ON TABLE PROCUREMENT_QUOTE_CHECK_ITEM IS 'F06询比价供应商报价分析明细';
COMMENT ON COLUMN PROCUREMENT_QUOTE_CHECK.COEFFICIENT_OF_VARIATION IS '报价离散系数CV，保留4位小数';
COMMENT ON COLUMN PROCUREMENT_QUOTE_CHECK_ITEM.OVER_BUDGET_RATIO IS '超预算比例，保留4位小数';

COMMIT;
