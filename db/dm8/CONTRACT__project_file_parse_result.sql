-- PURPOSE: immutable parse result history for ProjectFile
-- EXECUTION: CONTROLLED_MANUAL
-- IDEMPOTENCY: NOT_ASSUMED

CREATE TABLE PROJECT_FILE_PARSE_RESULT (
    PARSE_RESULT_ID VARCHAR(36) NOT NULL,
    PROJECT_ID VARCHAR(36) NOT NULL,
    FILE_ID VARCHAR(36) NOT NULL,
    FILE_SHA256 VARCHAR(64) NOT NULL,
    PARSE_VERSION INTEGER NOT NULL,
    PARSE_ORIGIN VARCHAR(32) NOT NULL,
    PARSE_STATUS VARCHAR(32) NOT NULL,
    PARSE_METHOD VARCHAR(32) NOT NULL,
    ENGINE VARCHAR(100) NOT NULL,
    ENGINE_VERSION VARCHAR(100),
    CANONICAL_TEXT CLOB,
    CANONICAL_TEXT_SHA256 VARCHAR(64),
    PAGE_COUNT INTEGER,
    DURATION_MS BIGINT,
    CONFIDENCE DECIMAL(5,4),
    SUPERSEDES_PARSE_RESULT_ID VARCHAR(36),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    COMPLETED_AT TIMESTAMP NOT NULL,
    VERSION_NO BIGINT DEFAULT 0 NOT NULL,
    CONSTRAINT PK_PROJECT_FILE_PARSE_RESULT PRIMARY KEY (PARSE_RESULT_ID),
    CONSTRAINT UK_PROJECT_FILE_PARSE_RESULT_FILE_VERSION UNIQUE (FILE_ID, PARSE_VERSION),
    CONSTRAINT UK_PROJECT_FILE_PARSE_RESULT_BINDING UNIQUE
        (PARSE_RESULT_ID, PROJECT_ID, FILE_ID, FILE_SHA256, PARSE_VERSION),
    CONSTRAINT FK_PROJECT_FILE_PARSE_RESULT_PROJECT FOREIGN KEY (PROJECT_ID) REFERENCES PROJECT (ID),
    CONSTRAINT FK_PROJECT_FILE_PARSE_RESULT_FILE FOREIGN KEY (PROJECT_ID, FILE_ID)
        REFERENCES PROJECT_FILE (PROJECT_ID, ID),
    CONSTRAINT FK_PROJECT_FILE_PARSE_RESULT_SUPERSEDES FOREIGN KEY (SUPERSEDES_PARSE_RESULT_ID)
        REFERENCES PROJECT_FILE_PARSE_RESULT (PARSE_RESULT_ID),
    CONSTRAINT CK_PROJECT_FILE_PARSE_RESULT_VERSION CHECK (PARSE_VERSION > 0 AND VERSION_NO >= 0),
    CONSTRAINT CK_PROJECT_FILE_PARSE_RESULT_ORIGIN CHECK (PARSE_ORIGIN IN ('CURRENT_PIPELINE', 'LEGACY_IMPORTED')),
    CONSTRAINT CK_PROJECT_FILE_PARSE_RESULT_STATUS CHECK (PARSE_STATUS IN ('PENDING', 'PARSED', 'UNSUPPORTED', 'FAILED', 'NOT_APPLICABLE')),
    CONSTRAINT CK_PROJECT_FILE_PARSE_RESULT_METHOD CHECK (PARSE_METHOD IN ('PDF_TEXT', 'DOCX_TEXT', 'OCR')),
    CONSTRAINT CK_PROJECT_FILE_PARSE_RESULT_CONFIDENCE CHECK (CONFIDENCE IS NULL OR (CONFIDENCE >= 0 AND CONFIDENCE <= 1)),
    CONSTRAINT CK_PROJECT_FILE_PARSE_RESULT_PAGE_COUNT CHECK (PAGE_COUNT IS NULL OR PAGE_COUNT >= 0),
    CONSTRAINT CK_PROJECT_FILE_PARSE_RESULT_DURATION CHECK (DURATION_MS IS NULL OR DURATION_MS >= 0),
    CONSTRAINT CK_PROJECT_FILE_PARSE_RESULT_COMPLETED CHECK (COMPLETED_AT >= CREATED_AT),
    CONSTRAINT CK_PROJECT_FILE_PARSE_RESULT_TEXT CHECK (
        (PARSE_STATUS = 'PARSED' AND CANONICAL_TEXT IS NOT NULL AND CANONICAL_TEXT_SHA256 IS NOT NULL)
        OR (PARSE_STATUS <> 'PARSED' AND CANONICAL_TEXT IS NULL AND CANONICAL_TEXT_SHA256 IS NULL)
    )
);

CREATE INDEX IDX_PROJECT_FILE_PARSE_RESULT_FILE ON PROJECT_FILE_PARSE_RESULT (FILE_ID, PARSE_VERSION DESC);
CREATE INDEX IDX_PROJECT_FILE_PARSE_RESULT_PROJECT ON PROJECT_FILE_PARSE_RESULT (PROJECT_ID, FILE_ID, CREATED_AT, PARSE_RESULT_ID);
