CREATE TABLE PROJECT_CONTRACT (
    PROJECT_ID VARCHAR(36) NOT NULL,
    CONTRACT_ID VARCHAR(36) NOT NULL,
    CANDIDATE_ID VARCHAR(36) NOT NULL,
    CREATED_BY VARCHAR(36) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_PROJECT_CONTRACT PRIMARY KEY (PROJECT_ID, CONTRACT_ID),
    CONSTRAINT UK_PROJECT_CONTRACT_CONTRACT UNIQUE (CONTRACT_ID),
    CONSTRAINT UK_PROJECT_CONTRACT_CANDIDATE UNIQUE (CANDIDATE_ID),
    CONSTRAINT FK_PROJECT_CONTRACT_PROJECT FOREIGN KEY (PROJECT_ID) REFERENCES PROJECT (ID),
    CONSTRAINT FK_PROJECT_CONTRACT_CONTRACT FOREIGN KEY (CONTRACT_ID) REFERENCES CONTRACT (ID),
    CONSTRAINT FK_PROJECT_CONTRACT_CREATED_BY FOREIGN KEY (CREATED_BY) REFERENCES SYS_USER (ID),
    CONSTRAINT FK_PROJECT_CONTRACT_CANDIDATE FOREIGN KEY (PROJECT_ID, CANDIDATE_ID)
        REFERENCES CONTRACT_CANDIDATE (PROJECT_ID, ID)
);

CREATE INDEX IDX_PROJECT_CONTRACT_PROJECT ON PROJECT_CONTRACT (PROJECT_ID, CREATED_AT, CONTRACT_ID);
