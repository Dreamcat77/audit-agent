CREATE TABLE PROJECT (
    ID VARCHAR(36) NOT NULL,
    NAME VARCHAR(200),
    PROJECT_NO VARCHAR(100),
    CATEGORY VARCHAR(100),
    CREATED_BY VARCHAR(36) NOT NULL,
    VERSION_NO BIGINT DEFAULT 0 NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_PROJECT PRIMARY KEY (ID),
    CONSTRAINT FK_PROJECT_CREATED_BY FOREIGN KEY (CREATED_BY) REFERENCES SYS_USER (ID),
    CONSTRAINT CK_PROJECT_VERSION CHECK (VERSION_NO >= 0)
);

CREATE TABLE PROJECT_FILE (
    ID VARCHAR(36) NOT NULL,
    PROJECT_ID VARCHAR(36) NOT NULL,
    PARENT_ARCHIVE_FILE_ID VARCHAR(36),
    NORMALIZED_RELATIVE_PATH VARCHAR(1024),
    ORIGINAL_FILENAME VARCHAR(255) NOT NULL,
    MEDIA_TYPE VARCHAR(128) NOT NULL,
    CATEGORY VARCHAR(32) NOT NULL,
    INGESTION_STATUS VARCHAR(32) NOT NULL,
    PARSE_STATUS VARCHAR(32) NOT NULL,
    STORAGE_KEY VARCHAR(64) NOT NULL,
    SHA256 VARCHAR(64) NOT NULL,
    SIZE_BYTES BIGINT NOT NULL,
    PARSED_TEXT CLOB,
    SAFE_REASON_CODE VARCHAR(64),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_PROJECT_FILE PRIMARY KEY (ID),
    CONSTRAINT UK_PROJECT_FILE_PROJECT_ID UNIQUE (PROJECT_ID, ID),
    CONSTRAINT UK_PROJECT_FILE_STORAGE_KEY UNIQUE (STORAGE_KEY),
    CONSTRAINT UK_PROJECT_FILE_PARENT_PATH UNIQUE (PARENT_ARCHIVE_FILE_ID, NORMALIZED_RELATIVE_PATH),
    CONSTRAINT FK_PROJECT_FILE_PROJECT FOREIGN KEY (PROJECT_ID) REFERENCES PROJECT (ID),
    CONSTRAINT FK_PROJECT_FILE_PARENT FOREIGN KEY (PROJECT_ID, PARENT_ARCHIVE_FILE_ID)
        REFERENCES PROJECT_FILE (PROJECT_ID, ID),
    CONSTRAINT CK_PROJECT_FILE_SIZE CHECK (SIZE_BYTES >= 0),
    CONSTRAINT CK_PROJECT_FILE_CATEGORY CHECK (CATEGORY IN
        ('PACKAGE','CONTRACT_BODY','AWARD_NOTICE','BID_RESPONSE','TENDER_DOCUMENT','SUPPLEMENT','OTHER','UNKNOWN')),
    CONSTRAINT CK_PROJECT_FILE_INGESTION CHECK (INGESTION_STATUS IN
        ('UPLOAD_PENDING','AVAILABLE','UPLOAD_FAILED')),
    CONSTRAINT CK_PROJECT_FILE_PARSE CHECK (PARSE_STATUS IN
        ('PENDING','PARSED','UNSUPPORTED','FAILED','NOT_APPLICABLE'))
);

CREATE TABLE CONTRACT_CANDIDATE (
    ID VARCHAR(36) NOT NULL,
    PROJECT_ID VARCHAR(36) NOT NULL,
    SOURCE_CONTRACT_FILE_ID VARCHAR(36) NOT NULL,
    CONTRACT_NO VARCHAR(200),
    CONTRACT_NAME VARCHAR(500),
    CONTRACT_TYPE VARCHAR(100),
    PARTY_A VARCHAR(500),
    PARTY_B VARCHAR(500),
    PARTY_B_CREDIT_CODE VARCHAR(64),
    CONTRACT_AMOUNT DECIMAL(18,2),
    AMOUNT_IN_WORDS VARCHAR(1000),
    AWARD_AMOUNT DECIMAL(18,2),
    AWARD_SUPPLIER VARCHAR(500),
    AWARD_SUPPLIER_CREDIT_CODE VARCHAR(64),
    PROMOTION_STATE VARCHAR(16) NOT NULL,
    VERSION_NO BIGINT DEFAULT 0 NOT NULL,
    PROMOTED_CONTRACT_ID VARCHAR(36),
    PROMOTED_BY VARCHAR(36),
    PROMOTED_AT TIMESTAMP,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_CONTRACT_CANDIDATE PRIMARY KEY (ID),
    CONSTRAINT UK_CONTRACT_CANDIDATE_PROJECT_ID UNIQUE (PROJECT_ID, ID),
    CONSTRAINT UK_CONTRACT_CANDIDATE_SOURCE UNIQUE (SOURCE_CONTRACT_FILE_ID),
    CONSTRAINT FK_CONTRACT_CANDIDATE_PROJECT FOREIGN KEY (PROJECT_ID) REFERENCES PROJECT (ID),
    CONSTRAINT FK_CONTRACT_CANDIDATE_SOURCE FOREIGN KEY (PROJECT_ID, SOURCE_CONTRACT_FILE_ID)
        REFERENCES PROJECT_FILE (PROJECT_ID, ID),
    CONSTRAINT FK_CONTRACT_CANDIDATE_PROMOTED_CONTRACT FOREIGN KEY (PROMOTED_CONTRACT_ID) REFERENCES CONTRACT (ID),
    CONSTRAINT FK_CONTRACT_CANDIDATE_PROMOTER FOREIGN KEY (PROMOTED_BY) REFERENCES SYS_USER (ID),
    CONSTRAINT CK_CONTRACT_CANDIDATE_VERSION CHECK (VERSION_NO >= 0),
    CONSTRAINT CK_CONTRACT_CANDIDATE_STATE CHECK (
        (PROMOTION_STATE = 'DRAFT' AND PROMOTED_CONTRACT_ID IS NULL AND PROMOTED_BY IS NULL AND PROMOTED_AT IS NULL)
        OR (PROMOTION_STATE = 'PROMOTED' AND PROMOTED_CONTRACT_ID IS NOT NULL AND PROMOTED_BY IS NOT NULL AND PROMOTED_AT IS NOT NULL)
    )
);

CREATE TABLE PROJECT_EXTRACTION_RESULT (
    ID VARCHAR(36) NOT NULL,
    PROJECT_ID VARCHAR(36) NOT NULL,
    SOURCE_FILE_ID VARCHAR(36) NOT NULL,
    CANDIDATE_ID VARCHAR(36),
    EXTRACTION_KEY VARCHAR(64) NOT NULL,
    EXTRACTION_VERSION VARCHAR(64) NOT NULL,
    FACT_TYPE VARCHAR(64) NOT NULL,
    GROUP_KEY VARCHAR(200),
    VALUE_TEXT VARCHAR(2000),
    NORMALIZED_VALUE VARCHAR(2000),
    VALUE_AMOUNT DECIMAL(18,2),
    SOURCE_TEXT VARCHAR(240) NOT NULL,
    PAGE_NUMBER INTEGER,
    PARAGRAPH_INDEX INTEGER,
    SOURCE_LOCATOR VARCHAR(500) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_PROJECT_EXTRACTION_RESULT PRIMARY KEY (ID),
    CONSTRAINT UK_PROJECT_EXTRACTION_KEY UNIQUE (EXTRACTION_KEY),
    CONSTRAINT FK_PROJECT_EXTRACTION_PROJECT FOREIGN KEY (PROJECT_ID) REFERENCES PROJECT (ID),
    CONSTRAINT FK_PROJECT_EXTRACTION_SOURCE FOREIGN KEY (PROJECT_ID, SOURCE_FILE_ID)
        REFERENCES PROJECT_FILE (PROJECT_ID, ID),
    CONSTRAINT FK_PROJECT_EXTRACTION_CANDIDATE FOREIGN KEY (PROJECT_ID, CANDIDATE_ID)
        REFERENCES CONTRACT_CANDIDATE (PROJECT_ID, ID)
);

CREATE TABLE CONTRACT_CANDIDATE_LINE_ITEM (
    ID VARCHAR(36) NOT NULL,
    PROJECT_ID VARCHAR(36) NOT NULL,
    CANDIDATE_ID VARCHAR(36) NOT NULL,
    ITEM_KEY VARCHAR(200),
    ITEM_NAME VARCHAR(500),
    QUANTITY DECIMAL(18,4),
    UNIT_PRICE DECIMAL(18,2),
    DECLARED_AMOUNT DECIMAL(18,2),
    SORT_NO INTEGER NOT NULL,
    CONSTRAINT PK_CONTRACT_CANDIDATE_LINE PRIMARY KEY (ID),
    CONSTRAINT FK_CONTRACT_CANDIDATE_LINE_OWNER FOREIGN KEY (PROJECT_ID, CANDIDATE_ID)
        REFERENCES CONTRACT_CANDIDATE (PROJECT_ID, ID),
    CONSTRAINT CK_CONTRACT_CANDIDATE_LINE_SORT CHECK (SORT_NO >= 0)
);

CREATE INDEX IDX_PROJECT_CREATED ON PROJECT (CREATED_AT, ID);
CREATE INDEX IDX_PROJECT_FILE_PROJECT ON PROJECT_FILE (PROJECT_ID, CREATED_AT, ID);
CREATE INDEX IDX_PROJECT_EXTRACTION_SOURCE ON PROJECT_EXTRACTION_RESULT (PROJECT_ID, SOURCE_FILE_ID, SOURCE_LOCATOR, ID);
CREATE INDEX IDX_PROJECT_EXTRACTION_CANDIDATE ON PROJECT_EXTRACTION_RESULT (PROJECT_ID, CANDIDATE_ID, SOURCE_LOCATOR, ID);
CREATE INDEX IDX_CONTRACT_CANDIDATE_PROJECT ON CONTRACT_CANDIDATE (PROJECT_ID, CREATED_AT, ID);
