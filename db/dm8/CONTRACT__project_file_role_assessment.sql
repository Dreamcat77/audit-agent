-- MIGRATION-NAMESPACE: CONTRACT
-- MIGRATION-ID: project-file-role-assessment
-- DEPENDS-ON: project-file-parse-result
-- PURPOSE: durable machine role assessment, evidence, and human decision history
-- EXECUTION: CONTROLLED_MANUAL
-- IDEMPOTENCY: NOT_ASSUMED

CREATE TABLE PROJECT_FILE_ROLE_ASSESSMENT (
    ASSESSMENT_ID VARCHAR(36) NOT NULL,
    PROJECT_ID VARCHAR(36) NOT NULL,
    FILE_ID VARCHAR(36) NOT NULL,
    FILE_SHA256 VARCHAR(64) NOT NULL,
    PARSE_RESULT_ID VARCHAR(36) NOT NULL,
    PARSE_VERSION INTEGER NOT NULL,
    EXECUTION_STATUS VARCHAR(32) NOT NULL,
    PROPOSED_ROLE VARCHAR(32),
    CONFIDENCE DECIMAL(7,6),
    CONFLICT_FLAG SMALLINT DEFAULT 0 NOT NULL,
    ASSESSMENT_SOURCE VARCHAR(32) NOT NULL,
    ASSESSMENT_VERSION VARCHAR(100) NOT NULL,
    ROLE_POLICY_VERSION VARCHAR(100) NOT NULL,
    CANDIDATE_ROLES_JSON CLOB,
    PRECEDING_DETERMINISTIC_ASSESSMENT_ID VARCHAR(36),
    PRECEDING_ASSESSMENT_SOURCE VARCHAR(32),
    MODEL_PROVIDER VARCHAR(100),
    MODEL_NAME VARCHAR(100),
    MODEL_REVISION VARCHAR(100),
    PROMPT_VERSION VARCHAR(100),
    SCHEMA_VERSION VARCHAR(100),
    INPUT_FINGERPRINT VARCHAR(64) NOT NULL,
    ASSESSMENT_FENCE_KEY VARCHAR(64) NOT NULL,
    SAFE_REASON_CODE VARCHAR(100),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    STARTED_AT TIMESTAMP,
    COMPLETED_AT TIMESTAMP,
    ATTEMPT_NO INTEGER DEFAULT 0 NOT NULL,
    VERSION_NO BIGINT DEFAULT 0 NOT NULL,
    CONSTRAINT PK_PROJECT_FILE_ROLE_ASSESSMENT PRIMARY KEY (ASSESSMENT_ID),
    CONSTRAINT UK_PROJECT_FILE_ROLE_ASSESSMENT_BINDING UNIQUE
        (ASSESSMENT_ID, PROJECT_ID, FILE_ID, FILE_SHA256, PARSE_RESULT_ID, PARSE_VERSION),
    CONSTRAINT UK_PROJECT_FILE_ROLE_ASSESSMENT_SOURCE_BINDING UNIQUE
        (ASSESSMENT_ID, PROJECT_ID, FILE_ID, FILE_SHA256, PARSE_RESULT_ID, PARSE_VERSION, ASSESSMENT_SOURCE),
    CONSTRAINT UK_PROJECT_FILE_ROLE_ASSESSMENT_FENCE UNIQUE (FILE_ID, ASSESSMENT_FENCE_KEY),
    CONSTRAINT FK_PROJECT_FILE_ROLE_ASSESSMENT_PROJECT FOREIGN KEY (PROJECT_ID) REFERENCES PROJECT (ID),
    CONSTRAINT FK_PROJECT_FILE_ROLE_ASSESSMENT_FILE FOREIGN KEY (PROJECT_ID, FILE_ID)
        REFERENCES PROJECT_FILE (PROJECT_ID, ID),
    CONSTRAINT FK_PROJECT_FILE_ROLE_ASSESSMENT_PARSE FOREIGN KEY
        (PARSE_RESULT_ID, PROJECT_ID, FILE_ID, FILE_SHA256, PARSE_VERSION)
        REFERENCES PROJECT_FILE_PARSE_RESULT
        (PARSE_RESULT_ID, PROJECT_ID, FILE_ID, FILE_SHA256, PARSE_VERSION),
    CONSTRAINT FK_PROJECT_FILE_ROLE_ASSESSMENT_PRECEDING FOREIGN KEY
        (PRECEDING_DETERMINISTIC_ASSESSMENT_ID, PROJECT_ID, FILE_ID, FILE_SHA256, PARSE_RESULT_ID, PARSE_VERSION,
            PRECEDING_ASSESSMENT_SOURCE)
        REFERENCES PROJECT_FILE_ROLE_ASSESSMENT
        (ASSESSMENT_ID, PROJECT_ID, FILE_ID, FILE_SHA256, PARSE_RESULT_ID, PARSE_VERSION, ASSESSMENT_SOURCE),
    CONSTRAINT CK_PROJECT_FILE_ROLE_ASSESSMENT_EXECUTION CHECK
        (EXECUTION_STATUS IN ('PENDING', 'RUNNING', 'COMPLETED', 'FAILED', 'UNKNOWN')),
    CONSTRAINT CK_PROJECT_FILE_ROLE_ASSESSMENT_SOURCE CHECK
        (ASSESSMENT_SOURCE IN ('MACHINE_DETERMINISTIC', 'MACHINE_AI')),
    CONSTRAINT CK_PROJECT_FILE_ROLE_ASSESSMENT_ROLE CHECK
        (PROPOSED_ROLE IS NULL OR PROPOSED_ROLE IN
            ('CONTRACT_BODY', 'AWARD_NOTICE', 'TENDER_DOCUMENT', 'BID_RESPONSE', 'SUPPLEMENT', 'OTHER', 'UNKNOWN')),
    CONSTRAINT CK_PROJECT_FILE_ROLE_ASSESSMENT_CONFIDENCE CHECK
        (CONFIDENCE IS NULL OR (CONFIDENCE >= 0 AND CONFIDENCE <= 1)),
    CONSTRAINT CK_PROJECT_FILE_ROLE_ASSESSMENT_CONFLICT CHECK (CONFLICT_FLAG IN (0, 1)),
    CONSTRAINT CK_PROJECT_FILE_ROLE_ASSESSMENT_VERSION CHECK
        (PARSE_VERSION > 0 AND ATTEMPT_NO >= 0 AND VERSION_NO >= 0),
    CONSTRAINT CK_PROJECT_FILE_ROLE_ASSESSMENT_HASHES CHECK
        (LENGTH(FILE_SHA256) = 64 AND LENGTH(INPUT_FINGERPRINT) = 64),
    CONSTRAINT CK_PROJECT_FILE_ROLE_ASSESSMENT_FENCE CHECK (
        (EXECUTION_STATUS IN ('PENDING', 'RUNNING', 'UNKNOWN')
            AND ASSESSMENT_FENCE_KEY = INPUT_FINGERPRINT)
        OR
        (EXECUTION_STATUS IN ('COMPLETED', 'FAILED')
            AND ASSESSMENT_FENCE_KEY = ASSESSMENT_ID)
    ),
    CONSTRAINT CK_PROJECT_FILE_ROLE_ASSESSMENT_PROVENANCE CHECK (
        (ASSESSMENT_SOURCE = 'MACHINE_DETERMINISTIC'
            AND PRECEDING_DETERMINISTIC_ASSESSMENT_ID IS NULL
            AND PRECEDING_ASSESSMENT_SOURCE IS NULL
            AND MODEL_PROVIDER IS NULL AND MODEL_NAME IS NULL AND MODEL_REVISION IS NULL
            AND PROMPT_VERSION IS NULL AND SCHEMA_VERSION IS NULL)
        OR
        (ASSESSMENT_SOURCE = 'MACHINE_AI'
            AND PRECEDING_DETERMINISTIC_ASSESSMENT_ID IS NOT NULL
            AND PRECEDING_ASSESSMENT_SOURCE = 'MACHINE_DETERMINISTIC'
            AND MODEL_PROVIDER IS NOT NULL AND MODEL_NAME IS NOT NULL AND MODEL_REVISION IS NOT NULL
            AND PROMPT_VERSION IS NOT NULL AND SCHEMA_VERSION IS NOT NULL)
    ),
    CONSTRAINT CK_PROJECT_FILE_ROLE_ASSESSMENT_STATE CHECK (
        (EXECUTION_STATUS = 'PENDING' AND PROPOSED_ROLE IS NULL AND CONFIDENCE IS NULL
            AND CONFLICT_FLAG = 0 AND CANDIDATE_ROLES_JSON IS NULL AND SAFE_REASON_CODE IS NULL
            AND STARTED_AT IS NULL AND COMPLETED_AT IS NULL AND ATTEMPT_NO = 0)
        OR
        (EXECUTION_STATUS = 'RUNNING' AND PROPOSED_ROLE IS NULL AND CONFIDENCE IS NULL
            AND CONFLICT_FLAG = 0 AND CANDIDATE_ROLES_JSON IS NULL AND SAFE_REASON_CODE IS NULL
            AND STARTED_AT IS NOT NULL AND COMPLETED_AT IS NULL AND ATTEMPT_NO >= 1)
        OR
        (EXECUTION_STATUS = 'COMPLETED' AND PROPOSED_ROLE IS NOT NULL AND CONFIDENCE IS NOT NULL
            AND CANDIDATE_ROLES_JSON IS NOT NULL AND STARTED_AT IS NOT NULL AND COMPLETED_AT IS NOT NULL
            AND ATTEMPT_NO >= 1)
        OR
        (EXECUTION_STATUS IN ('FAILED', 'UNKNOWN') AND PROPOSED_ROLE IS NULL AND CONFIDENCE IS NULL
            AND CONFLICT_FLAG = 0 AND CANDIDATE_ROLES_JSON IS NULL AND SAFE_REASON_CODE IS NOT NULL
            AND STARTED_AT IS NOT NULL AND COMPLETED_AT IS NOT NULL AND ATTEMPT_NO >= 1)
    ),
    CONSTRAINT CK_PROJECT_FILE_ROLE_ASSESSMENT_TIMES CHECK
        ((STARTED_AT IS NULL OR STARTED_AT >= CREATED_AT)
            AND (COMPLETED_AT IS NULL OR (STARTED_AT IS NOT NULL AND COMPLETED_AT >= STARTED_AT)))
);

CREATE TABLE PROJECT_FILE_ROLE_EVIDENCE (
    EVIDENCE_ID VARCHAR(36) NOT NULL,
    ASSESSMENT_ID VARCHAR(36) NOT NULL,
    PROJECT_ID VARCHAR(36) NOT NULL,
    FILE_ID VARCHAR(36) NOT NULL,
    FILE_SHA256 VARCHAR(64) NOT NULL,
    PARSE_RESULT_ID VARCHAR(36) NOT NULL,
    PARSE_VERSION INTEGER NOT NULL,
    ROLE VARCHAR(32) NOT NULL,
    SIGNAL_TYPE VARCHAR(32) NOT NULL,
    NORMALIZED_VALUE VARCHAR(500) NOT NULL,
    RULE_CODE VARCHAR(100) NOT NULL,
    WEIGHT DECIMAL(12,4) NOT NULL,
    SOURCE_LOCATOR VARCHAR(300) NOT NULL,
    CHAR_START INTEGER NOT NULL,
    CHAR_END INTEGER NOT NULL,
    TEXT_HASH VARCHAR(64) NOT NULL,
    BOUNDED_EXCERPT VARCHAR(500) NOT NULL,
    EXTRACTOR_VERSION VARCHAR(100) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_PROJECT_FILE_ROLE_EVIDENCE PRIMARY KEY (EVIDENCE_ID),
    CONSTRAINT UK_PROJECT_FILE_ROLE_EVIDENCE_SIGNAL UNIQUE (ASSESSMENT_ID, ROLE, RULE_CODE, SOURCE_LOCATOR),
    CONSTRAINT FK_PROJECT_FILE_ROLE_EVIDENCE_ASSESSMENT FOREIGN KEY
        (ASSESSMENT_ID, PROJECT_ID, FILE_ID, FILE_SHA256, PARSE_RESULT_ID, PARSE_VERSION)
        REFERENCES PROJECT_FILE_ROLE_ASSESSMENT
        (ASSESSMENT_ID, PROJECT_ID, FILE_ID, FILE_SHA256, PARSE_RESULT_ID, PARSE_VERSION),
    CONSTRAINT FK_PROJECT_FILE_ROLE_EVIDENCE_PARSE FOREIGN KEY (PARSE_RESULT_ID)
        REFERENCES PROJECT_FILE_PARSE_RESULT (PARSE_RESULT_ID),
    CONSTRAINT CK_PROJECT_FILE_ROLE_EVIDENCE_ROLE CHECK
        (ROLE IN ('CONTRACT_BODY', 'AWARD_NOTICE', 'TENDER_DOCUMENT', 'BID_RESPONSE', 'SUPPLEMENT', 'OTHER', 'UNKNOWN')),
    CONSTRAINT CK_PROJECT_FILE_ROLE_EVIDENCE_SIGNAL_TYPE CHECK
        (SIGNAL_TYPE IN ('TITLE', 'FRONT_MATTER', 'KEY_PHRASE', 'HEADING', 'STRUCTURE')),
    CONSTRAINT CK_PROJECT_FILE_ROLE_EVIDENCE_RANGE CHECK
        (PARSE_VERSION > 0 AND CHAR_START >= 0 AND CHAR_END > CHAR_START),
    CONSTRAINT CK_PROJECT_FILE_ROLE_EVIDENCE_WEIGHT CHECK (WEIGHT > 0),
    CONSTRAINT CK_PROJECT_FILE_ROLE_EVIDENCE_HASHES CHECK
        (LENGTH(FILE_SHA256) = 64 AND LENGTH(TEXT_HASH) = 64),
    CONSTRAINT CK_PROJECT_FILE_ROLE_EVIDENCE_EXCERPT CHECK (LENGTH(BOUNDED_EXCERPT) <= 160)
);

CREATE TABLE PROJECT_FILE_ROLE_DECISION (
    DECISION_ID VARCHAR(36) NOT NULL,
    PROJECT_ID VARCHAR(36) NOT NULL,
    FILE_ID VARCHAR(36) NOT NULL,
    FILE_SHA256 VARCHAR(64) NOT NULL,
    PARSE_RESULT_ID VARCHAR(36) NOT NULL,
    PARSE_VERSION INTEGER NOT NULL,
    ASSESSMENT_ID VARCHAR(36) NOT NULL,
    SELECTED_ROLE VARCHAR(32) NOT NULL,
    DECISION_STATUS VARCHAR(32) NOT NULL,
    DECIDED_BY VARCHAR(36) NOT NULL,
    DECIDED_AT TIMESTAMP NOT NULL,
    SUPERSEDES_DECISION_ID VARCHAR(36),
    REASON VARCHAR(500),
    VERSION_NO BIGINT NOT NULL,
    CONSTRAINT PK_PROJECT_FILE_ROLE_DECISION PRIMARY KEY (DECISION_ID),
    CONSTRAINT UK_PROJECT_FILE_ROLE_DECISION_VERSION UNIQUE (FILE_ID, VERSION_NO),
    CONSTRAINT UK_PROJECT_FILE_ROLE_DECISION_OWNERSHIP UNIQUE (DECISION_ID, PROJECT_ID, FILE_ID),
    CONSTRAINT FK_PROJECT_FILE_ROLE_DECISION_ASSESSMENT FOREIGN KEY
        (ASSESSMENT_ID, PROJECT_ID, FILE_ID, FILE_SHA256, PARSE_RESULT_ID, PARSE_VERSION)
        REFERENCES PROJECT_FILE_ROLE_ASSESSMENT
        (ASSESSMENT_ID, PROJECT_ID, FILE_ID, FILE_SHA256, PARSE_RESULT_ID, PARSE_VERSION),
    CONSTRAINT FK_PROJECT_FILE_ROLE_DECISION_DECIDED_BY FOREIGN KEY (DECIDED_BY)
        REFERENCES SYS_USER (ID),
    CONSTRAINT FK_PROJECT_FILE_ROLE_DECISION_SUPERSEDES FOREIGN KEY
        (SUPERSEDES_DECISION_ID, PROJECT_ID, FILE_ID)
        REFERENCES PROJECT_FILE_ROLE_DECISION (DECISION_ID, PROJECT_ID, FILE_ID),
    CONSTRAINT CK_PROJECT_FILE_ROLE_DECISION_ROLE CHECK
        (SELECTED_ROLE IN ('CONTRACT_BODY', 'AWARD_NOTICE', 'TENDER_DOCUMENT', 'BID_RESPONSE', 'SUPPLEMENT', 'OTHER', 'UNKNOWN')),
    CONSTRAINT CK_PROJECT_FILE_ROLE_DECISION_STATUS CHECK (DECISION_STATUS = 'CONFIRMED'),
    CONSTRAINT CK_PROJECT_FILE_ROLE_DECISION_VERSION CHECK (PARSE_VERSION > 0 AND VERSION_NO > 0),
    CONSTRAINT CK_PROJECT_FILE_ROLE_DECISION_HASH CHECK (LENGTH(FILE_SHA256) = 64),
    CONSTRAINT CK_PROJECT_FILE_ROLE_DECISION_SUPERSEDES CHECK
        (SUPERSEDES_DECISION_ID IS NULL OR SUPERSEDES_DECISION_ID <> DECISION_ID)
);

CREATE INDEX IDX_PROJECT_FILE_ROLE_ASSESSMENT_FILE
    ON PROJECT_FILE_ROLE_ASSESSMENT (FILE_ID, CREATED_AT DESC, ASSESSMENT_ID DESC);
CREATE INDEX IDX_PROJECT_FILE_ROLE_ASSESSMENT_PARSE
    ON PROJECT_FILE_ROLE_ASSESSMENT (PARSE_RESULT_ID, ASSESSMENT_SOURCE, CREATED_AT);
CREATE INDEX IDX_PROJECT_FILE_ROLE_EVIDENCE_ASSESSMENT
    ON PROJECT_FILE_ROLE_EVIDENCE (ASSESSMENT_ID, SOURCE_LOCATOR, EVIDENCE_ID);
CREATE INDEX IDX_PROJECT_FILE_ROLE_DECISION_FILE
    ON PROJECT_FILE_ROLE_DECISION (FILE_ID, VERSION_NO DESC, DECISION_ID DESC);
CREATE INDEX IDX_PROJECT_FILE_ROLE_DECISION_ASSESSMENT
    ON PROJECT_FILE_ROLE_DECISION (ASSESSMENT_ID, DECIDED_AT, DECISION_ID);
