-- V017: additive ProjectFile extraction provenance for PDFBox, POI, and OCR.
-- Existing rows remain valid because every new data column is nullable.

ALTER TABLE PROJECT_FILE ADD PARSE_METHOD VARCHAR(32);
ALTER TABLE PROJECT_FILE ADD PARSE_ENGINE VARCHAR(100);
ALTER TABLE PROJECT_FILE ADD PARSE_CONFIDENCE DECIMAL(5,4);
ALTER TABLE PROJECT_FILE ADD PAGE_COUNT INTEGER;
ALTER TABLE PROJECT_FILE ADD PARSE_DURATION_MS BIGINT;

ALTER TABLE PROJECT_FILE ADD CONSTRAINT CK_PROJECT_FILE_PARSE_METHOD CHECK (
    PARSE_METHOD IS NULL OR PARSE_METHOD IN ('PDF_TEXT', 'DOCX_TEXT', 'OCR')
);
ALTER TABLE PROJECT_FILE ADD CONSTRAINT CK_PROJECT_FILE_PARSE_CONF CHECK (
    PARSE_CONFIDENCE IS NULL OR (PARSE_CONFIDENCE >= 0 AND PARSE_CONFIDENCE <= 1)
);
ALTER TABLE PROJECT_FILE ADD CONSTRAINT CK_PROJECT_FILE_PAGE_COUNT CHECK (
    PAGE_COUNT IS NULL OR PAGE_COUNT >= 0
);
ALTER TABLE PROJECT_FILE ADD CONSTRAINT CK_PROJECT_FILE_PARSE_DURATION CHECK (
    PARSE_DURATION_MS IS NULL OR PARSE_DURATION_MS >= 0
);

COMMENT ON COLUMN PROJECT_FILE.PARSE_METHOD IS 'Extraction method: PDF_TEXT, DOCX_TEXT, or OCR.';
COMMENT ON COLUMN PROJECT_FILE.PARSE_ENGINE IS 'Safe parser/OCR engine identifier; never a secret or document text.';
COMMENT ON COLUMN PROJECT_FILE.PARSE_CONFIDENCE IS 'Optional normalized extraction confidence from 0 through 1.';
COMMENT ON COLUMN PROJECT_FILE.PAGE_COUNT IS 'Optional non-negative source page count reported by extraction.';
COMMENT ON COLUMN PROJECT_FILE.PARSE_DURATION_MS IS 'Optional non-negative extraction duration in milliseconds.';
