-- F01 material parsing and review facts.
-- Apply after V006__f01_budget_approval.sql.

CREATE TABLE BUDGET_REVIEW_TASK (
    ID                  VARCHAR(36)  NOT NULL PRIMARY KEY,
    FILE_NAME           VARCHAR(255) NOT NULL,
    CONTENT_TYPE        VARCHAR(100),
    FILE_SIZE           BIGINT       NOT NULL,
    TEMP_FILE_PATH      VARCHAR(1000),
    STATUS              VARCHAR(32)  NOT NULL,
    PARSED_LINE_COUNT   INT          DEFAULT 0,
    ERROR_DETAIL        VARCHAR(2000),
    CREATED_TIME        TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    UPDATED_TIME        TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE BUDGET_REVIEW_ITEM (
    ID                    VARCHAR(36)     NOT NULL PRIMARY KEY,
    TASK_ID               VARCHAR(36)     NOT NULL,
    ROW_NUMBER            INT,
    SUBJECT_CODE          VARCHAR(64),
    SUBJECT_NAME          VARCHAR(200),
    DECLARED_AMOUNT       DECIMAL(18,2),
    SUPPLIER_NAME         VARCHAR(200),
    APPROVAL_SUBJECT_CODE VARCHAR(64),
    APPROVAL_SUBJECT_NAME VARCHAR(200),
    APPROVAL_AMOUNT       DECIMAL(18,2),
    APPROVAL_SUPPLIER_NAME VARCHAR(200),
    MATCH_STATUS          VARCHAR(32)     NOT NULL,
    MATCH_METHOD          VARCHAR(32),
    MATCH_DISTANCE        INT,
    AMOUNT_STATUS         VARCHAR(32),
    DIFFERENCE_AMOUNT     DECIMAL(18,2),
    EXCEPTION_TYPE        VARCHAR(64),
    ERROR_DETAIL          VARCHAR(2000),
    CREATED_TIME          TIMESTAMP       DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IDX_BUDGET_REVIEW_ITEM_TASK
    ON BUDGET_REVIEW_ITEM (TASK_ID, ROW_NUMBER);
