-- Independent upload cases. Additive only. Apply through AutoCaseSchemaCheck.
-- Apply once using the approved migration process; existing objects must be catalog-checked,
-- never dropped/recreated to make this script run. Code rollback leaves these tables intact.
CREATE TABLE AUDIT_CASE (
 ID VARCHAR(36) NOT NULL PRIMARY KEY,
 OWNER_ID VARCHAR(128) NOT NULL,
 OPERATION_KEY VARCHAR(36) NOT NULL,
 FINGERPRINT VARCHAR(64) NOT NULL,
 STATUS VARCHAR(32) NOT NULL,
 ROW_VERSION BIGINT NOT NULL,
 LEASE_TOKEN VARCHAR(36) NOT NULL,
 LEASE_UNTIL TIMESTAMP NOT NULL,
 CREATED_AT TIMESTAMP NOT NULL,
 SNAPSHOT_JSON CLOB NOT NULL,
 CONSTRAINT UK_AUDIT_CASE_OPERATION UNIQUE (OWNER_ID,OPERATION_KEY),
 CONSTRAINT CK_AUDIT_CASE_VERSION CHECK (ROW_VERSION>=0),
 CONSTRAINT CK_AUDIT_CASE_STATUS CHECK (STATUS IN ('UPLOADING','QUEUED','RUNNING','COMPLETED','PARTIAL','DATA_INSUFFICIENT','FAILED','UNKNOWN'))
);
CREATE INDEX IX_AUDIT_CASE_PENDING ON AUDIT_CASE(STATUS,LEASE_UNTIL,CREATED_AT);
CREATE INDEX IX_AUDIT_CASE_OWNER ON AUDIT_CASE(OWNER_ID,CREATED_AT);
CREATE TABLE AUDIT_CASE_FILE (
 ID VARCHAR(36) NOT NULL PRIMARY KEY,
 CASE_ID VARCHAR(36) NOT NULL,
 FILE_ORDER INT NOT NULL,
 SHA256 VARCHAR(64) NOT NULL,
 STORAGE_KEY VARCHAR(64) NOT NULL,
 STATUS VARCHAR(32) NOT NULL,
 SNAPSHOT_JSON CLOB NOT NULL,
 CONSTRAINT FK_AUTO_FILE_CASE FOREIGN KEY (CASE_ID) REFERENCES AUDIT_CASE(ID),
 CONSTRAINT UK_AUTO_FILE_ORDER UNIQUE (CASE_ID,FILE_ORDER),
 CONSTRAINT UK_AUTO_FILE_CASE_ID UNIQUE (CASE_ID,ID),
 CONSTRAINT CK_AUTO_FILE_ORDER CHECK (FILE_ORDER>=0),
 CONSTRAINT CK_AUTO_FILE_STATUS CHECK (STATUS IN ('STAGING','STORED','PARSING','PARSED','CALLING','EXTRACTED','FAILED','UNKNOWN'))
);
CREATE TABLE AUDIT_FACT (
 ID VARCHAR(36) NOT NULL PRIMARY KEY,
 CASE_ID VARCHAR(36) NOT NULL,
 FILE_ID VARCHAR(36) NOT NULL,
 FACT_ORDER INT NOT NULL,
 FACT_TYPE VARCHAR(40) NOT NULL,
 DATA_TYPE VARCHAR(16) NOT NULL,
 VERIFICATION VARCHAR(24) NOT NULL,
 FACT_JSON CLOB NOT NULL,
 CONSTRAINT FK_AUTO_FACT_FILE FOREIGN KEY (CASE_ID,FILE_ID) REFERENCES AUDIT_CASE_FILE(CASE_ID,ID),
 CONSTRAINT UK_AUTO_FACT_ORDER UNIQUE (CASE_ID,FILE_ID,FACT_ORDER),
 CONSTRAINT CK_AUTO_FACT_ORDER CHECK (FACT_ORDER>=0),
 CONSTRAINT CK_AUTO_FACT_VERIFY CHECK (VERIFICATION IN ('SOURCE_VERIFIED','UNVERIFIED'))
);
CREATE INDEX IX_AUDIT_FACT_CASE ON AUDIT_FACT(CASE_ID,FACT_TYPE);
CREATE TABLE AUDIT_QUOTE_LINE (
 ID VARCHAR(36) NOT NULL PRIMARY KEY,
 CASE_ID VARCHAR(36) NOT NULL,
 FILE_ID VARCHAR(36) NOT NULL,
 ITEM_NAME VARCHAR(2000) NOT NULL,
 QUANTITY DECIMAL(18,4) NOT NULL,
 UNIT_PRICE DECIMAL(18,2) NOT NULL,
 LINE_AMOUNT DECIMAL(18,2) NOT NULL,
 LOCATOR VARCHAR(300) NOT NULL,
 CONSTRAINT FK_AUTO_LINE_FILE FOREIGN KEY (CASE_ID,FILE_ID) REFERENCES AUDIT_CASE_FILE(CASE_ID,ID),
 CONSTRAINT CK_AUTO_LINE_VALUES CHECK (QUANTITY>0 AND UNIT_PRICE>=0 AND LINE_AMOUNT>=0)
);
CREATE INDEX IX_AUTO_LINE_CASE ON AUDIT_QUOTE_LINE(CASE_ID,FILE_ID);
