CREATE TABLE BLACKLIST_SUPPLIER (
    ID              VARCHAR(36)  NOT NULL PRIMARY KEY,
    SUPPLIER_NAME   VARCHAR(200) NOT NULL,
    SUPPLIER_CODE   VARCHAR(50),
    BLACKLIST_TYPE  VARCHAR(50)  NOT NULL,
    REASON          VARCHAR(500) NOT NULL,
    SOURCE          VARCHAR(50)  NOT NULL,
    EFFECTIVE_DATE  DATE         NOT NULL,
    EXPIRY_DATE     DATE,
    IS_ACTIVE       BOOLEAN      NOT NULL DEFAULT TRUE,
    CREATED_BY      VARCHAR(50)  NOT NULL,
    CREATED_TIME    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_TIME    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IDX_BLACKLIST_SUPPLIER_NAME ON BLACKLIST_SUPPLIER (SUPPLIER_NAME);
CREATE INDEX IDX_BLACKLIST_SUPPLIER_CODE ON BLACKLIST_SUPPLIER (SUPPLIER_CODE);
CREATE INDEX IDX_BLACKLIST_SUPPLIER_ACTIVE ON BLACKLIST_SUPPLIER (IS_ACTIVE, EFFECTIVE_DATE, EXPIRY_DATE);

CREATE TABLE BLACKLIST_ALERT (
    ID               VARCHAR(36)  NOT NULL PRIMARY KEY,
    BATCH_ID         VARCHAR(50)  NOT NULL,
    ROW_NUMBER       INT,
    PROCUREMENT_ID   VARCHAR(64),
    SUPPLIER_NAME    VARCHAR(200) NOT NULL,
    SUPPLIER_CODE    VARCHAR(50),
    BLACKLIST_ID     VARCHAR(36)  NOT NULL,
    MATCHED_NAME     VARCHAR(200) NOT NULL,
    BLACKLIST_TYPE   VARCHAR(50)  NOT NULL,
    BLACKLIST_REASON VARCHAR(500) NOT NULL,
    MATCH_TYPE       VARCHAR(16)  NOT NULL,
    MATCH_SCORE      DECIMAL(5,2) NOT NULL,
    ALERT_LEVEL      VARCHAR(20)  NOT NULL,
    ALERT_STATUS     VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    RESOLVED_BY      VARCHAR(50),
    RESOLVED_TIME    TIMESTAMP,
    REMARK           VARCHAR(500),
    CREATED_TIME     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IDX_BLACKLIST_ALERT_BATCH ON BLACKLIST_ALERT (BATCH_ID, ROW_NUMBER);
CREATE INDEX IDX_BLACKLIST_ALERT_SUPPLIER ON BLACKLIST_ALERT (SUPPLIER_NAME, SUPPLIER_CODE);
CREATE INDEX IDX_BLACKLIST_ALERT_LEVEL ON BLACKLIST_ALERT (ALERT_LEVEL, ALERT_STATUS);
CREATE UNIQUE INDEX UK_BLACKLIST_ALERT_BATCH_SUPPLIER ON BLACKLIST_ALERT (BATCH_ID, SUPPLIER_NAME);

CREATE TABLE BLACKLIST_RULE (
    ID              VARCHAR(36)  NOT NULL PRIMARY KEY,
    RULE_NAME       VARCHAR(100) NOT NULL,
    RULE_TYPE       VARCHAR(50)  NOT NULL,
    BLACKLIST_TYPES VARCHAR(200),
    ALERT_LEVEL     VARCHAR(20)  NOT NULL,
    AUTO_RESOLVE    BOOLEAN      NOT NULL DEFAULT FALSE,
    IS_ACTIVE       BOOLEAN      NOT NULL DEFAULT TRUE,
    CREATED_TIME    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_TIME    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IDX_BLACKLIST_RULE_ACTIVE ON BLACKLIST_RULE (IS_ACTIVE, RULE_TYPE);

