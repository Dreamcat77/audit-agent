-- 1. 采购需求表
CREATE TABLE PROCUREMENT_DEMAND (
    ID                 VARCHAR(36)     NOT NULL PRIMARY KEY,
    PROCUREMENT_NAME   VARCHAR(200)    NOT NULL,
    BUDGET_APPROVAL_ID VARCHAR(64),
    SUBJECT_CODE       VARCHAR(64)     NOT NULL,
    SUBJECT_NAME       VARCHAR(200),
    AMOUNT             DECIMAL(18,2),
    SUPPLIER_NAME      VARCHAR(200),
    STATUS             VARCHAR(32)     DEFAULT 'DRAFT',
    CREATED_TIME       TIMESTAMP       DEFAULT CURRENT_TIMESTAMP,
    UPDATED_TIME       TIMESTAMP,
    DELETED            INT             DEFAULT 0
);

COMMENT ON TABLE PROCUREMENT_DEMAND IS '采购需求表';
COMMENT ON COLUMN PROCUREMENT_DEMAND.ID IS '主键ID';
COMMENT ON COLUMN PROCUREMENT_DEMAND.PROCUREMENT_NAME IS '采购需求名称';
COMMENT ON COLUMN PROCUREMENT_DEMAND.BUDGET_APPROVAL_ID IS '关联预算审批ID';
COMMENT ON COLUMN PROCUREMENT_DEMAND.SUBJECT_CODE IS '实际科目编码';
COMMENT ON COLUMN PROCUREMENT_DEMAND.SUBJECT_NAME IS '实际科目名称';
COMMENT ON COLUMN PROCUREMENT_DEMAND.AMOUNT IS '实际金额（元）';
COMMENT ON COLUMN PROCUREMENT_DEMAND.SUPPLIER_NAME IS '供应商名称';
COMMENT ON COLUMN PROCUREMENT_DEMAND.STATUS IS '状态（DRAFT/SUBMITTED/APPROVED/REJECTED）';
COMMENT ON COLUMN PROCUREMENT_DEMAND.CREATED_TIME IS '创建时间';
COMMENT ON COLUMN PROCUREMENT_DEMAND.UPDATED_TIME IS '更新时间';
COMMENT ON COLUMN PROCUREMENT_DEMAND.DELETED IS '是否删除（0-否，1-是）';

CREATE INDEX IDX_PROCUREMENT_DEMAND_SUBJECT ON PROCUREMENT_DEMAND (SUBJECT_CODE, STATUS);

-- 2. 预算科目映射表
CREATE TABLE BUDGET_SUBJECT_MAPPING (
    ID                    VARCHAR(36)     NOT NULL PRIMARY KEY,
    SYSTEM_SUBJECT_CODE   VARCHAR(64)     NOT NULL,
    SYSTEM_SUBJECT_NAME   VARCHAR(200),
    BUDGET_SUBJECT_CODE   VARCHAR(64)     NOT NULL,
    BUDGET_SUBJECT_NAME   VARCHAR(200),
    BUDGET_AMOUNT         DECIMAL(18,2),
    BUDGET_YEAR           VARCHAR(10),
    DEPARTMENT_CODE       VARCHAR(64),
    DEPARTMENT_NAME       VARCHAR(200),
    PROJECT_CODE          VARCHAR(100),
    PROJECT_NAME          VARCHAR(200),
    SUPPLIER_NAME         VARCHAR(200),
    PROCUREMENT_TYPE      VARCHAR(50),
    MAPPING_TYPE          VARCHAR(20)     DEFAULT 'EXACT',
    STATUS                VARCHAR(20)     DEFAULT 'ACTIVE',
    CREATE_TIME           TIMESTAMP       DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE BUDGET_SUBJECT_MAPPING IS '预算科目映射表';
COMMENT ON COLUMN BUDGET_SUBJECT_MAPPING.ID IS '主键ID';
COMMENT ON COLUMN BUDGET_SUBJECT_MAPPING.SYSTEM_SUBJECT_CODE IS '系统科目编码';
COMMENT ON COLUMN BUDGET_SUBJECT_MAPPING.SYSTEM_SUBJECT_NAME IS '系统科目名称';
COMMENT ON COLUMN BUDGET_SUBJECT_MAPPING.BUDGET_SUBJECT_CODE IS '预算科目编码';
COMMENT ON COLUMN BUDGET_SUBJECT_MAPPING.BUDGET_SUBJECT_NAME IS '预算科目名称';
COMMENT ON COLUMN BUDGET_SUBJECT_MAPPING.BUDGET_AMOUNT IS '预算金额（元）';
COMMENT ON COLUMN BUDGET_SUBJECT_MAPPING.BUDGET_YEAR IS '预算年度';
COMMENT ON COLUMN BUDGET_SUBJECT_MAPPING.DEPARTMENT_CODE IS '部门编码';
COMMENT ON COLUMN BUDGET_SUBJECT_MAPPING.DEPARTMENT_NAME IS '部门名称';
COMMENT ON COLUMN BUDGET_SUBJECT_MAPPING.PROJECT_CODE IS '项目编号';
COMMENT ON COLUMN BUDGET_SUBJECT_MAPPING.PROJECT_NAME IS '项目名称';
COMMENT ON COLUMN BUDGET_SUBJECT_MAPPING.SUPPLIER_NAME IS '供应商名称';
COMMENT ON COLUMN BUDGET_SUBJECT_MAPPING.PROCUREMENT_TYPE IS '采购类型';
COMMENT ON COLUMN BUDGET_SUBJECT_MAPPING.MAPPING_TYPE IS '映射类型（EXACT/SMART）';
COMMENT ON COLUMN BUDGET_SUBJECT_MAPPING.STATUS IS '状态（ACTIVE/INACTIVE）';
COMMENT ON COLUMN BUDGET_SUBJECT_MAPPING.CREATE_TIME IS '创建时间';

CREATE INDEX IDX_BUDGET_MAPPING_SYSTEM ON BUDGET_SUBJECT_MAPPING (SYSTEM_SUBJECT_CODE, STATUS);

-- 3. 预算审批校验记录表
CREATE TABLE BUDGET_APPROVAL_CHECK (
    ID                VARCHAR(36)     NOT NULL PRIMARY KEY,
    PROCUREMENT_ID    VARCHAR(36)     NOT NULL,
    CHECK_TYPE        VARCHAR(50)     NOT NULL,
    SUBJECT_CODE      VARCHAR(64),
    EXPECTED_VALUE    VARCHAR(500),
    ACTUAL_VALUE      VARCHAR(500),
    IS_PASSED         BOOLEAN         DEFAULT FALSE,
    ERROR_DETAIL      VARCHAR(2000),
    CHECK_TIME        TIMESTAMP       DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE BUDGET_APPROVAL_CHECK IS '预算审批校验记录表';
COMMENT ON COLUMN BUDGET_APPROVAL_CHECK.ID IS '主键ID';
COMMENT ON COLUMN BUDGET_APPROVAL_CHECK.PROCUREMENT_ID IS '采购需求ID';
COMMENT ON COLUMN BUDGET_APPROVAL_CHECK.CHECK_TYPE IS '校验类型（SUBJECT_CODE/BUDGET_AMOUNT/SUPPLIER_NAME/SUBJECT_NAME）';
COMMENT ON COLUMN BUDGET_APPROVAL_CHECK.SUBJECT_CODE IS '科目编码（可选）';
COMMENT ON COLUMN BUDGET_APPROVAL_CHECK.EXPECTED_VALUE IS '预期值';
COMMENT ON COLUMN BUDGET_APPROVAL_CHECK.ACTUAL_VALUE IS '实际值';
COMMENT ON COLUMN BUDGET_APPROVAL_CHECK.IS_PASSED IS '是否通过';
COMMENT ON COLUMN BUDGET_APPROVAL_CHECK.ERROR_DETAIL IS '错误详情';
COMMENT ON COLUMN BUDGET_APPROVAL_CHECK.CHECK_TIME IS '校验时间';

CREATE INDEX IDX_BUDGET_CHECK_PROC ON BUDGET_APPROVAL_CHECK (PROCUREMENT_ID, CHECK_TIME);

