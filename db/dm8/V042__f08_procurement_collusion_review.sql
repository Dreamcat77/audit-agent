-- V042: project-level F08 bidder document similarity and risk assessment.
CREATE TABLE PROCUREMENT_COLLUSION_DOCUMENT (
 ID VARCHAR(36) NOT NULL PRIMARY KEY, PROJECT_ID VARCHAR(36) NOT NULL, BIDDER_NAME VARCHAR(500) NOT NULL,
 IP_ADDRESS VARCHAR(64), HANDLER_NAME VARCHAR(200), FILE_NAME VARCHAR(500) NOT NULL, FILE_EXTENSION VARCHAR(16) NOT NULL,
 CONTENT_TYPE VARCHAR(200) NOT NULL, FILE_SIZE BIGINT NOT NULL, SHA256 VARCHAR(64) NOT NULL, STORAGE_KEY VARCHAR(128) NOT NULL,
 PARSED_TEXT CLOB NOT NULL, CREATED_TIME TIMESTAMP NOT NULL,
 CONSTRAINT FK_PROC_COLLUSION_DOCUMENT_PROJECT FOREIGN KEY (PROJECT_ID) REFERENCES PROCUREMENT_DEMAND(ID)
);
CREATE INDEX IDX_PROC_COLLUSION_DOCUMENT_PROJECT ON PROCUREMENT_COLLUSION_DOCUMENT(PROJECT_ID, CREATED_TIME);
CREATE TABLE PROCUREMENT_COLLUSION_ASSESSMENT (
 ID VARCHAR(36) NOT NULL PRIMARY KEY, PROJECT_ID VARCHAR(36) NOT NULL, RISK_SCORE INTEGER NOT NULL, RISK_LEVEL VARCHAR(16) NOT NULL,
 QUOTE_CV DECIMAL(18,8), MAX_DOCUMENT_SIMILARITY DECIMAL(18,8) NOT NULL, DUPLICATE_IP_GROUPS INTEGER NOT NULL,
 DUPLICATE_HANDLER_GROUPS INTEGER NOT NULL, SIMILARITIES_JSON CLOB NOT NULL, ASSESSED_TIME TIMESTAMP NOT NULL,
 CONSTRAINT UK_PROC_COLLUSION_ASSESSMENT_PROJECT UNIQUE(PROJECT_ID),
 CONSTRAINT FK_PROC_COLLUSION_ASSESSMENT_PROJECT FOREIGN KEY (PROJECT_ID) REFERENCES PROCUREMENT_DEMAND(ID),
 CONSTRAINT CK_PROC_COLLUSION_SCORE CHECK (RISK_SCORE BETWEEN 0 AND 100),
 CONSTRAINT CK_PROC_COLLUSION_LEVEL CHECK (RISK_LEVEL IN ('CRITICAL','WARNING','INFO'))
);
COMMENT ON TABLE PROCUREMENT_COLLUSION_DOCUMENT IS 'F08 投标文件解析及关联信息';
COMMENT ON TABLE PROCUREMENT_COLLUSION_ASSESSMENT IS 'F08 围串标综合风险评分，仅保留项目最新结果';
COMMIT;
