-- MIGRATION-NAMESPACE: CONTRACT
-- MIGRATION-ID: sanitized-debug-bundle
-- DEPENDS-ON: review-run-results
-- PURPOSE: internal metadata-only diagnostic artifact identity and rediscovery
-- EXECUTION: CONTROLLED_MANUAL
-- IDEMPOTENCY: NOT_ASSUMED
-- Preflight requires proven dependency and complete catalog evidence; see quality/schema_preflight.py.
-- Only NOT_APPLIED permits controlled execution. ALREADY_MATCHING skips; PARTIAL-SCHEMA_DRIFT/UNKNOWN stop.
-- Real DM8 execution NOT VERIFIED. MANIFEST_JSON contains validated allowlisted metadata only.
CREATE TABLE SANITIZED_DEBUG_BUNDLE (
    BUNDLE_ID VARCHAR(36) NOT NULL,
    PROJECT_ID VARCHAR(36) NOT NULL,
    CONTRACT_ID VARCHAR(36) NOT NULL,
    RUN_ID VARCHAR(36) NOT NULL,
    STEP_ID VARCHAR(36),
    ATTEMPT_ID VARCHAR(36),
    CONTENT_LEVEL VARCHAR(48) NOT NULL,
    STATUS VARCHAR(16) NOT NULL,
    MANIFEST_JSON CLOB NOT NULL,
    STORAGE_KEY VARCHAR(64) NOT NULL,
    ARTIFACT_SHA256 VARCHAR(64) NOT NULL,
    ARTIFACT_SIZE BIGINT NOT NULL,
    GENERATED_BY VARCHAR(36) NOT NULL,
    REQUESTED_AT TIMESTAMP NOT NULL,
    REQUEST_ID VARCHAR(128) NOT NULL,
    TRACE_ID VARCHAR(128) NOT NULL,
    VERSION_NO BIGINT DEFAULT 0 NOT NULL,
    CONSTRAINT PK_SDB PRIMARY KEY (BUNDLE_ID),
    CONSTRAINT UK_SDB_STORAGE UNIQUE (STORAGE_KEY),
    CONSTRAINT FK_SDB_RUN FOREIGN KEY (RUN_ID,PROJECT_ID) REFERENCES CONTRACT_REVIEW_RUN (RUN_ID,PROJECT_ID),
    CONSTRAINT FK_SDB_CONTRACT FOREIGN KEY (PROJECT_ID,CONTRACT_ID) REFERENCES PROJECT_CONTRACT (PROJECT_ID,CONTRACT_ID),
    CONSTRAINT FK_SDB_STEP FOREIGN KEY (RUN_ID,STEP_ID) REFERENCES CONTRACT_REVIEW_STEP (RUN_ID,STEP_ID),
    CONSTRAINT FK_SDB_ATTEMPT FOREIGN KEY (RUN_ID,STEP_ID,ATTEMPT_ID) REFERENCES CONTRACT_REVIEW_STEP_ATTEMPT (RUN_ID,STEP_ID,ATTEMPT_ID),
    CONSTRAINT FK_SDB_ACTOR FOREIGN KEY (GENERATED_BY) REFERENCES SYS_USER (ID),
    CONSTRAINT CK_SDB_LEVEL CHECK (CONTENT_LEVEL='METADATA_ONLY'),
    CONSTRAINT CK_SDB_STATUS CHECK (STATUS IN ('GENERATING','AVAILABLE','UNKNOWN')),
    CONSTRAINT CK_SDB_SCOPE CHECK (ATTEMPT_ID IS NULL OR STEP_ID IS NOT NULL),
    CONSTRAINT CK_SDB_BOUNDS CHECK (ARTIFACT_SIZE>0 AND ARTIFACT_SIZE<=1048576 AND VERSION_NO>=0),
    CONSTRAINT CK_SDB_HASH CHECK (LENGTH(STORAGE_KEY)=64 AND LENGTH(ARTIFACT_SHA256)=64)
);
CREATE INDEX IDX_SDB_RUN ON SANITIZED_DEBUG_BUNDLE (RUN_ID,REQUESTED_AT,BUNDLE_ID);
