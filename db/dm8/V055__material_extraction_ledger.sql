-- F01 / F10 / F11 shared bounded extraction checkpoints. Never raw documents in logs.
CREATE TABLE MATERIAL_EXTRACTION_LEDGER (
    ID VARCHAR(36) NOT NULL,
    SOURCE_HASH VARCHAR(64) NOT NULL,
    POLICY_HASH VARCHAR(64) NOT NULL,
    UNIT_COUNT INT NOT NULL,
    NEXT_UNIT INT DEFAULT 0 NOT NULL,
    CALL_COUNT INT DEFAULT 0 NOT NULL,
    USED_MILLIS BIGINT DEFAULT 0 NOT NULL,
    STATUS VARCHAR(16) NOT NULL,
    CALL_TOKEN VARCHAR(36),
    UPDATED_AT TIMESTAMP NOT NULL,
    RESULTS_JSON CLOB NOT NULL,
    REASON_CODE VARCHAR(64),
    CONSTRAINT PK_MATERIAL_EXTRACTION_LEDGER PRIMARY KEY(ID),
    CONSTRAINT CK_MATERIAL_EXTRACTION_STATUS CHECK(STATUS IN ('READY','CALLING','COMPLETE','UNKNOWN')),
    CONSTRAINT CK_MATERIAL_EXTRACTION_BUDGET CHECK(UNIT_COUNT BETWEEN 1 AND 512 AND NEXT_UNIT BETWEEN 0 AND UNIT_COUNT AND CALL_COUNT BETWEEN 0 AND 512 AND USED_MILLIS BETWEEN 0 AND 900000)
);
COMMENT ON TABLE MATERIAL_EXTRACTION_LEDGER IS '预算及采购分段提取确认快照、冻结策略和累计调用预算；UNKNOWN禁止自动重发';
