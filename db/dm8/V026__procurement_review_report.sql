-- V026: 采购项目统一审查报告元数据。
-- 报告正文由项目、预审、F06 和 F03 已有事实汇总，不复制模块明细。

CREATE TABLE PROCUREMENT_REVIEW_REPORT (
    ID             VARCHAR(36)  NOT NULL PRIMARY KEY,
    PROJECT_ID     VARCHAR(36)  NOT NULL,
    REPORT_NUMBER  VARCHAR(64)  NOT NULL,
    RISK_LEVEL     VARCHAR(16)  NOT NULL,
    GENERATED_TIME TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT UK_PROC_REVIEW_REPORT_NUMBER UNIQUE (REPORT_NUMBER),
    CONSTRAINT FK_PROC_REVIEW_REPORT_PROJECT FOREIGN KEY (PROJECT_ID)
        REFERENCES PROCUREMENT_DEMAND (ID),
    CONSTRAINT CK_PROC_REVIEW_REPORT_RISK CHECK (RISK_LEVEL IN ('CRITICAL', 'WARNING', 'INFO'))
);

CREATE INDEX IDX_PROC_REVIEW_REPORT_PROJECT
    ON PROCUREMENT_REVIEW_REPORT (PROJECT_ID, GENERATED_TIME);

COMMENT ON TABLE PROCUREMENT_REVIEW_REPORT IS '采购项目统一审查报告元数据';
COMMENT ON COLUMN PROCUREMENT_REVIEW_REPORT.REPORT_NUMBER IS '采购审查报告编号';
COMMENT ON COLUMN PROCUREMENT_REVIEW_REPORT.RISK_LEVEL IS '综合风险等级';

COMMIT;
