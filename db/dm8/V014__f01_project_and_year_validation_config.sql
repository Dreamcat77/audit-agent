-- Apply after V013__f01_validation_confirm_log.sql.

ALTER TABLE BUDGET_REVIEW_ITEM ADD REQUIRED_FIELDS_STATUS VARCHAR(16);
ALTER TABLE BUDGET_REVIEW_ITEM ADD AMOUNT_FORMAT_STATUS VARCHAR(16);
ALTER TABLE BUDGET_REVIEW_ITEM ADD PROJECT_CODE_STATUS VARCHAR(16);
ALTER TABLE BUDGET_REVIEW_ITEM ADD PROJECT_DEPARTMENT_STATUS VARCHAR(16);
ALTER TABLE BUDGET_REVIEW_ITEM ADD BUDGET_YEAR_VALIDITY_STATUS VARCHAR(16);

CREATE TABLE BUDGET_PROJECT_CONFIG (
    ID              VARCHAR(36)  NOT NULL PRIMARY KEY,
    PROJECT_CODE    VARCHAR(128) NOT NULL,
    PROJECT_NAME    VARCHAR(200),
    DEPARTMENT_CODE VARCHAR(64)  NOT NULL,
    DEPARTMENT_NAME VARCHAR(200),
    STATUS          VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    CREATED_TIME    TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    UPDATED_TIME    TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX UK_BUDGET_PROJECT_CONFIG_CODE
    ON BUDGET_PROJECT_CONFIG (PROJECT_CODE);

CREATE INDEX IDX_BUDGET_PROJECT_CONFIG_DEPT
    ON BUDGET_PROJECT_CONFIG (DEPARTMENT_CODE);

CREATE TABLE BUDGET_YEAR_VALIDITY_CONFIG (
    ID           VARCHAR(36) NOT NULL PRIMARY KEY,
    SUBJECT_CODE VARCHAR(64) NOT NULL,
    START_YEAR   INT         NOT NULL,
    END_YEAR     INT         NOT NULL,
    STATUS       VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    CREATED_TIME TIMESTAMP   DEFAULT CURRENT_TIMESTAMP,
    UPDATED_TIME TIMESTAMP   DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX UK_BUDGET_YEAR_VALIDITY_CODE
    ON BUDGET_YEAR_VALIDITY_CONFIG (SUBJECT_CODE);

CREATE INDEX IDX_BUDGET_YEAR_VALIDITY_STATUS
    ON BUDGET_YEAR_VALIDITY_CONFIG (STATUS);
