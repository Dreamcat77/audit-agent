CREATE TABLE PROCUREMENT_NOTIFICATION (
 ID VARCHAR(36) NOT NULL PRIMARY KEY, RECIPIENT_USER_ID VARCHAR(64) NOT NULL,
 PROJECT_ID VARCHAR(36) NOT NULL, PROJECT_NAME VARCHAR(300) NOT NULL, TYPE VARCHAR(32) NOT NULL,
 TITLE VARCHAR(200) NOT NULL, CONTENT VARCHAR(2000) NOT NULL, OPERATOR_NAME VARCHAR(100), OPINION VARCHAR(2000),
 READ_FLAG SMALLINT DEFAULT 0 NOT NULL, CREATED_TIME TIMESTAMP NOT NULL, READ_TIME TIMESTAMP,
 CONSTRAINT CK_PROC_NOTIFICATION_READ CHECK (READ_FLAG IN (0,1)),
 CONSTRAINT FK_PROC_NOTIFICATION_PROJECT FOREIGN KEY (PROJECT_ID) REFERENCES PROCUREMENT_DEMAND(ID)
);
CREATE INDEX IDX_PROC_NOTIFICATION_RECIPIENT ON PROCUREMENT_NOTIFICATION(RECIPIENT_USER_ID, READ_FLAG, CREATED_TIME);
COMMIT;
