ALTER TABLE PROCUREMENT_DEMAND ADD SOURCE_PROJECT_ID VARCHAR(36);

ALTER TABLE PROCUREMENT_DEMAND ADD CONSTRAINT FK_PROC_DEMAND_SOURCE_PROJECT
    FOREIGN KEY (SOURCE_PROJECT_ID) REFERENCES PROJECT (ID);

CREATE INDEX IDX_PROC_DEMAND_SOURCE_PROJECT
    ON PROCUREMENT_DEMAND (SOURCE_PROJECT_ID, DELETED, CREATED_TIME);

COMMENT ON COLUMN PROCUREMENT_DEMAND.SOURCE_PROJECT_ID IS
    '上游项目资料准入 PROJECT.ID；历史采购需求允许为空，新建采购需求由应用层强制填写';
