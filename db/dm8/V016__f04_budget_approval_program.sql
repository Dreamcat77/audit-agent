-- V016：F04 预算审批程序规范性校验。
-- PM_DEMO_20260828 是当前项目演示规则集，待甲方审批权限矩阵最终确认后通过配置修订。

CREATE TABLE BUDGET_APPROVAL_RULE_CONFIG (
    ID VARCHAR(36) NOT NULL,
    RULE_SET_CODE VARCHAR(64) NOT NULL,
    RULE_GROUP_CODE VARCHAR(64) NOT NULL,
    MATCH_MODE VARCHAR(32) NOT NULL,
    MIN_AMOUNT DECIMAL(18,2) NULL,
    MAX_AMOUNT DECIMAL(18,2) NULL,
    MIN_INCLUSIVE SMALLINT DEFAULT 0 NOT NULL,
    MAX_INCLUSIVE SMALLINT DEFAULT 0 NOT NULL,
    STEP_CODE VARCHAR(64) NOT NULL,
    STEP_NAME VARCHAR(128) NOT NULL,
    STEP_ORDER INT NOT NULL,
    STATUS VARCHAR(16) NOT NULL,
    VERSION_NO BIGINT DEFAULT 0 NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT PK_BUDGET_APPROVAL_RULE_CONFIG PRIMARY KEY (ID),
    CONSTRAINT UK_BUDGET_APPROVAL_RULE_STEP UNIQUE (RULE_SET_CODE, RULE_GROUP_CODE, STEP_CODE),
    CONSTRAINT CK_BUDGET_APPROVAL_RULE_GROUP CHECK (
        RULE_GROUP_CODE IN ('PROCEDURE_REQUIREMENT', 'AUTHORITY_LEVEL')),
    CONSTRAINT CK_BUDGET_APPROVAL_MATCH_MODE CHECK (MATCH_MODE IN ('CUMULATIVE_MIN', 'RANGE')),
    CONSTRAINT CK_BUDGET_APPROVAL_MODE_GROUP CHECK (
        (RULE_GROUP_CODE = 'PROCEDURE_REQUIREMENT' AND MATCH_MODE = 'CUMULATIVE_MIN')
        OR (RULE_GROUP_CODE = 'AUTHORITY_LEVEL' AND MATCH_MODE = 'RANGE')),
    CONSTRAINT CK_BUDGET_APPROVAL_CUMULATIVE CHECK (
        RULE_GROUP_CODE <> 'PROCEDURE_REQUIREMENT'
        OR (MIN_AMOUNT IS NOT NULL AND MAX_AMOUNT IS NULL)),
    CONSTRAINT CK_BUDGET_APPROVAL_MIN_FLAG CHECK (MIN_INCLUSIVE IN (0, 1)),
    CONSTRAINT CK_BUDGET_APPROVAL_MAX_FLAG CHECK (MAX_INCLUSIVE IN (0, 1)),
    CONSTRAINT CK_BUDGET_APPROVAL_RULE_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT CK_BUDGET_APPROVAL_RULE_ORDER CHECK (STEP_ORDER >= 0),
    CONSTRAINT CK_BUDGET_APPROVAL_AMOUNT_RANGE CHECK (
        MIN_AMOUNT IS NULL OR MAX_AMOUNT IS NULL OR MIN_AMOUNT <= MAX_AMOUNT)
);

COMMENT ON TABLE BUDGET_APPROVAL_RULE_CONFIG IS 'F04预算审批程序规则配置；PM_DEMO_20260828为演示规则集，待甲方审批权限矩阵最终确认。';
COMMENT ON COLUMN BUDGET_APPROVAL_RULE_CONFIG.RULE_SET_CODE IS '规则集代码；PM_DEMO_20260828表示当前演示确认版本。';
COMMENT ON COLUMN BUDGET_APPROVAL_RULE_CONFIG.RULE_GROUP_CODE IS '规则组：累计程序要求或互斥审批权限层级。';
COMMENT ON COLUMN BUDGET_APPROVAL_RULE_CONFIG.MATCH_MODE IS '金额匹配模式：累计下限或范围。';
COMMENT ON COLUMN BUDGET_APPROVAL_RULE_CONFIG.MIN_AMOUNT IS '金额下界；为空表示无下界。';
COMMENT ON COLUMN BUDGET_APPROVAL_RULE_CONFIG.MAX_AMOUNT IS '金额上界；为空表示无上界。';
COMMENT ON COLUMN BUDGET_APPROVAL_RULE_CONFIG.MIN_INCLUSIVE IS '金额下界是否包含，使用0或1。';
COMMENT ON COLUMN BUDGET_APPROVAL_RULE_CONFIG.MAX_INCLUSIVE IS '金额上界是否包含，使用0或1。';
COMMENT ON COLUMN BUDGET_APPROVAL_RULE_CONFIG.STEP_CODE IS '稳定审批步骤代码。';
COMMENT ON COLUMN BUDGET_APPROVAL_RULE_CONFIG.STEP_NAME IS '审批步骤中文展示名称。';
COMMENT ON COLUMN BUDGET_APPROVAL_RULE_CONFIG.STEP_ORDER IS '同规则组内步骤顺序。';
COMMENT ON COLUMN BUDGET_APPROVAL_RULE_CONFIG.STATUS IS '规则启停状态。';
COMMENT ON COLUMN BUDGET_APPROVAL_RULE_CONFIG.VERSION_NO IS '规则配置版本号。';

CREATE INDEX IDX_BUDGET_APPROVAL_RULE_ACTIVE
    ON BUDGET_APPROVAL_RULE_CONFIG (RULE_SET_CODE, STATUS, RULE_GROUP_CODE, STEP_ORDER);

CREATE TABLE BUDGET_APPROVAL_VALIDATION (
    ID VARCHAR(36) NOT NULL,
    RULE_SET_CODE VARCHAR(64) NOT NULL,
    SOURCE_TASK_ID VARCHAR(36) NOT NULL,
    SOURCE_ITEM_ID VARCHAR(36) NOT NULL,
    SOURCE_ROW_NUMBER INT NULL,
    DECLARED_AMOUNT DECIMAL(18,2) NOT NULL,
    ACTUAL_SOURCE VARCHAR(32) NOT NULL,
    REQUIRED_PROCEDURE_STEPS VARCHAR(1000) NOT NULL,
    REQUIRED_AUTHORITY_STEP VARCHAR(64) NOT NULL,
    ACTUAL_STEPS VARCHAR(1000) NOT NULL,
    MISSING_PROCEDURE_STEPS VARCHAR(1000) NOT NULL,
    PROCEDURE_ORDER_VALID SMALLINT NOT NULL,
    AUTHORITY_MATCHED SMALLINT NOT NULL,
    IS_PASSED SMALLINT NOT NULL,
    RESULT_SUMMARY VARCHAR(1000) NOT NULL,
    CREATED_BY VARCHAR(36) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT PK_BUDGET_APPROVAL_VALIDATION PRIMARY KEY (ID),
    CONSTRAINT FK_BUDGET_APPROVAL_VALID_TASK FOREIGN KEY (SOURCE_TASK_ID)
        REFERENCES BUDGET_REVIEW_TASK (ID),
    CONSTRAINT FK_BUDGET_APPROVAL_VALID_ITEM FOREIGN KEY (SOURCE_ITEM_ID)
        REFERENCES BUDGET_REVIEW_ITEM (ID),
    CONSTRAINT FK_BUDGET_APPROVAL_VALID_USER FOREIGN KEY (CREATED_BY)
        REFERENCES SYS_USER (ID),
    CONSTRAINT CK_BUDGET_APPROVAL_ACTUAL_SOURCE CHECK (ACTUAL_SOURCE = 'MANUAL_TEST'),
    CONSTRAINT CK_BUDGET_APPROVAL_ORDER_FLAG CHECK (PROCEDURE_ORDER_VALID IN (0, 1)),
    CONSTRAINT CK_BUDGET_APPROVAL_AUTH_FLAG CHECK (AUTHORITY_MATCHED IN (0, 1)),
    CONSTRAINT CK_BUDGET_APPROVAL_PASS_FLAG CHECK (IS_PASSED IN (0, 1)),
    CONSTRAINT CK_BUDGET_APPROVAL_DECLARED_AMOUNT CHECK (DECLARED_AMOUNT >= 0)
);

COMMENT ON TABLE BUDGET_APPROVAL_VALIDATION IS 'F04预算审批程序规范性校验历史；当前实际审批来源仅为联调前MANUAL_TEST。';
COMMENT ON COLUMN BUDGET_APPROVAL_VALIDATION.RULE_SET_CODE IS '执行校验时采用的规则集代码快照。';
COMMENT ON COLUMN BUDGET_APPROVAL_VALIDATION.SOURCE_TASK_ID IS '来源F01持久化预算审查任务标识。';
COMMENT ON COLUMN BUDGET_APPROVAL_VALIDATION.SOURCE_ITEM_ID IS '来源F01持久化预算项目标识。';
COMMENT ON COLUMN BUDGET_APPROVAL_VALIDATION.SOURCE_ROW_NUMBER IS '来源预算材料行号快照。';
COMMENT ON COLUMN BUDGET_APPROVAL_VALIDATION.DECLARED_AMOUNT IS '从F01预算项目读取的申报金额快照。';
COMMENT ON COLUMN BUDGET_APPROVAL_VALIDATION.ACTUAL_SOURCE IS '实际审批记录来源；MVP固定为MANUAL_TEST。';
COMMENT ON COLUMN BUDGET_APPROVAL_VALIDATION.REQUIRED_PROCEDURE_STEPS IS '按竖线分隔的应履行程序代码有序快照。';
COMMENT ON COLUMN BUDGET_APPROVAL_VALIDATION.REQUIRED_AUTHORITY_STEP IS '应审批权限层级代码快照。';
COMMENT ON COLUMN BUDGET_APPROVAL_VALIDATION.ACTUAL_STEPS IS '按竖线分隔的实际审批步骤代码有序快照。';
COMMENT ON COLUMN BUDGET_APPROVAL_VALIDATION.MISSING_PROCEDURE_STEPS IS '按竖线分隔的缺失程序代码有序快照。';
COMMENT ON COLUMN BUDGET_APPROVAL_VALIDATION.PROCEDURE_ORDER_VALID IS '程序顺序是否有效，使用0或1。';
COMMENT ON COLUMN BUDGET_APPROVAL_VALIDATION.AUTHORITY_MATCHED IS '审批权限层级是否匹配，使用0或1。';
COMMENT ON COLUMN BUDGET_APPROVAL_VALIDATION.IS_PASSED IS '当前规则集程序校验是否通过，使用0或1。';
COMMENT ON COLUMN BUDGET_APPROVAL_VALIDATION.RESULT_SUMMARY IS '不包含最终法规认定的程序校验结果摘要。';
COMMENT ON COLUMN BUDGET_APPROVAL_VALIDATION.CREATED_BY IS '从AuthContext取得的执行用户标识。';

CREATE INDEX IDX_BUDGET_APPROVAL_VALID_TASK
    ON BUDGET_APPROVAL_VALIDATION (SOURCE_TASK_ID, CREATED_AT);
CREATE INDEX IDX_BUDGET_APPROVAL_VALID_ITEM
    ON BUDGET_APPROVAL_VALIDATION (SOURCE_ITEM_ID, CREATED_AT);

