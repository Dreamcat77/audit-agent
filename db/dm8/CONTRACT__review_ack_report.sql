CREATE TABLE CONTRACT_REVIEW_FINDING_ACKNOWLEDGEMENT (
    ACKNOWLEDGEMENT_ID VARCHAR(36) NOT NULL,
    PROJECT_ID VARCHAR(36) NOT NULL,
    CONTRACT_ID VARCHAR(36) NOT NULL,
    RUN_ID VARCHAR(36) NOT NULL,
    STEP_ID VARCHAR(36) NOT NULL,
    ATTEMPT_ID VARCHAR(36) NOT NULL,
    FINDING_ID VARCHAR(36) NOT NULL,
    FINDING_VERSION_NO BIGINT NOT NULL,
    ACKNOWLEDGED_BY VARCHAR(36) NOT NULL,
    ACKNOWLEDGED_AT TIMESTAMP NOT NULL,
    HANDLING_NOTE CLOB,
    REQUEST_ID VARCHAR(128) NOT NULL,
    TRACE_ID VARCHAR(64) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    VERSION_NO BIGINT DEFAULT 0 NOT NULL,
    CONSTRAINT PK_CONTRACT_FINDING_ACK PRIMARY KEY (ACKNOWLEDGEMENT_ID),
    CONSTRAINT UK_CONTRACT_FINDING_ACK UNIQUE (FINDING_ID),
    CONSTRAINT FK_CONTRACT_FINDING_ACK_OWNER FOREIGN KEY (FINDING_ID, RUN_ID, STEP_ID, ATTEMPT_ID)
        REFERENCES CONTRACT_REVIEW_FINDING (FINDING_ID, RUN_ID, STEP_ID, ATTEMPT_ID),
    CONSTRAINT FK_CONTRACT_FINDING_ACK_RUN FOREIGN KEY (RUN_ID, PROJECT_ID)
        REFERENCES CONTRACT_REVIEW_RUN (RUN_ID, PROJECT_ID),
    CONSTRAINT FK_CONTRACT_FINDING_ACK_CONTRACT FOREIGN KEY (PROJECT_ID, CONTRACT_ID)
        REFERENCES PROJECT_CONTRACT (PROJECT_ID, CONTRACT_ID),
    CONSTRAINT FK_CONTRACT_FINDING_ACK_ACTOR FOREIGN KEY (ACKNOWLEDGED_BY) REFERENCES SYS_USER (ID),
    CONSTRAINT CK_CONTRACT_FINDING_ACK_VERSION CHECK (FINDING_VERSION_NO >= 0 AND VERSION_NO = 0)
);
CREATE INDEX IDX_CONTRACT_FINDING_ACK_RUN ON CONTRACT_REVIEW_FINDING_ACKNOWLEDGEMENT (RUN_ID, FINDING_ID);

CREATE TABLE CONTRACT_REVIEW_REPORT (
    REPORT_ID VARCHAR(36) NOT NULL,
    RUN_ID VARCHAR(36) NOT NULL,
    REPORT_VERSION INTEGER NOT NULL,
    REPORT_SCHEMA_VERSION INTEGER NOT NULL,
    STATUS VARCHAR(32) NOT NULL,
    INPUT_SNAPSHOT_IDENTITY VARCHAR(64) NOT NULL,
    FINDING_SNAPSHOT_IDENTITY VARCHAR(64) NOT NULL,
    ACKNOWLEDGEMENT_SNAPSHOT_IDENTITY VARCHAR(64) NOT NULL,
    SNAPSHOT_JSON CLOB NOT NULL,
    ARTIFACT_STORAGE_KEY VARCHAR(64),
    ARTIFACT_MEDIA_TYPE VARCHAR(100),
    ARTIFACT_SIZE BIGINT,
    SHA256 VARCHAR(64),
    GENERATED_BY VARCHAR(36) NOT NULL,
    REQUESTED_AT TIMESTAMP NOT NULL,
    GENERATED_AT TIMESTAMP,
    FAILED_AT TIMESTAMP,
    UNKNOWN_AT TIMESTAMP,
    SAFE_REASON_CODE VARCHAR(100),
    REQUEST_ID VARCHAR(128) NOT NULL,
    TRACE_ID VARCHAR(64) NOT NULL,
    VERSION_NO BIGINT DEFAULT 0 NOT NULL,
    CONSTRAINT PK_CONTRACT_REVIEW_REPORT PRIMARY KEY (REPORT_ID),
    CONSTRAINT UK_CONTRACT_REVIEW_REPORT_VERSION UNIQUE (RUN_ID, REPORT_VERSION),
    CONSTRAINT FK_CONTRACT_REVIEW_REPORT_RUN FOREIGN KEY (RUN_ID) REFERENCES CONTRACT_REVIEW_RUN (RUN_ID),
    CONSTRAINT FK_CONTRACT_REVIEW_REPORT_ACTOR FOREIGN KEY (GENERATED_BY) REFERENCES SYS_USER (ID),
    CONSTRAINT CK_CONTRACT_REVIEW_REPORT_VERSION CHECK
        (REPORT_VERSION > 0 AND REPORT_SCHEMA_VERSION > 0 AND VERSION_NO >= 0),
    CONSTRAINT CK_CONTRACT_REVIEW_REPORT_STATUS CHECK
        (STATUS IN ('PENDING', 'GENERATING', 'AVAILABLE', 'FAILED', 'UNKNOWN')),
    CONSTRAINT CK_CONTRACT_REVIEW_REPORT_HASH CHECK
        (LENGTH(INPUT_SNAPSHOT_IDENTITY) = 64 AND LENGTH(FINDING_SNAPSHOT_IDENTITY) = 64
            AND LENGTH(ACKNOWLEDGEMENT_SNAPSHOT_IDENTITY) = 64
            AND (SHA256 IS NULL OR LENGTH(SHA256) = 64)),
    CONSTRAINT CK_CONTRACT_REVIEW_REPORT_ARTIFACT CHECK
        ((ARTIFACT_STORAGE_KEY IS NULL AND ARTIFACT_MEDIA_TYPE IS NULL AND ARTIFACT_SIZE IS NULL AND SHA256 IS NULL)
         OR (ARTIFACT_STORAGE_KEY IS NOT NULL AND LENGTH(ARTIFACT_STORAGE_KEY) = 64
             AND ARTIFACT_MEDIA_TYPE IS NOT NULL AND ARTIFACT_SIZE > 0 AND SHA256 IS NOT NULL)),
    CONSTRAINT CK_CONTRACT_REVIEW_REPORT_AVAILABLE CHECK
        (STATUS <> 'AVAILABLE' OR (ARTIFACT_STORAGE_KEY IS NOT NULL AND GENERATED_AT IS NOT NULL
            AND FAILED_AT IS NULL AND SAFE_REASON_CODE IS NULL))
);
CREATE INDEX IDX_CONTRACT_REVIEW_REPORT_RUN ON CONTRACT_REVIEW_REPORT (RUN_ID, REPORT_VERSION);
