-- Durable upload identities and verified parts; business processing reuses existing intake services.
CREATE TABLE MATERIAL_TRANSFER (
    ID VARCHAR(36) NOT NULL PRIMARY KEY,
    ACTOR_ID VARCHAR(64) NOT NULL,
    KIND VARCHAR(24) NOT NULL,
    OPERATION_ID VARCHAR(36) NOT NULL,
    SPEC_JSON CLOB NOT NULL,
    STATUS VARCHAR(16) NOT NULL,
    LEASE_TOKEN VARCHAR(36),
    LEASE_UNTIL TIMESTAMP,
    RESULT_JSON CLOB,
    CREATED_AT TIMESTAMP NOT NULL
);
CREATE TABLE MATERIAL_TRANSFER_PART (
    TRANSFER_ID VARCHAR(36) NOT NULL,
    PART_INDEX INT NOT NULL,
    FILE_SIZE BIGINT NOT NULL,
    SHA256 VARCHAR(64) NOT NULL,
    STORAGE_KEY VARCHAR(64) NOT NULL,
    PRIMARY KEY(TRANSFER_ID,PART_INDEX),
    FOREIGN KEY(TRANSFER_ID) REFERENCES MATERIAL_TRANSFER(ID)
);
CREATE INDEX IX_MATERIAL_TRANSFER_ACTOR ON MATERIAL_TRANSFER(ACTOR_ID,CREATED_AT);
