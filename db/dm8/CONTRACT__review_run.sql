-- MIGRATION-NAMESPACE: CONTRACT
-- MIGRATION-ID: review-run
-- DEPENDS-ON: contract-candidate-confirmation
-- PURPOSE: durable immutable contract review runs, material snapshots and step manifests
-- EXECUTION: CONTROLLED_MANUAL
-- IDEMPOTENCY: NOT_ASSUMED

-- The existing one-to-one association must also bind this run's exact source candidate.
ALTER TABLE PROJECT_CONTRACT ADD
    CONSTRAINT UK_PROJECT_CONTRACT_RUN_SOURCE UNIQUE (PROJECT_ID, CONTRACT_ID, CANDIDATE_ID);

CREATE TABLE CONTRACT_REVIEW_RUN (
    RUN_ID VARCHAR(36) NOT NULL,
    PROJECT_ID VARCHAR(36) NOT NULL,
    CONTRACT_ID VARCHAR(36) NOT NULL,
    CONTRACT_VERSION BIGINT NOT NULL,
    SOURCE_CANDIDATE_ID VARCHAR(36),
    SOURCE_CONFIRMATION_ID VARCHAR(36),
    RUN_SCHEMA_VERSION INTEGER NOT NULL,
    CONTRACT_SNAPSHOT_CANONICAL_JSON CLOB NOT NULL,
    CONTRACT_SNAPSHOT_SHA256 VARCHAR(64) NOT NULL,
    REVIEW_PROFILE_VERSION VARCHAR(100) NOT NULL,
    RULE_VERSION VARCHAR(100) NOT NULL,
    MODEL_POLICY_VERSION VARCHAR(100) NOT NULL,
    INPUT_SNAPSHOT_IDENTITY VARCHAR(64) NOT NULL,
    REQUESTED_BY VARCHAR(36) NOT NULL,
    STATUS VARCHAR(32) NOT NULL,
    REQUESTED_AT TIMESTAMP NOT NULL,
    STARTED_AT TIMESTAMP,
    COMPLETED_AT TIMESTAMP,
    FAILED_AT TIMESTAMP,
    UNKNOWN_AT TIMESTAMP,
    SAFE_REASON_CODE VARCHAR(100),
    VERSION_NO BIGINT DEFAULT 0 NOT NULL,
    CONSTRAINT PK_CONTRACT_REVIEW_RUN NOT CLUSTER PRIMARY KEY (RUN_ID),
    CONSTRAINT UK_CONTRACT_REVIEW_RUN_OWNER UNIQUE (RUN_ID, PROJECT_ID),
    CONSTRAINT FK_CONTRACT_REVIEW_RUN_ASSOCIATION FOREIGN KEY (PROJECT_ID, CONTRACT_ID)
        REFERENCES PROJECT_CONTRACT (PROJECT_ID, CONTRACT_ID),
    CONSTRAINT FK_CONTRACT_REVIEW_RUN_ASSOCIATION_SOURCE FOREIGN KEY
        (PROJECT_ID, CONTRACT_ID, SOURCE_CANDIDATE_ID)
        REFERENCES PROJECT_CONTRACT (PROJECT_ID, CONTRACT_ID, CANDIDATE_ID),
    CONSTRAINT FK_CONTRACT_REVIEW_RUN_CANDIDATE FOREIGN KEY (PROJECT_ID, SOURCE_CANDIDATE_ID)
        REFERENCES CONTRACT_CANDIDATE (PROJECT_ID, ID),
    CONSTRAINT FK_CONTRACT_REVIEW_RUN_CONFIRMATION FOREIGN KEY
        (SOURCE_CONFIRMATION_ID, PROJECT_ID, SOURCE_CANDIDATE_ID)
        REFERENCES CONTRACT_CANDIDATE_CONFIRMATION (CONFIRMATION_ID, PROJECT_ID, CANDIDATE_ID),
    CONSTRAINT FK_CONTRACT_REVIEW_RUN_ACTOR FOREIGN KEY (REQUESTED_BY) REFERENCES SYS_USER (ID),
    CONSTRAINT CK_CONTRACT_REVIEW_RUN_VERSIONS CHECK
        (CONTRACT_VERSION >= 0 AND RUN_SCHEMA_VERSION > 0 AND VERSION_NO >= 0),
    CONSTRAINT CK_CONTRACT_REVIEW_RUN_HASHES CHECK
        (LENGTH(CONTRACT_SNAPSHOT_SHA256) = 64 AND LENGTH(INPUT_SNAPSHOT_IDENTITY) = 64),
    CONSTRAINT CK_CONTRACT_REVIEW_RUN_PROVENANCE CHECK
        (SOURCE_CONFIRMATION_ID IS NULL OR SOURCE_CANDIDATE_ID IS NOT NULL),
    CONSTRAINT CK_CONTRACT_REVIEW_RUN_STATUS CHECK
        (STATUS IN ('PENDING', 'RUNNING', 'COMPLETED', 'PARTIALLY_COMPLETED', 'FAILED', 'UNKNOWN')),
    CONSTRAINT CK_CONTRACT_REVIEW_RUN_PENDING CHECK
        (STATUS <> 'PENDING' OR (STARTED_AT IS NULL AND COMPLETED_AT IS NULL
            AND FAILED_AT IS NULL AND UNKNOWN_AT IS NULL AND SAFE_REASON_CODE IS NULL))
);

CREATE INDEX IDX_CONTRACT_REVIEW_RUN_PROJECT
    ON CONTRACT_REVIEW_RUN (PROJECT_ID, CONTRACT_ID, REQUESTED_AT DESC, RUN_ID);

CREATE TABLE CONTRACT_REVIEW_RUN_MATERIAL (
    RUN_MATERIAL_ID VARCHAR(36) NOT NULL,
    RUN_ID VARCHAR(36) NOT NULL,
    ORDINAL INTEGER NOT NULL,
    PROJECT_ID VARCHAR(36) NOT NULL,
    FILE_ID VARCHAR(36) NOT NULL,
    FILE_SHA256 VARCHAR(64) NOT NULL,
    PARSE_RESULT_ID VARCHAR(36) NOT NULL,
    PARSE_VERSION INTEGER NOT NULL,
    CANONICAL_TEXT_SHA256 VARCHAR(64) NOT NULL,
    EFFECTIVE_ROLE VARCHAR(32) NOT NULL,
    ROLE_DECISION_ID VARCHAR(36),
    IDENTITY_DECISION_ID VARCHAR(36) NOT NULL,
    SOURCE_ROLE_DISPOSITION_ID VARCHAR(36),
    SELECTED_BY VARCHAR(36) NOT NULL,
    SNAPSHOTTED_AT TIMESTAMP NOT NULL,
    CONSTRAINT PK_CONTRACT_REVIEW_RUN_MATERIAL PRIMARY KEY (RUN_MATERIAL_ID),
    CONSTRAINT UK_CONTRACT_REVIEW_RUN_MATERIAL_FILE UNIQUE (RUN_ID, FILE_ID),
    CONSTRAINT UK_CONTRACT_REVIEW_RUN_MATERIAL_ORDINAL UNIQUE (RUN_ID, ORDINAL),
    CONSTRAINT FK_CONTRACT_REVIEW_RUN_MATERIAL_RUN FOREIGN KEY (RUN_ID, PROJECT_ID)
        REFERENCES CONTRACT_REVIEW_RUN (RUN_ID, PROJECT_ID),
    CONSTRAINT FK_CONTRACT_REVIEW_RUN_MATERIAL_FILE FOREIGN KEY (PROJECT_ID, FILE_ID)
        REFERENCES PROJECT_FILE (PROJECT_ID, ID),
    CONSTRAINT FK_CONTRACT_REVIEW_RUN_MATERIAL_PARSE FOREIGN KEY
        (PARSE_RESULT_ID, PROJECT_ID, FILE_ID, FILE_SHA256, PARSE_VERSION)
        REFERENCES PROJECT_FILE_PARSE_RESULT (PARSE_RESULT_ID, PROJECT_ID, FILE_ID, FILE_SHA256, PARSE_VERSION),
    CONSTRAINT FK_CONTRACT_REVIEW_RUN_MATERIAL_ROLE FOREIGN KEY
        (ROLE_DECISION_ID, PROJECT_ID, FILE_ID, PARSE_RESULT_ID)
        REFERENCES PROJECT_FILE_ROLE_DECISION (DECISION_ID, PROJECT_ID, FILE_ID, PARSE_RESULT_ID),
    CONSTRAINT FK_CONTRACT_REVIEW_RUN_MATERIAL_IDENTITY FOREIGN KEY
        (IDENTITY_DECISION_ID, PROJECT_ID, FILE_ID, PARSE_RESULT_ID)
        REFERENCES PROJECT_FILE_IDENTITY_DECISION (DECISION_ID, PROJECT_ID, FILE_ID, PARSE_RESULT_ID),
    CONSTRAINT FK_CONTRACT_REVIEW_RUN_MATERIAL_ACTOR FOREIGN KEY (SELECTED_BY)
        REFERENCES SYS_USER (ID),
    CONSTRAINT CK_CONTRACT_REVIEW_RUN_MATERIAL_VERSION CHECK (ORDINAL > 0 AND PARSE_VERSION > 0),
    CONSTRAINT CK_CONTRACT_REVIEW_RUN_MATERIAL_HASH CHECK
        (LENGTH(FILE_SHA256) = 64 AND LENGTH(CANONICAL_TEXT_SHA256) = 64),
    CONSTRAINT CK_CONTRACT_REVIEW_RUN_MATERIAL_ROLE CHECK
        (EFFECTIVE_ROLE IN ('CONTRACT_BODY', 'AWARD_NOTICE', 'TENDER_DOCUMENT',
            'BID_RESPONSE', 'SUPPLEMENT', 'OTHER'))
);

CREATE INDEX IDX_CONTRACT_REVIEW_RUN_MATERIAL_RUN
    ON CONTRACT_REVIEW_RUN_MATERIAL (RUN_ID, ORDINAL);

CREATE TABLE CONTRACT_REVIEW_STEP (
    STEP_ID VARCHAR(36) NOT NULL,
    RUN_ID VARCHAR(36) NOT NULL,
    STEP_TYPE VARCHAR(64) NOT NULL,
    REQUIRED_FLAG INTEGER NOT NULL,
    STATUS VARCHAR(32) NOT NULL,
    STEP_POLICY_VERSION VARCHAR(100) NOT NULL,
    CURRENT_ATTEMPT_NO INTEGER NOT NULL,
    OUTPUT_RESOURCE_TYPE VARCHAR(64),
    OUTPUT_RESOURCE_ID VARCHAR(36),
    SAFE_REASON_CODE VARCHAR(100),
    STARTED_AT TIMESTAMP,
    COMPLETED_AT TIMESTAMP,
    VERSION_NO BIGINT DEFAULT 0 NOT NULL,
    CONSTRAINT PK_CONTRACT_REVIEW_STEP PRIMARY KEY (STEP_ID),
    CONSTRAINT UK_CONTRACT_REVIEW_STEP_RUN_TYPE UNIQUE (RUN_ID, STEP_TYPE),
    CONSTRAINT UK_CONTRACT_REVIEW_STEP_RUN_ID UNIQUE (RUN_ID, STEP_ID),
    CONSTRAINT FK_CONTRACT_REVIEW_STEP_RUN FOREIGN KEY (RUN_ID)
        REFERENCES CONTRACT_REVIEW_RUN (RUN_ID),
    CONSTRAINT CK_CONTRACT_REVIEW_STEP_REQUIRED CHECK (REQUIRED_FLAG IN (0, 1)),
    CONSTRAINT CK_CONTRACT_REVIEW_STEP_VERSIONS CHECK (CURRENT_ATTEMPT_NO >= 0 AND VERSION_NO >= 0),
    CONSTRAINT CK_CONTRACT_REVIEW_STEP_STATUS CHECK
        (STATUS IN ('PENDING', 'RUNNING', 'COMPLETED', 'FAILED', 'UNKNOWN')),
    CONSTRAINT CK_CONTRACT_REVIEW_STEP_OUTPUT CHECK
        ((OUTPUT_RESOURCE_TYPE IS NULL AND OUTPUT_RESOURCE_ID IS NULL)
            OR (OUTPUT_RESOURCE_TYPE IS NOT NULL AND OUTPUT_RESOURCE_ID IS NOT NULL)),
    CONSTRAINT CK_CONTRACT_REVIEW_STEP_MATERIAL CHECK
        (STEP_TYPE <> 'MATERIAL_VALIDATION' OR (STATUS = 'COMPLETED'
            AND CURRENT_ATTEMPT_NO = 0 AND OUTPUT_RESOURCE_TYPE = 'RUN_MATERIAL_SNAPSHOT'
            AND OUTPUT_RESOURCE_ID = RUN_ID AND COMPLETED_AT IS NOT NULL)),
    CONSTRAINT CK_CONTRACT_REVIEW_STEP_PENDING CHECK
        (STATUS <> 'PENDING' OR (CURRENT_ATTEMPT_NO > 0 AND OUTPUT_RESOURCE_TYPE IS NULL
            AND OUTPUT_RESOURCE_ID IS NULL AND STARTED_AT IS NULL AND COMPLETED_AT IS NULL))
);

CREATE INDEX IDX_CONTRACT_REVIEW_STEP_RUN ON CONTRACT_REVIEW_STEP (RUN_ID, STEP_TYPE);

CREATE TABLE CONTRACT_REVIEW_STEP_ATTEMPT (
    ATTEMPT_ID VARCHAR(36) NOT NULL,
    RUN_ID VARCHAR(36) NOT NULL,
    STEP_ID VARCHAR(36) NOT NULL,
    ATTEMPT_NO INTEGER NOT NULL,
    OPERATION_IDENTITY VARCHAR(64) NOT NULL,
    STATUS VARCHAR(32) NOT NULL,
    LEASE_OWNER VARCHAR(100),
    LEASE_UNTIL TIMESTAMP,
    CLAIMED_AT TIMESTAMP,
    EXTERNAL_CALL_STATE VARCHAR(32) NOT NULL,
    EXTERNAL_REQUEST_FINGERPRINT VARCHAR(64),
    PROVIDER_REQUEST_ID VARCHAR(100),
    PROVIDER VARCHAR(100),
    "MODEL" VARCHAR(100),
    STARTED_AT TIMESTAMP,
    COMPLETED_AT TIMESTAMP,
    SAFE_REASON_CODE VARCHAR(100),
    OUTPUT_RESOURCE_TYPE VARCHAR(64),
    OUTPUT_RESOURCE_ID VARCHAR(36),
    VERSION_NO BIGINT DEFAULT 0 NOT NULL,
    CONSTRAINT PK_CONTRACT_REVIEW_STEP_ATTEMPT PRIMARY KEY (ATTEMPT_ID),
    CONSTRAINT UK_CONTRACT_REVIEW_STEP_ATTEMPT_NO UNIQUE (STEP_ID, ATTEMPT_NO),
    CONSTRAINT UK_CONTRACT_REVIEW_STEP_ATTEMPT_OPERATION UNIQUE (OPERATION_IDENTITY),
    CONSTRAINT FK_CONTRACT_REVIEW_STEP_ATTEMPT_STEP FOREIGN KEY (RUN_ID, STEP_ID)
        REFERENCES CONTRACT_REVIEW_STEP (RUN_ID, STEP_ID),
    CONSTRAINT CK_CONTRACT_REVIEW_STEP_ATTEMPT_VERSIONS CHECK (ATTEMPT_NO > 0 AND VERSION_NO >= 0),
    CONSTRAINT CK_CONTRACT_REVIEW_STEP_ATTEMPT_STATUS CHECK
        (STATUS IN ('PENDING', 'RUNNING', 'COMPLETED', 'FAILED', 'UNKNOWN')),
    CONSTRAINT CK_CONTRACT_REVIEW_STEP_ATTEMPT_CALL CHECK
        (EXTERNAL_CALL_STATE IN ('NOT_STARTED', 'REQUESTED', 'OUTCOME_UNKNOWN', 'COMPLETED')),
    CONSTRAINT CK_CONTRACT_REVIEW_STEP_ATTEMPT_PENDING CHECK
        (STATUS <> 'PENDING' OR (EXTERNAL_CALL_STATE = 'NOT_STARTED' AND LEASE_OWNER IS NULL
            AND LEASE_UNTIL IS NULL AND CLAIMED_AT IS NULL AND EXTERNAL_REQUEST_FINGERPRINT IS NULL
            AND PROVIDER_REQUEST_ID IS NULL AND PROVIDER IS NULL AND "MODEL" IS NULL
            AND STARTED_AT IS NULL AND COMPLETED_AT IS NULL AND SAFE_REASON_CODE IS NULL
            AND OUTPUT_RESOURCE_TYPE IS NULL AND OUTPUT_RESOURCE_ID IS NULL))
);

CREATE INDEX IDX_CONTRACT_REVIEW_STEP_ATTEMPT_RUN
    ON CONTRACT_REVIEW_STEP_ATTEMPT (RUN_ID, STEP_ID, ATTEMPT_NO);
CREATE INDEX IDX_CONTRACT_REVIEW_STEP_ATTEMPT_PENDING
    ON CONTRACT_REVIEW_STEP_ATTEMPT (STATUS, LEASE_UNTIL, ATTEMPT_ID);
