-- V004：合同审核会话、不可覆盖文档元数据、当前材料绑定及 abandoned upload recovery 查询能力。
-- 本迁移仅为 additive DM8 DDL；不修改 AUDIT_TASK，也不恢复长事务或数据库 BLOB 文件存储。

CREATE TABLE CONTRACT_REVIEW_SESSION (
    ID VARCHAR(36) NOT NULL,
    CONTRACT_ID VARCHAR(36) NOT NULL,
    CONTRACT_VERSION BIGINT NOT NULL,
    NAME VARCHAR(256) NOT NULL,
    REVIEW_TYPE VARCHAR(64) NOT NULL,
    STATUS VARCHAR(32) NOT NULL,
    REMARK VARCHAR(1000) NULL,
    CREATED_BY VARCHAR(36) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP NOT NULL,
    MATERIALS_CONFIRMED_AT TIMESTAMP NULL,
    VERSION_NO BIGINT NOT NULL,
    CONSTRAINT PK_CR_SESSION PRIMARY KEY (ID),
    CONSTRAINT FK_CR_SESSION_CONTRACT FOREIGN KEY (CONTRACT_ID) REFERENCES CONTRACT (ID),
    CONSTRAINT FK_CR_SESSION_USER FOREIGN KEY (CREATED_BY) REFERENCES SYS_USER (ID),
    CONSTRAINT CK_CR_SESSION_CONTRACT_VER CHECK (CONTRACT_VERSION >= 0),
    CONSTRAINT CK_CR_SESSION_VERSION CHECK (VERSION_NO >= 0),
    CONSTRAINT CK_CR_SESSION_STATUS CHECK (STATUS IN ('PREPARING_MATERIALS', 'READY')),
    CONSTRAINT CK_CR_SESSION_CONFIRM CHECK (
        (STATUS = 'PREPARING_MATERIALS' AND MATERIALS_CONFIRMED_AT IS NULL)
        OR (STATUS = 'READY' AND MATERIALS_CONFIRMED_AT IS NOT NULL))
);

COMMENT ON TABLE CONTRACT_REVIEW_SESSION IS '合同审核会话；记录用户从材料准备到 READY 的业务生命周期。';
COMMENT ON COLUMN CONTRACT_REVIEW_SESSION.ID IS '合同审核会话唯一标识。';
COMMENT ON COLUMN CONTRACT_REVIEW_SESSION.CONTRACT_ID IS '本次审核会话关联的合同标识。';
COMMENT ON COLUMN CONTRACT_REVIEW_SESSION.CONTRACT_VERSION IS '创建审核会话时的合同版本快照；不直接等同于未来 AuditTask 的最终 SOURCE_VERSION。';
COMMENT ON COLUMN CONTRACT_REVIEW_SESSION.NAME IS '用户可编辑的审核名称。';
COMMENT ON COLUMN CONTRACT_REVIEW_SESSION.REVIEW_TYPE IS '服务端固定的审核类型；客户端不可指定。';
COMMENT ON COLUMN CONTRACT_REVIEW_SESSION.STATUS IS '会话状态：PREPARING_MATERIALS 或 READY。';
COMMENT ON COLUMN CONTRACT_REVIEW_SESSION.REMARK IS '审核发起备注，可为空。';
COMMENT ON COLUMN CONTRACT_REVIEW_SESSION.CREATED_BY IS '发起审核会话的系统用户标识。';
COMMENT ON COLUMN CONTRACT_REVIEW_SESSION.CREATED_AT IS '审核会话创建时间。';
COMMENT ON COLUMN CONTRACT_REVIEW_SESSION.UPDATED_AT IS '审核会话最近业务更新时间。';
COMMENT ON COLUMN CONTRACT_REVIEW_SESSION.MATERIALS_CONFIRMED_AT IS '核心材料确认并进入 READY 的时间。';
COMMENT ON COLUMN CONTRACT_REVIEW_SESSION.VERSION_NO IS '整个材料集合与会话状态的乐观并发版本。';

CREATE INDEX IDX_CR_SESSION_CONTRACT_CREATED
    ON CONTRACT_REVIEW_SESSION (CONTRACT_ID, CREATED_AT);
CREATE INDEX IDX_CR_SESSION_STATUS_UPDATED
    ON CONTRACT_REVIEW_SESSION (STATUS, UPDATED_AT);

CREATE TABLE CONTRACT_REVIEW_DOCUMENT (
    ID VARCHAR(36) NOT NULL,
    SESSION_ID VARCHAR(36) NOT NULL,
    DOCUMENT_KIND VARCHAR(32) NOT NULL,
    SLOT_KEY VARCHAR(128) NOT NULL,
    ORIGINAL_FILE_NAME VARCHAR(256) NOT NULL,
    FILE_EXTENSION VARCHAR(16) NOT NULL,
    CONTENT_TYPE VARCHAR(128) NOT NULL,
    FILE_SIZE BIGINT NOT NULL,
    SHA256 VARCHAR(64) NOT NULL,
    STORAGE_KEY VARCHAR(256) NOT NULL,
    STATUS VARCHAR(32) NOT NULL,
    REPLACES_DOCUMENT_ID VARCHAR(36) NULL,
    REQUESTED_SESSION_VERSION BIGINT NOT NULL,
    RESERVED_SESSION_VERSION BIGINT NOT NULL,
    CREATED_BY VARCHAR(36) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP NOT NULL,
    STORED_AT TIMESTAMP NULL,
    FAILED_AT TIMESTAMP NULL,
    VERSION_NO BIGINT NOT NULL,
    CONSTRAINT PK_CR_DOCUMENT PRIMARY KEY (ID),
    CONSTRAINT UK_CR_DOCUMENT_STORAGE UNIQUE (STORAGE_KEY),
    CONSTRAINT UK_CR_DOC_SCOPE UNIQUE (SESSION_ID, SLOT_KEY, DOCUMENT_KIND, ID),
    CONSTRAINT FK_CR_DOCUMENT_SESSION FOREIGN KEY (SESSION_ID)
        REFERENCES CONTRACT_REVIEW_SESSION (ID),
    CONSTRAINT FK_CR_DOCUMENT_USER FOREIGN KEY (CREATED_BY) REFERENCES SYS_USER (ID),
    CONSTRAINT FK_CR_DOC_REPLACES FOREIGN KEY (
        SESSION_ID, SLOT_KEY, DOCUMENT_KIND, REPLACES_DOCUMENT_ID)
        REFERENCES CONTRACT_REVIEW_DOCUMENT (SESSION_ID, SLOT_KEY, DOCUMENT_KIND, ID),
    CONSTRAINT CK_CR_DOCUMENT_KIND CHECK (DOCUMENT_KIND IN (
        'CONTRACT_BODY', 'BIDDING_DOCUMENT', 'TENDER_DOCUMENT', 'AWARD_NOTICE', 'OTHER')),
    CONSTRAINT CK_CR_DOCUMENT_SIZE CHECK (FILE_SIZE > 0),
    CONSTRAINT CK_CR_DOCUMENT_SHA CHECK (LENGTH(SHA256) = 64),
    CONSTRAINT CK_CR_DOCUMENT_VERSION CHECK (
        REQUESTED_SESSION_VERSION >= 0
        AND RESERVED_SESSION_VERSION = REQUESTED_SESSION_VERSION + 1
        AND VERSION_NO >= 0),
    CONSTRAINT CK_CR_DOCUMENT_STATUS CHECK (
        STATUS IN ('UPLOAD_PENDING', 'AVAILABLE', 'UPLOAD_FAILED')),
    CONSTRAINT CK_CR_DOCUMENT_TIMES CHECK (
        (STATUS = 'UPLOAD_PENDING' AND STORED_AT IS NULL AND FAILED_AT IS NULL)
        OR (STATUS = 'AVAILABLE' AND STORED_AT IS NOT NULL AND FAILED_AT IS NULL)
        OR (STATUS = 'UPLOAD_FAILED' AND STORED_AT IS NULL AND FAILED_AT IS NOT NULL))
);

COMMENT ON TABLE CONTRACT_REVIEW_DOCUMENT IS '合同审核文件元数据；文档行不可覆盖，保存 durable 文件接入状态与替换链。';
COMMENT ON COLUMN CONTRACT_REVIEW_DOCUMENT.ID IS '审核文档唯一标识。';
COMMENT ON COLUMN CONTRACT_REVIEW_DOCUMENT.SESSION_ID IS '文档所属合同审核会话标识。';
COMMENT ON COLUMN CONTRACT_REVIEW_DOCUMENT.DOCUMENT_KIND IS '材料类型：合同正文、招投标材料、中标通知或其他附件。';
COMMENT ON COLUMN CONTRACT_REVIEW_DOCUMENT.SLOT_KEY IS '服务端生成的材料 Slot 标识；客户端不可指定。';
COMMENT ON COLUMN CONTRACT_REVIEW_DOCUMENT.ORIGINAL_FILE_NAME IS '去除客户端路径并校验后的原始文件名，仅作元数据。';
COMMENT ON COLUMN CONTRACT_REVIEW_DOCUMENT.FILE_EXTENSION IS '经校验的规范文件扩展名。';
COMMENT ON COLUMN CONTRACT_REVIEW_DOCUMENT.CONTENT_TYPE IS '与扩展名及 magic 一致的规范 MIME。';
COMMENT ON COLUMN CONTRACT_REVIEW_DOCUMENT.FILE_SIZE IS '流式接收计算得到的文件字节长度。';
COMMENT ON COLUMN CONTRACT_REVIEW_DOCUMENT.SHA256 IS '流式计算的小写十六进制 SHA-256。';
COMMENT ON COLUMN CONTRACT_REVIEW_DOCUMENT.STORAGE_KEY IS '服务端生成的 opaque 稳定对象键，不包含真实目录。';
COMMENT ON COLUMN CONTRACT_REVIEW_DOCUMENT.STATUS IS '文件接入状态；UPLOAD_PENDING 不表示 OCR 或 AI 处理。';
COMMENT ON COLUMN CONTRACT_REVIEW_DOCUMENT.REPLACES_DOCUMENT_ID IS '同一会话、Slot、材料类型内被替换的历史文档。';
COMMENT ON COLUMN CONTRACT_REVIEW_DOCUMENT.REQUESTED_SESSION_VERSION IS '客户端上传请求携带的会话版本 N。';
COMMENT ON COLUMN CONTRACT_REVIEW_DOCUMENT.RESERVED_SESSION_VERSION IS 'START 事务预留后的会话版本 N+1。';
COMMENT ON COLUMN CONTRACT_REVIEW_DOCUMENT.CREATED_BY IS '上传材料的系统用户标识。';
COMMENT ON COLUMN CONTRACT_REVIEW_DOCUMENT.CREATED_AT IS 'UPLOAD_PENDING durable 创建时间。';
COMMENT ON COLUMN CONTRACT_REVIEW_DOCUMENT.UPDATED_AT IS '文件接入状态最近更新时间；用于 recovery 候选判断。';
COMMENT ON COLUMN CONTRACT_REVIEW_DOCUMENT.STORED_AT IS '文件 metadata 完成并进入 AVAILABLE 的时间。';
COMMENT ON COLUMN CONTRACT_REVIEW_DOCUMENT.FAILED_AT IS '文件接入失败收口时间。';
COMMENT ON COLUMN CONTRACT_REVIEW_DOCUMENT.VERSION_NO IS '文件状态 CAS 版本号。';

CREATE INDEX IDX_CR_DOCUMENT_SESSION_CREATED
    ON CONTRACT_REVIEW_DOCUMENT (SESSION_ID, CREATED_AT);
CREATE INDEX IDX_CR_DOCUMENT_SESSION_SHA
    ON CONTRACT_REVIEW_DOCUMENT (SESSION_ID, SHA256);
CREATE INDEX IDX_CR_DOCUMENT_PENDING
    ON CONTRACT_REVIEW_DOCUMENT (SESSION_ID, STATUS, UPDATED_AT);

CREATE TABLE CONTRACT_REVIEW_MATERIAL_BINDING (
    ID VARCHAR(36) NOT NULL,
    SESSION_ID VARCHAR(36) NOT NULL,
    SLOT_KEY VARCHAR(128) NOT NULL,
    DOCUMENT_KIND VARCHAR(32) NOT NULL,
    BOUND_DOCUMENT_ID VARCHAR(36) NOT NULL,
    ACTIVE_FLAG INTEGER NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP NOT NULL,
    VERSION_NO BIGINT NOT NULL,
    CONSTRAINT PK_CR_BINDING PRIMARY KEY (ID),
    CONSTRAINT UK_CR_BINDING_SLOT UNIQUE (SESSION_ID, SLOT_KEY),
    CONSTRAINT FK_CR_BINDING_SESSION FOREIGN KEY (SESSION_ID)
        REFERENCES CONTRACT_REVIEW_SESSION (ID),
    CONSTRAINT FK_CR_BINDING_DOCUMENT FOREIGN KEY (
        SESSION_ID, SLOT_KEY, DOCUMENT_KIND, BOUND_DOCUMENT_ID)
        REFERENCES CONTRACT_REVIEW_DOCUMENT (SESSION_ID, SLOT_KEY, DOCUMENT_KIND, ID),
    CONSTRAINT CK_CR_BINDING_KIND CHECK (DOCUMENT_KIND IN (
        'CONTRACT_BODY', 'BIDDING_DOCUMENT', 'TENDER_DOCUMENT', 'AWARD_NOTICE', 'OTHER')),
    CONSTRAINT CK_CR_BINDING_ACTIVE CHECK (ACTIVE_FLAG IN (0, 1)),
    CONSTRAINT CK_CR_BINDING_VERSION CHECK (VERSION_NO >= 0)
);

COMMENT ON TABLE CONTRACT_REVIEW_MATERIAL_BINDING IS '合同审核会话材料 Slot 当前绑定；替换和移除不删除历史 Document。';
COMMENT ON COLUMN CONTRACT_REVIEW_MATERIAL_BINDING.ID IS '材料绑定唯一标识。';
COMMENT ON COLUMN CONTRACT_REVIEW_MATERIAL_BINDING.SESSION_ID IS '绑定所属合同审核会话标识。';
COMMENT ON COLUMN CONTRACT_REVIEW_MATERIAL_BINDING.SLOT_KEY IS '会话范围内唯一的服务端材料 Slot。';
COMMENT ON COLUMN CONTRACT_REVIEW_MATERIAL_BINDING.DOCUMENT_KIND IS 'Slot 对应的材料类型。';
COMMENT ON COLUMN CONTRACT_REVIEW_MATERIAL_BINDING.BOUND_DOCUMENT_ID IS '当前或最近一次绑定的同范围 AVAILABLE 文档标识。';
COMMENT ON COLUMN CONTRACT_REVIEW_MATERIAL_BINDING.ACTIVE_FLAG IS '1 表示当前材料，0 表示已逻辑移除。';
COMMENT ON COLUMN CONTRACT_REVIEW_MATERIAL_BINDING.CREATED_AT IS '材料 Slot 首次创建时间。';
COMMENT ON COLUMN CONTRACT_REVIEW_MATERIAL_BINDING.UPDATED_AT IS '材料绑定替换、恢复或移除时间。';
COMMENT ON COLUMN CONTRACT_REVIEW_MATERIAL_BINDING.VERSION_NO IS '绑定 CAS 版本号。';

CREATE INDEX IDX_CR_BINDING_CURRENT
    ON CONTRACT_REVIEW_MATERIAL_BINDING (SESSION_ID, ACTIVE_FLAG, DOCUMENT_KIND);

