-- V005：为 V004 的 CONTRACT_REVIEW_SESSION 增加审计友好的 lifecycle tombstone。
-- UI 的“删除”不会物理删除 Session、Document、MaterialBinding、storage object 或审计记录。

ALTER TABLE CONTRACT_REVIEW_SESSION ADD DELETED_AT TIMESTAMP NULL;
ALTER TABLE CONTRACT_REVIEW_SESSION ADD DELETED_BY VARCHAR(36) NULL;

ALTER TABLE CONTRACT_REVIEW_SESSION ADD CONSTRAINT FK_CR_SESSION_DELETED_BY
    FOREIGN KEY (DELETED_BY) REFERENCES SYS_USER (ID);

ALTER TABLE CONTRACT_REVIEW_SESSION ADD CONSTRAINT CK_CR_SESSION_DELETED_PAIR CHECK (
    (DELETED_AT IS NULL AND DELETED_BY IS NULL)
    OR (DELETED_AT IS NOT NULL AND DELETED_BY IS NOT NULL));

COMMENT ON COLUMN CONTRACT_REVIEW_SESSION.DELETED_AT IS
    '合同审核会话 soft-delete 时间；为空表示仍在正常业务列表。';
COMMENT ON COLUMN CONTRACT_REVIEW_SESSION.DELETED_BY IS
    '执行合同审核会话 soft delete 的系统用户标识。';

CREATE INDEX IDX_CR_SESSION_ACTIVE_READY
    ON CONTRACT_REVIEW_SESSION (DELETED_AT, STATUS, CREATED_AT, ID);
