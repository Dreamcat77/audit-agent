-- F01 manual exception confirmation state and audit log.
-- Apply after V012__f01_validation_risk_fields.sql.

ALTER TABLE BUDGET_REVIEW_TASK ADD REVIEW_CURSOR INT DEFAULT 0;
ALTER TABLE BUDGET_REVIEW_TASK ADD PENDING_ROW_NUMBER INT;
ALTER TABLE BUDGET_REVIEW_TASK ADD PENDING_STEP VARCHAR(50);
ALTER TABLE BUDGET_REVIEW_TASK ADD PENDING_REASON VARCHAR(500);

CREATE TABLE BUDGET_VALIDATION_CONFIRM_LOG (
    ID BIGINT IDENTITY(1,1) PRIMARY KEY,
    BATCH_ID VARCHAR(50) NOT NULL,
    ROW_NUMBER INT NOT NULL,
    DEPARTMENT_CODE VARCHAR(50),
    DEPARTMENT_NAME VARCHAR(100),
    CONFIRMER_USER_ID VARCHAR(50) NOT NULL,
    CONFIRMER_NAME VARCHAR(50) NOT NULL,
    CONFIRM_TIME TIMESTAMP NOT NULL,
    CONFIRM_STEP VARCHAR(50) NOT NULL,
    ABNORMAL_REASON VARCHAR(500),
    REMARK VARCHAR(500),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IDX_CONFIRM_LOG_BATCH
    ON BUDGET_VALIDATION_CONFIRM_LOG (BATCH_ID);
CREATE INDEX IDX_CONFIRM_LOG_USER
    ON BUDGET_VALIDATION_CONFIRM_LOG (CONFIRMER_USER_ID);
CREATE INDEX IDX_CONFIRM_LOG_TIME
    ON BUDGET_VALIDATION_CONFIRM_LOG (CONFIRM_TIME);
