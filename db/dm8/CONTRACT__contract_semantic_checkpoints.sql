-- Controlled additive candidate only: NOT APPLIED. Requires catalog/backup approval before execution.
-- Only two new execution tables; existing review tables and business output tables are unchanged.
CREATE TABLE CONTRACT_SEMANTIC_PLAN (
    PLAN_ID VARCHAR(36) NOT NULL,
    RUN_ID VARCHAR(36) NOT NULL,
    STEP_ID VARCHAR(36) NOT NULL,
    ORIGINAL_ATTEMPT_ID VARCHAR(36) NOT NULL,
    CURRENT_ATTEMPT_ID VARCHAR(36) NOT NULL,
    INPUT_FINGERPRINT VARCHAR(64) NOT NULL,
    POLICY_FINGERPRINT VARCHAR(64) NOT NULL,
    PLAN_JSON CLOB NOT NULL,
    DEADLINE_AT TIMESTAMP NOT NULL,
    TIME_LIMIT_MS BIGINT NOT NULL,
    CALL_LIMIT INTEGER NOT NULL,
    REPAIR_LIMIT INTEGER NOT NULL,
    OWNER VARCHAR(128) NOT NULL,
    FENCE BIGINT NOT NULL,
    LEASE_UNTIL TIMESTAMP NOT NULL,
    STATUS VARCHAR(16) NOT NULL,
    USED_CALLS INTEGER DEFAULT 0 NOT NULL,
    RESERVED_CALLS INTEGER DEFAULT 0 NOT NULL,
    USED_REPAIRS INTEGER DEFAULT 0 NOT NULL,
    RESERVED_REPAIRS INTEGER DEFAULT 0 NOT NULL,
    USED_MS BIGINT DEFAULT 0 NOT NULL,
    RESERVED_MS BIGINT DEFAULT 0 NOT NULL,
    FINAL_RESULT_SHA256 VARCHAR(64),
    VERSION_NO BIGINT DEFAULT 0 NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT PK_CONTRACT_SEMANTIC_PLAN PRIMARY KEY (PLAN_ID),
    CONSTRAINT UK_SEMANTIC_PLAN_STEP UNIQUE (STEP_ID),
    CONSTRAINT FK_SEM_PLAN_RUN FOREIGN KEY (RUN_ID) REFERENCES CONTRACT_REVIEW_RUN(RUN_ID),
    CONSTRAINT FK_SEM_PLAN_STEP FOREIGN KEY (STEP_ID) REFERENCES CONTRACT_REVIEW_STEP(STEP_ID),
    CONSTRAINT FK_SEM_PLAN_ORIGINAL FOREIGN KEY (ORIGINAL_ATTEMPT_ID) REFERENCES CONTRACT_REVIEW_STEP_ATTEMPT(ATTEMPT_ID),
    CONSTRAINT FK_SEM_PLAN_CURRENT FOREIGN KEY (CURRENT_ATTEMPT_ID) REFERENCES CONTRACT_REVIEW_STEP_ATTEMPT(ATTEMPT_ID),
    CONSTRAINT CK_SEM_PLAN_STATUS CHECK (STATUS IN ('ACTIVE','COMPLETE')),
    CONSTRAINT CK_SEM_PLAN_BUDGET CHECK (TIME_LIMIT_MS > 0 AND CALL_LIMIT > 0 AND REPAIR_LIMIT >= 0
        AND REPAIR_LIMIT <= CALL_LIMIT AND USED_CALLS >= 0 AND RESERVED_CALLS >= 0
        AND USED_CALLS + RESERVED_CALLS <= CALL_LIMIT AND USED_REPAIRS >= 0 AND RESERVED_REPAIRS >= 0
        AND USED_REPAIRS + RESERVED_REPAIRS <= REPAIR_LIMIT AND USED_MS >= 0 AND RESERVED_MS >= 0
        AND FENCE > 0 AND VERSION_NO >= 0),
    CONSTRAINT CK_SEM_PLAN_FINAL CHECK (STATUS <> 'COMPLETE' OR FINAL_RESULT_SHA256 IS NOT NULL)
);
CREATE TABLE CONTRACT_SEMANTIC_UNIT (
    UNIT_EXECUTION_ID VARCHAR(36) NOT NULL,
    PLAN_ID VARCHAR(36) NOT NULL,
    LOGICAL_UNIT_KEY VARCHAR(64) NOT NULL,
    EXECUTION_NO INTEGER NOT NULL,
    UNIT_ORDINAL INTEGER NOT NULL,
    PURPOSE VARCHAR(16) NOT NULL,
    ATTEMPT_ID VARCHAR(36) NOT NULL,
    INPUT_FINGERPRINT VARCHAR(64) NOT NULL,
    DEPENDENCIES_JSON CLOB NOT NULL,
    STATUS VARCHAR(24) NOT NULL,
    OWNER VARCHAR(128) NOT NULL,
    FENCE BIGINT NOT NULL,
    LEASE_UNTIL TIMESTAMP NOT NULL,
    RESERVED_MS BIGINT DEFAULT 0 NOT NULL,
    DURATION_MS BIGINT DEFAULT 0 NOT NULL,
    RESULT_JSON CLOB,
    RESULT_SHA256 VARCHAR(64),
    SAFE_REASON VARCHAR(64),
    CALL_AUDIT_ID VARCHAR(36),
    PROVIDER VARCHAR(128),
    MODEL_NAME VARCHAR(200),
    REQUEST_FINGERPRINT VARCHAR(64),
    CALL_ORDINAL INTEGER DEFAULT 0 NOT NULL,
    VERSION_NO BIGINT DEFAULT 0 NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT PK_CONTRACT_SEMANTIC_UNIT PRIMARY KEY (UNIT_EXECUTION_ID),
    CONSTRAINT UK_SEMANTIC_UNIT_EXEC UNIQUE (PLAN_ID,LOGICAL_UNIT_KEY,EXECUTION_NO),
    CONSTRAINT UK_SEMANTIC_CALL_AUDIT UNIQUE (CALL_AUDIT_ID),
    CONSTRAINT FK_SEM_UNIT_PLAN FOREIGN KEY (PLAN_ID) REFERENCES CONTRACT_SEMANTIC_PLAN(PLAN_ID),
    CONSTRAINT FK_SEM_UNIT_ATTEMPT FOREIGN KEY (ATTEMPT_ID) REFERENCES CONTRACT_REVIEW_STEP_ATTEMPT(ATTEMPT_ID),
    CONSTRAINT CK_SEM_UNIT_PURPOSE CHECK (PURPOSE IN ('ANALYZE','REPAIR','SYNTHESIZE')),
    CONSTRAINT CK_SEM_UNIT_STATUS CHECK (STATUS IN ('PLANNED','CLAIMED','SENT','VERIFIED','REPAIR_REQUIRED','FAILED','UNKNOWN')),
    CONSTRAINT CK_SEM_UNIT_COUNTER CHECK (EXECUTION_NO > 0 AND UNIT_ORDINAL > 0 AND FENCE > 0
        AND RESERVED_MS >= 0 AND DURATION_MS >= 0 AND VERSION_NO >= 0),
    CONSTRAINT CK_SEM_UNIT_RESULT CHECK (STATUS <> 'VERIFIED' OR (RESULT_JSON IS NOT NULL AND RESULT_SHA256 IS NOT NULL)),
    CONSTRAINT CK_SEM_UNIT_CALL CHECK (STATUS IN ('PLANNED','CLAIMED') OR
        (CALL_AUDIT_ID IS NOT NULL AND PROVIDER IS NOT NULL AND MODEL_NAME IS NOT NULL
         AND REQUEST_FINGERPRINT IS NOT NULL AND CALL_ORDINAL > 0))
);
CREATE INDEX IX_SEMANTIC_UNIT_PLAN ON CONTRACT_SEMANTIC_UNIT(PLAN_ID,UNIT_ORDINAL,EXECUTION_NO);
