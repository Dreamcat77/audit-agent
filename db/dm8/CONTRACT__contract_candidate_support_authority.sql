-- MIGRATION-NAMESPACE: CONTRACT
-- MIGRATION-ID: contract-candidate-support-authority
-- DEPENDS-ON: project-file-identity-assessment,contract-candidate-authority
-- PURPOSE: bind candidate award support to exact current file parse role identity and fact authority
-- EXECUTION: CONTROLLED_MANUAL
-- IDEMPOTENCY: NOT_ASSUMED

ALTER TABLE CONTRACT_CANDIDATE ADD SUPPORT_AUTHORITY_VERSION_NO BIGINT;
ALTER TABLE CONTRACT_CANDIDATE ADD SUPPORT_AUTHORITY_FINGERPRINT VARCHAR(64);

ALTER TABLE CONTRACT_CANDIDATE ADD
    CONSTRAINT UK_CONTRACT_CANDIDATE_SUPPORT_COHORT
    UNIQUE (PROJECT_ID, ID, SUPPORT_AUTHORITY_VERSION_NO);
ALTER TABLE CONTRACT_CANDIDATE ADD
    CONSTRAINT CK_CONTRACT_CANDIDATE_SUPPORT_AUTHORITY_TUPLE CHECK (
        (SUPPORT_AUTHORITY_VERSION_NO IS NULL AND SUPPORT_AUTHORITY_FINGERPRINT IS NULL)
        OR (SUPPORT_AUTHORITY_VERSION_NO IS NOT NULL AND SUPPORT_AUTHORITY_FINGERPRINT IS NOT NULL));
ALTER TABLE CONTRACT_CANDIDATE ADD
    CONSTRAINT CK_CONTRACT_CANDIDATE_SUPPORT_AUTHORITY_VERSION CHECK
        (SUPPORT_AUTHORITY_VERSION_NO IS NULL OR SUPPORT_AUTHORITY_VERSION_NO > 0);
ALTER TABLE CONTRACT_CANDIDATE ADD
    CONSTRAINT CK_CONTRACT_CANDIDATE_SUPPORT_AUTHORITY_FINGERPRINT CHECK
        (SUPPORT_AUTHORITY_FINGERPRINT IS NULL OR
            (LENGTH(SUPPORT_AUTHORITY_FINGERPRINT) = 64
                AND SUPPORT_AUTHORITY_FINGERPRINT = LOWER(SUPPORT_AUTHORITY_FINGERPRINT)
                AND REGEXP_LIKE(SUPPORT_AUTHORITY_FINGERPRINT, '^[0-9a-f]{64}$')));

ALTER TABLE PROJECT_FILE_ROLE_DECISION ADD
    CONSTRAINT UK_PROJECT_FILE_ROLE_DECISION_SUPPORT_AUTHORITY_BINDING
    UNIQUE (DECISION_ID, PROJECT_ID, FILE_ID, FILE_SHA256, PARSE_RESULT_ID, PARSE_VERSION, SELECTED_ROLE);

ALTER TABLE PROJECT_FILE_IDENTITY_DECISION ADD
    CONSTRAINT UK_PROJECT_FILE_IDENTITY_DECISION_SUPPORT_AUTHORITY_BINDING
    UNIQUE (DECISION_ID, PROJECT_ID, PROJECT_VERSION_NO, FILE_ID, FILE_SHA256, PARSE_RESULT_ID, PARSE_VERSION, RESOLUTION);

CREATE TABLE CONTRACT_CANDIDATE_SUPPORT_AUTHORITY (
    SUPPORT_AUTHORITY_ID VARCHAR(36) NOT NULL,
    PROJECT_ID VARCHAR(36) NOT NULL,
    CANDIDATE_ID VARCHAR(36) NOT NULL,
    AUTHORITY_VERSION_NO BIGINT NOT NULL,
    SOURCE_FILE_ID VARCHAR(36) NOT NULL,
    FILE_SHA256 VARCHAR(64) NOT NULL,
    PARSE_RESULT_ID VARCHAR(36) NOT NULL,
    PARSE_VERSION INTEGER NOT NULL,
    PROJECT_VERSION_NO BIGINT NOT NULL,
    EFFECTIVE_ROLE VARCHAR(32) NOT NULL,
    ROLE_DECISION_ID VARCHAR(36) NOT NULL,
    IDENTITY_RESOLUTION VARCHAR(40) NOT NULL,
    IDENTITY_DECISION_ID VARCHAR(36) NOT NULL,
    SOURCE_FACT_FINGERPRINT VARCHAR(64) NOT NULL,
    CREATED_BY VARCHAR(36) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT PK_CONTRACT_CANDIDATE_SUPPORT_AUTHORITY PRIMARY KEY (SUPPORT_AUTHORITY_ID),
    CONSTRAINT UK_CONTRACT_CANDIDATE_SUPPORT_AUTHORITY_FILE UNIQUE
        (PROJECT_ID, CANDIDATE_ID, SOURCE_FILE_ID),
    CONSTRAINT FK_CONTRACT_CANDIDATE_SUPPORT_AUTHORITY_CANDIDATE FOREIGN KEY
        (PROJECT_ID, CANDIDATE_ID, AUTHORITY_VERSION_NO)
        REFERENCES CONTRACT_CANDIDATE (PROJECT_ID, ID, SUPPORT_AUTHORITY_VERSION_NO),
    CONSTRAINT FK_CONTRACT_CANDIDATE_SUPPORT_AUTHORITY_FILE FOREIGN KEY (PROJECT_ID, SOURCE_FILE_ID)
        REFERENCES PROJECT_FILE (PROJECT_ID, ID),
    CONSTRAINT FK_CONTRACT_CANDIDATE_SUPPORT_AUTHORITY_PARSE FOREIGN KEY
        (PARSE_RESULT_ID, PROJECT_ID, SOURCE_FILE_ID, FILE_SHA256, PARSE_VERSION)
        REFERENCES PROJECT_FILE_PARSE_RESULT (PARSE_RESULT_ID, PROJECT_ID, FILE_ID, FILE_SHA256, PARSE_VERSION),
    CONSTRAINT FK_CONTRACT_CANDIDATE_SUPPORT_AUTHORITY_ROLE FOREIGN KEY
        (ROLE_DECISION_ID, PROJECT_ID, SOURCE_FILE_ID, FILE_SHA256, PARSE_RESULT_ID, PARSE_VERSION, EFFECTIVE_ROLE)
        REFERENCES PROJECT_FILE_ROLE_DECISION
        (DECISION_ID, PROJECT_ID, FILE_ID, FILE_SHA256, PARSE_RESULT_ID, PARSE_VERSION, SELECTED_ROLE),
    CONSTRAINT FK_CONTRACT_CANDIDATE_SUPPORT_AUTHORITY_IDENTITY FOREIGN KEY
        (IDENTITY_DECISION_ID, PROJECT_ID, PROJECT_VERSION_NO, SOURCE_FILE_ID, FILE_SHA256, PARSE_RESULT_ID,
            PARSE_VERSION, IDENTITY_RESOLUTION)
        REFERENCES PROJECT_FILE_IDENTITY_DECISION
        (DECISION_ID, PROJECT_ID, PROJECT_VERSION_NO, FILE_ID, FILE_SHA256, PARSE_RESULT_ID, PARSE_VERSION, RESOLUTION),
    CONSTRAINT FK_CONTRACT_CANDIDATE_SUPPORT_AUTHORITY_CREATED_BY FOREIGN KEY (CREATED_BY)
        REFERENCES SYS_USER (ID),
    CONSTRAINT CK_CONTRACT_CANDIDATE_SUPPORT_AUTHORITY_ROLE CHECK (EFFECTIVE_ROLE = 'AWARD_NOTICE'),
    CONSTRAINT CK_CONTRACT_CANDIDATE_SUPPORT_AUTHORITY_IDENTITY CHECK
        (IDENTITY_RESOLUTION = 'CONFIRM_SAME_PROJECT'),
    CONSTRAINT CK_CONTRACT_CANDIDATE_SUPPORT_AUTHORITY_VERSIONS CHECK
        (PARSE_VERSION > 0 AND AUTHORITY_VERSION_NO > 0 AND PROJECT_VERSION_NO > 0),
    CONSTRAINT CK_CONTRACT_CANDIDATE_SUPPORT_AUTHORITY_HASHES CHECK
        (LENGTH(FILE_SHA256) = 64 AND FILE_SHA256 = LOWER(FILE_SHA256)
            AND REGEXP_LIKE(FILE_SHA256, '^[0-9a-f]{64}$')
            AND LENGTH(SOURCE_FACT_FINGERPRINT) = 64
            AND SOURCE_FACT_FINGERPRINT = LOWER(SOURCE_FACT_FINGERPRINT)
            AND REGEXP_LIKE(SOURCE_FACT_FINGERPRINT, '^[0-9a-f]{64}$'))
);

CREATE INDEX IDX_CONTRACT_CANDIDATE_SUPPORT_AUTHORITY_CURRENT
    ON CONTRACT_CANDIDATE_SUPPORT_AUTHORITY (PROJECT_ID, CANDIDATE_ID, AUTHORITY_VERSION_NO, SOURCE_FILE_ID);
CREATE INDEX IDX_CONTRACT_CANDIDATE_SUPPORT_AUTHORITY_SOURCE
    ON CONTRACT_CANDIDATE_SUPPORT_AUTHORITY (PROJECT_ID, SOURCE_FILE_ID, CANDIDATE_ID);
CREATE INDEX IDX_CONTRACT_CANDIDATE_SUPPORT_AUTHORITY_ROLE_DECISION
    ON CONTRACT_CANDIDATE_SUPPORT_AUTHORITY
    (ROLE_DECISION_ID, PROJECT_ID, SOURCE_FILE_ID, PARSE_RESULT_ID, PARSE_VERSION);
CREATE INDEX IDX_CONTRACT_CANDIDATE_SUPPORT_AUTHORITY_IDENTITY_DECISION
    ON CONTRACT_CANDIDATE_SUPPORT_AUTHORITY
    (IDENTITY_DECISION_ID, PROJECT_ID, SOURCE_FILE_ID, PARSE_RESULT_ID, PARSE_VERSION);
CREATE INDEX IDX_CONTRACT_CANDIDATE_SUPPORT_AUTHORITY_PARSE_EVIDENCE
    ON CONTRACT_CANDIDATE_SUPPORT_AUTHORITY (PROJECT_ID, SOURCE_FILE_ID, PARSE_RESULT_ID);
