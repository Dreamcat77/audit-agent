-- F03 供应商黑名单报警表（兼容历史手工初始化场景）。
-- 正式环境优先按 db/dm8/V018__f03_blacklist.sql 受控执行。

CREATE TABLE IF NOT EXISTS BLACKLIST_SUPPLIER (
    ID              VARCHAR(36)  NOT NULL PRIMARY KEY,
    SUPPLIER_NAME   VARCHAR(200) NOT NULL,
    SUPPLIER_CODE   VARCHAR(50),
    BLACKLIST_TYPE  VARCHAR(50)  NOT NULL,
    REASON          VARCHAR(500) NOT NULL,
    SOURCE          VARCHAR(50)  NOT NULL,
    EFFECTIVE_DATE  DATE         NOT NULL,
    EXPIRY_DATE     DATE,
    IS_ACTIVE       BOOLEAN      NOT NULL DEFAULT TRUE,
    CREATED_BY      VARCHAR(50)  NOT NULL,
    CREATED_TIME    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_TIME    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS BLACKLIST_ALERT (
    ID               VARCHAR(36)  NOT NULL PRIMARY KEY,
    BATCH_ID         VARCHAR(50)  NOT NULL,
    ROW_NUMBER       INT,
    PROCUREMENT_ID   VARCHAR(64),
    SUPPLIER_NAME    VARCHAR(200) NOT NULL,
    SUPPLIER_CODE    VARCHAR(50),
    BLACKLIST_ID     VARCHAR(36)  NOT NULL,
    MATCHED_NAME     VARCHAR(200) NOT NULL,
    BLACKLIST_TYPE   VARCHAR(50)  NOT NULL,
    BLACKLIST_REASON VARCHAR(500) NOT NULL,
    MATCH_TYPE       VARCHAR(16)  NOT NULL,
    MATCH_SCORE      DECIMAL(5,2) NOT NULL,
    ALERT_LEVEL      VARCHAR(20)  NOT NULL,
    ALERT_STATUS     VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    RESOLVED_BY      VARCHAR(50),
    RESOLVED_TIME    TIMESTAMP,
    REMARK           VARCHAR(500),
    CREATED_TIME     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS UK_BLACKLIST_ALERT_BATCH_SUPPLIER
    ON BLACKLIST_ALERT (BATCH_ID, SUPPLIER_NAME);

CREATE TABLE IF NOT EXISTS BLACKLIST_RULE (
    ID              VARCHAR(36)  NOT NULL PRIMARY KEY,
    RULE_NAME       VARCHAR(100) NOT NULL,
    RULE_TYPE       VARCHAR(50)  NOT NULL,
    BLACKLIST_TYPES VARCHAR(200),
    ALERT_LEVEL     VARCHAR(20)  NOT NULL,
    AUTO_RESOLVE    BOOLEAN      NOT NULL DEFAULT FALSE,
    IS_ACTIVE       BOOLEAN      NOT NULL DEFAULT TRUE,
    CREATED_TIME    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_TIME    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS BLACKLIST_SUPPLIER_OPERATION_LOG (
    ID                  VARCHAR(36)   NOT NULL PRIMARY KEY,
    BLACKLIST_ID        VARCHAR(36)   NOT NULL,
    OPERATION_TYPE      VARCHAR(32)   NOT NULL,
    OPERATOR_USER_ID    VARCHAR(64)   NOT NULL,
    OPERATOR_NAME       VARCHAR(100)  NOT NULL,
    OPERATION_REASON    VARCHAR(1000) NOT NULL,
    OPERATED_TIME       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CREATED_TIME        TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS IDX_BLACKLIST_OPERATION_LOG_ENTRY
    ON BLACKLIST_SUPPLIER_OPERATION_LOG (BLACKLIST_ID, OPERATED_TIME);
