export function enumLabel(value: string | null | undefined, fallback = "-"): string {
  if (!value) return fallback;
  if (labels[value]) return labels[value];
  return /^[A-Z][A-Z0-9_]*$/.test(value) ? "未知状态" : value;
}

export function approvalStatusLabel(value: string | null | undefined): string {
  return value === "IN_PROGRESS" ? "审批中" : enumLabel(value);
}

export function reviewStepStatusLabel(value: string | null | undefined): string {
  return value === "IN_PROGRESS" ? "进行中" : enumLabel(value);
}

export function riskLevelLabel(value: string | null | undefined): string {
  return enumLabel(value);
}
