"""Classify normalized, read-only DM8 catalog evidence; never connect or execute DDL."""
from copy import deepcopy

_COLUMNS = {
    "BUNDLE_ID": "VARCHAR(36) NOT NULL", "PROJECT_ID": "VARCHAR(36) NOT NULL",
    "CONTRACT_ID": "VARCHAR(36) NOT NULL", "RUN_ID": "VARCHAR(36) NOT NULL",
    "STEP_ID": "VARCHAR(36) NULL", "ATTEMPT_ID": "VARCHAR(36) NULL",
    "CONTENT_LEVEL": "VARCHAR(48) NOT NULL", "STATUS": "VARCHAR(16) NOT NULL",
    "MANIFEST_JSON": "CLOB NOT NULL", "STORAGE_KEY": "VARCHAR(64) NOT NULL",
    "ARTIFACT_SHA256": "VARCHAR(64) NOT NULL", "ARTIFACT_SIZE": "BIGINT NOT NULL",
    "GENERATED_BY": "VARCHAR(36) NOT NULL", "REQUESTED_AT": "TIMESTAMP NOT NULL",
    "REQUEST_ID": "VARCHAR(128) NOT NULL", "TRACE_ID": "VARCHAR(128) NOT NULL",
    "VERSION_NO": "BIGINT DEFAULT 0 NOT NULL",
}
_CONSTRAINTS = {
    "PK_SDB": "PRIMARY KEY (BUNDLE_ID)",
    "UK_SDB_STORAGE": "UNIQUE (STORAGE_KEY)",
    "FK_SDB_RUN": "FOREIGN KEY (RUN_ID,PROJECT_ID) REFERENCES CONTRACT_REVIEW_RUN (RUN_ID,PROJECT_ID)",
    "FK_SDB_CONTRACT": "FOREIGN KEY (PROJECT_ID,CONTRACT_ID) REFERENCES PROJECT_CONTRACT (PROJECT_ID,CONTRACT_ID)",
    "FK_SDB_STEP": "FOREIGN KEY (RUN_ID,STEP_ID) REFERENCES CONTRACT_REVIEW_STEP (RUN_ID,STEP_ID)",
    "FK_SDB_ATTEMPT": "FOREIGN KEY (RUN_ID,STEP_ID,ATTEMPT_ID) REFERENCES CONTRACT_REVIEW_STEP_ATTEMPT (RUN_ID,STEP_ID,ATTEMPT_ID)",
    "FK_SDB_ACTOR": "FOREIGN KEY (GENERATED_BY) REFERENCES SYS_USER (ID)",
    "CK_SDB_LEVEL": "CHECK (CONTENT_LEVEL='METADATA_ONLY')",
    "CK_SDB_STATUS": "CHECK (STATUS IN ('GENERATING','AVAILABLE','UNKNOWN'))",
    "CK_SDB_SCOPE": "CHECK (ATTEMPT_ID IS NULL OR STEP_ID IS NOT NULL)",
    "CK_SDB_BOUNDS": "CHECK (ARTIFACT_SIZE>0 AND ARTIFACT_SIZE<=1048576 AND VERSION_NO>=0)",
    "CK_SDB_HASH": "CHECK (LENGTH(STORAGE_KEY)=64 AND LENGTH(ARTIFACT_SHA256)=64)",
}


def expected_catalog():
    return deepcopy({"SANITIZED_DEBUG_BUNDLE": {
        "columns": _COLUMNS, "constraints": _CONSTRAINTS,
        "indexes": {"IDX_SDB_RUN": "(RUN_ID,REQUESTED_AT,BUNDLE_ID)"},
    }})


def classify(observed):
    if (not isinstance(observed, dict) or observed.get("readable") is not True
            or observed.get("dependenciesMatching") is not True or not isinstance(observed.get("tables"), dict)):
        return "UNKNOWN"
    tables = observed["tables"]
    if "SANITIZED_DEBUG_BUNDLE" not in tables:
        return "NOT_APPLIED"
    if tables["SANITIZED_DEBUG_BUNDLE"] == expected_catalog()["SANITIZED_DEBUG_BUNDLE"]:
        return "ALREADY_MATCHING"
    return "PARTIAL-SCHEMA_DRIFT"
